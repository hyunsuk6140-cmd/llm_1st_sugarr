//       끄려면 Ctrl + C
// ============================================================
//
// 04단원에서 이미 미들웨어를 썼습니다. 이름만 몰랐을 뿐입니다.
//
//   app.use(express.json())        ← 미들웨어
//   app.use((req, res) => 404)     ← 미들웨어
//   app.use((err, ...) => 에러)    ← 미들웨어
//
// 이번 단원에서 이걸 직접 만듭니다.
// 로그 남기기, 로그인 확인, 권한 확인, 요청 시간 재기 —
// 실무 서버 코드의 절반이 미들웨어입니다.

// ── 섹션 1: 미들웨어는 '거쳐 가는 함수' 입니다 ──

// 요청이 라우트에 도착하기 전에 들르는 곳이라고 생각하세요.
//
//   요청  →  미들웨어1  →  미들웨어2  →  라우트  →  응답
//
// 공항 검색대와 비슷합니다.
// 비행기(라우트)를 타기 전에 표 확인, 짐 검사, 보안 검색을 차례로 거칩니다.
// 어느 한 곳에서 걸리면 비행기까지 못 갑니다.
//
// 미들웨어 함수는 이렇게 생겼습니다.
//
//   (req, res, next) => { ... }
//    ───  ───  ────
//    요청  응답  다음으로 넘기는 함수
//
// 라우트 함수와 딱 하나 다릅니다. 세 번째 인자 next 가 있습니다.

const express = require("express");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

// ── 섹션 2: next 를 부르면 다음으로 갑니다 ──

// req 는 요청 하나가 끝날 때까지 계속 따라다니는 객체입니다.
// 여기에 값을 붙여 두면 다음 미들웨어와 라우트에서 꺼내 쓸 수 있습니다.

app.use((req, res, next) => {
  req.기록 = ["첫 번째 미들웨어"];
  next(); // ★ 이걸 불러야 다음으로 넘어갑니다
});

app.use((req, res, next) => {
  req.기록.push("두 번째 미들웨어");
  next();
});

app.get("/order", (req, res) => {
  req.기록.push("라우트");
  res.json({ 순서: req.기록 });
});

// 확인: GET /order
// 응답: 200 {"순서":["첫 번째 미들웨어","두 번째 미들웨어","라우트"]}

// 적은 순서 그대로 실행됐습니다.
//
// ★ req 에 값을 붙이는 것이 미들웨어의 핵심 쓸모입니다.
//   "이 요청을 보낸 사람이 누구인지" 를 미들웨어가 알아내서 req.user 에 붙여 두면,
//   라우트 서른 개가 전부 req.user 를 꺼내 쓸 수 있습니다.
//   같은 코드를 서른 번 안 써도 됩니다. 개념03 에서 실제로 만듭니다.
//
// ★ 이름은 마음대로 지어도 됩니다. req.기록, req.user, req.시작시각 ...
//   다만 Express 가 이미 쓰는 이름(req.body, req.query 등)은 피하세요.

// ── 섹션 3: next 를 안 부르면 거기서 멈춥니다 ──

app.use("/blocked", (req, res, next) => {
  res.status(403).json({ error: "여기서 막았습니다" });
  // next() 를 안 불렀습니다. 아래 라우트는 실행되지 않습니다.
});

app.get("/blocked", (req, res) => {
  res.json({ 도달: "여기는 절대 실행되지 않습니다" });
});

// 확인: GET /blocked
// 응답: 403 {"error":"여기서 막았습니다"}

// 라우트를 분명히 만들었는데 실행이 안 됐습니다.
// 미들웨어가 응답을 보내고 끝냈기 때문입니다.
//
// ★ 이게 '막는다' 는 뜻입니다.
//   로그인 안 한 사람을 여기서 돌려보내면, 아래 라우트는 로그인 확인을 안 해도 됩니다.
//
// ★★ 그런데 응답도 안 보내고 next 도 안 부르면?
//   요청이 영원히 멈춥니다. 브라우저가 계속 빙빙 돕니다. 에러도 안 납니다.
//   미들웨어를 만들 때 가장 많이 하는 실수입니다.
//
//   미들웨어 안의 모든 갈래는 셋 중 하나로 끝나야 합니다.
//     ① next() 를 부른다        → 다음으로 보낸다
//     ② 응답을 보낸다            → 여기서 끝낸다
//     ③ next(에러) 를 부른다     → 에러 처리기로 보낸다
//
//   if 를 썼다면 else 쪽도 확인하세요. 한쪽만 next() 를 부르는 실수가 흔합니다.

// ── 섹션 4: app.use 에 주소를 주면 그 아래만 ──

app.use("/admin", (req, res, next) => {
  req.관리자영역 = true;
  next();
});

app.get("/admin/users", (req, res) => {
  console.log(req.기록);
  res.json({ 관리자영역: req.관리자영역 === true });
});

// 확인: GET /admin/users
// 응답: 200 {"관리자영역":true}

app.get("/public/info", (req, res) => {
  res.json({ 관리자영역: req.관리자영역 === true });
});

// 확인: GET /public/info
// 응답: 200 {"관리자영역":false}

// app.use("/admin", ...) 은 "/admin 으로 시작하는 요청만" 이라는 뜻입니다.
//
//   /admin           걸립니다
//   /admin/users     걸립니다
//   /admin/x/y/z     걸립니다
//   /administrator   ★ 안 걸립니다 (조각 단위로 봅니다)
//   /public/info     안 걸립니다
//
// 주소를 안 주면 모든 요청에 걸립니다.
// 로그 남기기처럼 전부에 해야 하는 일은 주소를 안 줍니다.
// 로그인 확인처럼 일부만 해야 하는 일은 주소를 줍니다.

// ── 섹션 5: 라우트 하나에만 붙이기 ──

// app.use 말고, 라우트를 등록할 때 함수를 여러 개 넘겨도 됩니다.

function 표시남기기(req, res, next) {
  req.표시 = "이 라우트에만 붙었습니다";
  next();
}

app.get("/one-route", 표시남기기, (req, res) => {
  res.json({ 표시: req.표시 });
});

// 확인: GET /one-route
// 응답: 200 {"표시":"이 라우트에만 붙었습니다"}

app.get("/other-route", (req, res) => {
  res.json({ 표시: req.표시 ?? "안 붙었습니다" });
});

// 확인: GET /other-route
// 응답: 200 {"표시":"안 붙었습니다"}

// app.메서드(주소, 미들웨어1, 미들웨어2, ..., 최종처리)
//
// 몇 개를 넘겨도 됩니다. 앞에서부터 차례로 실행되고,
// 마지막 함수가 응답을 보냅니다.
//
// 사실 마지막 함수도 미들웨어입니다. next 를 안 쓸 뿐입니다.
// Express 에는 '미들웨어' 라는 한 종류만 있습니다.
// 라우트 함수는 "next 를 안 쓰고 응답을 보내는 미들웨어" 일 뿐입니다.

// ── 섹션 6: 배열로 묶어서 재사용하기 ──

function 확인1(req, res, next) {
  req.통과 = ["확인1"];
  next();
}

function 확인2(req, res, next) {
  req.통과.push("확인2");
  next();
}

const 검사세트 = [확인1, 확인2];

app.get("/checked", 검사세트, (req, res) => {
  res.json({ 통과: req.통과 });
});

// 확인: GET /checked
// 응답: 200 {"통과":["확인1","확인2"]}

// 자주 같이 쓰는 미들웨어들은 배열로 묶어 두면 편합니다.
//   app.get("/a", 검사세트, ...)
//   app.get("/b", 검사세트, ...)

// ── 섹션 7: express.json() 도 미들웨어였습니다 ──

app.post("/echo", (req, res) => {
  res.json({ 받은것: req.body });
});

// 확인: POST /echo {"a":1}
// 응답: 200 {"받은것":{"a":1}}

// app.use(express.json()) 이 하는 일을 이제 알 수 있습니다.
//
//   ① 본문 조각을 모은다
//   ② JSON.parse 로 객체를 만든다
//   ③ req.body 에 붙인다        ← 섹션 2에서 우리가 req.기록 을 붙인 것과 같습니다
//   ④ next() 를 부른다
//
// 04단원에서 "라우트보다 위에 써야 한다" 고 한 이유도 분명해졌습니다.
// 아래에 쓰면 라우트가 먼저 실행되어, req.body 를 붙일 기회가 없습니다.
//
// ★ express.json() 에 괄호가 붙은 이유
//   express.json 은 '미들웨어를 만들어 주는 함수' 입니다.
//   불러야 미들웨어가 나옵니다.
//
//     app.use(express.json)     ← 괄호 없음. 함수 자체를 넘김. 안 됩니다
//     app.use(express.json())   ← 불러서 나온 미들웨어를 넘김. 맞습니다
//
//   옵션을 줄 수 있어서 이렇게 만들어져 있습니다.
//     express.json({ limit: "1mb" })   본문 크기 제한

app.use((req, res) => {
  res.status(404).json({ error: "그런 주소가 없습니다" });
});

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.message}`);
  const 코드 = err.status || 500;
  res
    .status(코드)
    .json({ error: 코드 === 500 ? "서버에서 문제가 생겼습니다" : err.message });
});

app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}/order`);
});

// ============================================================
// 미들웨어를 등록하는 네 가지 방법
// ============================================================
//
//   app.use(함수)                     모든 요청
//   app.use("/admin", 함수)           /admin 으로 시작하는 요청
//   app.get("/x", 함수, 최종처리)      /x 로 오는 GET 하나
//   app.get("/x", [함수1, 함수2], ...) 여러 개를 배열로
//
// 어느 것이든 (req, res, next) 모양은 같습니다.

// ============================================================
// 직접 해 볼 것
// ============================================================
//
// ✏️ 직접 해보기 1 — 섹션 2의 두 번째 미들웨어에서 next() 를 지워 보세요.
//                    /order 로 요청하면 어떻게 되나요?
//                    브라우저 탭이 어떤 상태가 되는지 보세요.
//                    (확인했으면 반드시 되돌리세요)
//
// ✏️ 직접 해보기 2 — 섹션 2의 두 미들웨어 순서를 바꿔 보세요.
//                    무슨 에러가 나나요? 왜 그럴까요?
//                    (힌트: 두 번째 것이 먼저 오면 req.기록 이 아직 없습니다)
//
// ✏️ 직접 해보기 3 — 모든 요청에 대해 터미널에
//                    "요청 들어옴: GET /order" 를 찍는 미들웨어를 만들어 보세요.
//                    맨 위에 두어야 합니다.
//
// ✏️ 직접 해보기 4 — /admin 미들웨어를 /administrator 로 요청해 보세요.
//                    걸리나요? 왜 그럴까요?
//
// ✏️ 직접 해보기 5 — 섹션 3의 미들웨어에서 응답을 보낸 '뒤에' next() 를 불러 보세요.
//                    터미널에 어떤 에러가 나나요?
//                    (확인했으면 반드시 되돌리세요)

// ── 자주 하는 실수 ──

// [실수 1] next() 를 안 부름
//   요청이 영원히 멈춥니다. 에러도 안 나서 제일 찾기 어렵습니다.
//   브라우저 탭이 계속 도는데 터미널은 조용하면 이걸 의심하세요.

// [실수 2] if 의 한쪽에서만 next() 를 부름
//   if (조건) { next(); }
//   → 조건이 false 면 아무 일도 안 일어나고 멈춥니다.
//   else 쪽도 반드시 끝을 내세요.

// [실수 3] 응답을 보내고 next() 도 부름
//   res.json(...); next();
//   → 다음 미들웨어가 또 응답하려다 에러가 납니다.
//   → Cannot set headers after they are sent to the client
//   응답했으면 거기서 끝입니다. return 을 붙이는 습관이 좋습니다.

// [실수 4] 미들웨어를 라우트 아래에 등록
//   라우트가 먼저 걸려서 미들웨어가 실행되지 않습니다.
//   "미들웨어는 위, 라우트는 아래" 를 기억하세요.

// [실수 5] next 를 next() 로 안 부르고 next 라고만 씀
//   함수 이름만 적은 것입니다. 아무 일도 안 일어납니다. 괄호를 붙이세요.

// [실수 6] express.json 에 괄호를 안 붙임
//   app.use(express.json) → 미들웨어가 아니라 '만드는 함수' 를 등록한 것입니다.
//   이 함수는 next() 를 부르지 않아서, [실수 1]과 똑같이
//   모든 요청이 응답 없이 영영 멈춥니다. 에러도 안 나서 원인을 찾기 어렵습니다.

// ── 정리 ──

// 1. 미들웨어는 요청이 라우트에 닿기 전에 거쳐 가는 함수다. (req, res, next) 셋을 받는다.
// 2. next() 를 불러야 다음으로 간다. 안 부르면 거기서 멈추고 응답이 영영 안 나간다.
// 3. if 의 한쪽에서만 next() 를 부르면 나머지 길에서 멈춘다. 모든 갈래를 확인한다.
// 4. 응답을 보냈으면 next() 를 부르지 않는다. 두 번 보내려다 에러가 난다.
// 5. 미들웨어는 라우트보다 위에 등록한다. 아래에 두면 아예 안 거친다.
// 6. app.use("/주소", 미들웨어) 로 그 아래만 걸 수 있고, 라우트 하나에만 붙일 수도 있다.
// 7. 여러 개를 배열로 묶어 두면 그대로 재사용할 수 있다.
// 8. express.json() 도 미들웨어였다. 괄호를 붙여서 '만들어진 미들웨어' 를 넘겨야 한다.

// 실행: node 개념01_Node란_무엇인가.js
// ============================================================
//
// 지금까지 자바스크립트를 두 곳에서 실행해 봤습니다.
//
//   ① 터미널에서  node 파일.js
//   ② 브라우저에서  .html 파일을 열어서
//
// ①이 바로 Node.js 입니다. 사실 이미 쓰고 계셨습니다.
// 이번 단원에서는 그게 정확히 무엇인지, 왜 백엔드에 쓰는지를 봅니다.
//
// ── 한 줄로 말하면 ──
//
//   Node.js = 브라우저 밖에서 자바스크립트를 실행해 주는 프로그램
//
// 원래 자바스크립트는 브라우저 안에서만 돌았습니다.
// 웹페이지를 움직이라고 만든 언어였으니까요.
// 그런데 2009년에 "브라우저 없이도 돌게 하자" 며 만든 것이 Node.js 입니다.
//
// 그때부터 자바스크립트로 서버를 만들 수 있게 되었습니다.
// 프론트와 백엔드를 같은 언어로 쓸 수 있다는 것이 가장 큰 장점입니다.

// ── 섹션 1: 브라우저에는 있고 Node 에는 없는 것 ──

// 브라우저에서 늘 쓰던 것들을 여기서 찾아봅시다.

console.log(typeof window);
// 출력: undefined
// window 가 없습니다. 브라우저 창을 가리키던 그 window 입니다.

console.log(typeof document);
// 출력: undefined
// document 도 없습니다. 화면이 없으니 당연합니다.

console.log(typeof alert);
// 출력: undefined
// alert 도 없습니다. 띄울 창이 없으니까요.

console.log(typeof localStorage);
// 출력: undefined
// localStorage 도 없습니다. 브라우저가 주던 저장소였습니다.
console.log(typeof fetch);

// Node 에는 화면이 없습니다. 그래서 화면과 관련된 것이 전부 없습니다.
//
//   화면을 그리는 일   →  브라우저(프론트엔드)가 합니다
//   데이터를 다루는 일 →  Node(백엔드)가 합니다
//
// 이 구분이 이 과정 전체의 뼈대입니다.

// ✏️ 직접 해보기 1 — typeof fetch 를 찍어 보세요.
//                    (fetch 는 브라우저 것일까요, Node 것일까요?)

// ── 섹션 2: 그런데 이건 그대로 있습니다 ──

// 자바스크립트 '언어' 자체는 똑같습니다.
// 지금까지 배운 문법이 전부 그대로 동작합니다.

const menus = ["아메리카노", "라떼", "케이크"];
const prices = menus.map((menu, index) => `${menu} ${(index + 1) * 1000}원`);

console.log(prices);
// 출력: [ '아메리카노 1000원', '라떼 2000원', '케이크 3000원' ]

const total = [1000, 2000, 3000].reduce((sum, n) => sum + n, 0);
console.log(total);
// 출력: 6000

// map, reduce, 화살표 함수, 템플릿 리터럴 — 전부 그대로입니다.
// 새 언어를 배우는 게 아닙니다. 같은 언어를 다른 곳에서 쓰는 것뿐입니다.

console.log(typeof console.log);
// 출력: function
// console 은 양쪽에 다 있습니다. 다만 브라우저는 F12 창에,
// Node 는 터미널에 찍는다는 점만 다릅니다.

// ✏️ 직접 해보기 2 — 배열 [5, 3, 9] 를 filter 로 4보다 큰 것만 골라 출력해 보세요.

console.log([5, 3, 9].filter((n) => n > 4));

// ── 섹션 3: Node 에만 있는 것 — process ──

// 대신 브라우저에 없는 것이 생겼습니다. 그중 첫 번째가 process 입니다.
// "지금 돌고 있는 이 프로그램" 자신을 가리키는 객체입니다.

console.log(typeof process);
// 출력: object

// 버전 확인
console.log(process.version.startsWith("v"));
// 출력: true
// process.version 은 "v24.18.0" 처럼 생겼습니다.
// 설치한 Node 버전에 따라 다르므로 값 자체는 적어 두지 않았습니다.
// 직접 찍어 보세요:  console.log(process.version);

// 어떤 운영체제에서 도는지
console.log(typeof process.platform);
// 출력: string
// 윈도우는 "win32", 맥은 "darwin", 리눅스는 "linux" 가 나옵니다.
// 나중에 EC2(리눅스)에 올리면 "linux" 가 됩니다.

// 지금 이 파일이 어느 폴더에서 실행됐는지
console.log(typeof process.cwd());
// 출력: string
// cwd = current working directory. 터미널이 지금 있는 폴더입니다.

// ✏️ 직접 해보기 3 — process.version, process.platform, process.cwd() 를
//                    각각 찍어서 내 컴퓨터의 값을 확인해 보세요.

// ── 섹션 4: 실행할 때 값 넘겨 주기 ──

// 터미널에서 파일 이름 뒤에 값을 붙이면 프로그램에 전달됩니다.
//
//     node 개념01_Node란_무엇인가.js 안녕 반가워
//
// 그 값들은 process.argv 라는 배열에 담깁니다.

console.log(Array.isArray(process.argv));
// 출력: true

console.log(process.argv.length >= 2);
// 출력: true
// 최소 2개는 항상 들어 있습니다.
//   [0] node 프로그램의 위치
//   [1] 지금 실행 중인 파일의 위치
//   [2] 부터가 우리가 붙인 값입니다

// 우리가 붙인 값만 꺼내려면 앞의 두 개를 잘라냅니다.
const args = process.argv.slice(2);
console.log(args);
// 출력: []
// 아무것도 안 붙이고 실행했으니 빈 배열입니다.

// 위 명령처럼 값을 붙여 실행하면 [ '안녕', '반가워' ] 가 나옵니다.
// 직접 해 보세요. 서버를 만들 때 포트 번호를 이렇게 넘기기도 합니다.

// ✏️ 직접 해보기 4 — 터미널에서 아래처럼 실행하고 결과를 확인해 보세요.
//                    node 개념01_Node란_무엇인가.js 커피 3

// ── 섹션 5: 왜 백엔드에 Node 를 쓰나 ──

// 서버를 만드는 언어는 여러 가지가 있습니다. (파이썬, 자바, PHP, Go ...)
// 그중 Node 를 쓰는 이유는 이렇습니다.
//
//   1) 프론트와 같은 언어입니다
//      화면도 자바스크립트, 서버도 자바스크립트.
//      언어를 하나만 알아도 양쪽을 다 만들 수 있습니다.
//
//   2) 기다리는 일에 강합니다
//      서버가 하는 일의 대부분은 '기다리기' 입니다.
//      데이터베이스 응답을 기다리고, 파일을 읽길 기다리고, AI 응답을 기다립니다.
//      Node 는 기다리는 동안 다른 요청을 처리합니다. (JS자료 12단원의 비동기입니다)
//
//   3) 패키지가 많습니다
//      npm 에 남이 만들어 둔 것이 300만 개가 넘습니다.
//      파일 업로드, 로그인, 이미지 처리 — 대부분 갖다 쓰면 됩니다.
//
// 이 과정에서 만들 AI Assistant 도 "요청을 받아 → AI 응답을 기다렸다가 → 돌려주는"
// 일이 대부분입니다. Node 가 잘하는 일입니다.

// ── 섹션 6: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.

// [실수 1] 브라우저 코드를 그대로 가져옴 → ReferenceError
// document.querySelector("#app");
// 실수: ReferenceError: document is not defined
//       Node 에는 화면이 없습니다. 인터넷 예제를 복사할 때 자주 납니다.
//       "이 코드가 브라우저 것인지 서버 것인지" 를 항상 확인하세요.

// [실수 2] alert 로 확인하려 함 → ReferenceError
// alert("여기까지 왔습니다");
// 실수: 서버에서 값을 확인할 때는 console.log 만 씁니다.

// [실수 3] 파일 이름을 안 적고 실행
//   터미널에 그냥 node 라고만 치면 REPL 이라는 대화 모드로 들어갑니다.
//   > 표시가 뜨고 한 줄씩 실행됩니다. 나가려면 .exit 을 치거나 Ctrl+C 를 두 번 누릅니다.
//   당황하지 마세요. 파일을 실행하려면 node 파일이름.js 입니다.

// [실수 4] 확장자를 빼먹음
//   node 개념01_Node란_무엇인가        ← .js 없이도 되긴 합니다
//   node 개념01_Node란_무엇인가.js     ← 이렇게 쓰는 습관을 들이세요
//   폴더에 같은 이름의 폴더가 있으면 엉뚱한 것이 실행될 수 있습니다.

// [실수 5] 서버가 안 꺼져서 포트가 막힘
//   아직 서버를 안 만들었지만 미리 알아 두세요.
//   서버를 실행하면 프로그램이 안 끝나고 계속 돕니다. 정상입니다.
//   끄려면 그 터미널에서 Ctrl + C 입니다.
//   안 끄고 또 실행하면 "포트가 이미 사용 중" 에러가 납니다. (04단원에서 만납니다)

// ── 정리 ──

// 1. Node.js 는 브라우저 밖에서 자바스크립트를 실행해 주는 프로그램이다.
// 2. window, document, alert, localStorage 가 없다. 화면이 없기 때문이다.
// 3. 언어 문법은 완전히 같다. 새로 배울 문법이 아니다.
// 4. process 로 실행 환경(버전·OS·폴더)과 실행 인자를 알 수 있다.
// 5. node 파일이름.js 로 실행한다. node 만 치면 REPL 로 들어간다(.exit 로 나감).
// 6. 화면은 브라우저가, 데이터는 Node 가 담당한다.


// ============================================================
// _검증도구/구조감사.js — 자료의 '짜임새' 가 일정한지 본다
// ------------------------------------------------------------
// 사용:
//   node _검증도구/구조감사.js
//   node _검증도구/구조감사.js 07_데이터_저장하기
//   npm run 감사
//
// 왜 필요한가:
//   출력검증·서버검증·정합성검사는 전부 '이 코드가 제대로 도는가' 를 봅니다.
//   그런데 자료가 무너지는 방식은 하나가 더 있습니다.
//
//     단원을 만들다가 관례가 조용히 끊긴다.
//
//   실제로 겪은 것 — `── 정리 ──` 가 03단원 개념03에서 끊겨
//   04~10단원 38개 파일에 정리가 없었습니다. 코드는 멀쩡히 돌기 때문에
//   앞의 검증기 셋은 전부 초록불이었습니다.
//
//   문제 마커도 마찬가지입니다. `// ───── 문제 1 ─────` 로 쓰다가
//   몇 군데만 `// 문제 1` 로 쓰면, 세는 쪽이 그걸 못 보고 조용히 넘어갑니다.
//   ★ 마커를 놓치는 도구는 '못 찾았다' 고 하지 않고 '문제 없다' 고 합니다.
//
//   그래서 파일을 읽어서 짜임새를 셉니다.
//
// ── 무엇을 보나 ──
//
//   [개념 파일]
//     · 번호가 01부터 빠짐없이 이어지는가
//     · 섹션 · ✏️ 직접 해보기 · 자주 하는 실수 · 정리 가 다 있는가
//     · ✏️ 번호가 1부터 이어지는가
//     · 파일 끝에 `직접 해보기 정답` 블록이 있고, ✏️ 번호가 다 답해졌는가
//
//   [연습문제]
//     · 짝이 되는 정답 파일이 있는가
//     · 문제 마커가 `// ───── 문제 N ─────` 형식으로 일정한가
//     · 문제 번호가 1부터 빠짐없이 이어지는가
//     · 정답 파일에 같은 번호가 다 있는가
//
// ── 일부러 그런 경우 ──
//
//   그 파일 안에 이렇게 적어 두면 그 항목만 넘어갑니다. 이유를 반드시 쓰세요.
//
//     // 감사무시: 정리 — 이 파일은 다음 단원 예고라 정리할 것이 없음
//
//   쓸 수 있는 이름: 섹션 · 실습 · 실습정답 · 실수 · 정리
//
//   ★ '실습정답' 을 넣은 이유
//     `── 정리 ──` 가 03단원에서 조용히 끊겼던 것과 똑같은 일이
//     `직접 해보기 정답` 에서도 났습니다. 03단원 개념03 에서 끊겨
//     04~10단원 37개 파일 224문항에 답이 없었습니다.
//     세는 항목이 없으면 감사는 '문제 없음' 이라고 합니다.
// ============================================================

const fs = require("fs");
const path = require("path");

const 자료뿌리 = path.join(__dirname, "..");

const 섹션표시 = /──\s*섹션/;

// 섹션 줄 통째로.  번호를 보려면 있고 없고 말고 '줄' 을 봐야 한다.
const 섹션줄표시 = /──\s*섹션.*/g;
const 실습표시 = /✏️\s*직접 해보기\s*(\d+)/g;
const 실수표시 = /자주 하는 실수/;
const 정리표시 = /──\s*정리\s*──/;
const 실습정답표시 = /^\s*\/\/\s*직접 해보기 정답\s*$/m;

// 정답 블록 안의 항목 번호.  //  3) console.log(...)
const 실습정답항목 = /^\s*\/\/\s*(\d+)\)/gm;

// 정식 문제 마커.  // ───── 문제 3 ─────  (뒤에 제목이 붙어도 됨)
const 정식문제 = /^\s*\/\/\s*─+\s*문제\s*(\d+)/;

// 마커처럼 보이는데 ───── 가 없는 것.  // 문제 3 — 제목
//
// ★ 본문에서 문제를 '가리키는' 줄과 갈라야 한다.
//     // 문제 1의 주소에서        ← 가리키는 것. 마커가 아니다
//     //   문제 3·5·6 에서        ← 가리키는 것
//     // 문제 4·5 를 여기에 쓰세요  ← 가리키는 것
//     // 문제 1 — repositories/…  ← 이건 진짜 마커인데 형식만 다르다
//
//   숫자 뒤에 줄표가 오거나 줄이 끝나면 마커, 조사(의·를·에서)나 · 가 오면 본문이다.
const 어긋난문제 = /^\s*\/\/\s*문제\s*(\d+)\s*(?:[—–\-─]|$)/;

const 무시표시 = /\/\/\s*감사무시:\s*(\S+)/g;


function 읽기(경로) {
  return fs.readFileSync(경로, "utf8");
}

function 무시목록(소스) {
  const 목록 = new Set();
  for (const 맞음 of 소스.matchAll(무시표시)) 목록.add(맞음[1]);
  return 목록;
}

// 빠짐없이 이어지는지 본다. 어긋나면 설명을 돌려준다.
// 시작은 1번이 보통이지만 0번도 된다 — 04단원처럼 '문제 0: 공통 함수' 를 두는 곳이 있다.
function 이어지는가(번호들) {
  if (번호들.length === 0) return null;

  const 정렬 = [...new Set(번호들)].sort((가, 나) => 가 - 나);
  const 시작 = 정렬[0];

  if (시작 !== 0 && 시작 !== 1) return `1번이 아니라 ${시작}번부터 시작합니다`;

  for (let i = 0; i < 정렬.length; i += 1) {
    if (정렬[i] !== 시작 + i) return `${시작 + i}번이 빠졌습니다 (있는 것: ${정렬.join(", ")})`;
  }

  // 같은 번호를 두 번 쓴 경우
  if (정렬.length !== 번호들.length) {
    const 셈 = {};
    for (const n of 번호들) 셈[n] = (셈[n] || 0) + 1;
    const 겹침 = Object.keys(셈).filter((n) => 셈[n] > 1);
    if (겹침.length) return `번호가 겹칩니다: ${겹침.join(", ")}`;
  }

  return null;
}


// ★ 섹션 '번호' 까지 본다.
//
//   원래는 `── 섹션` 이 하나라도 있으면 통과였다. 그래서 한 파일에
//   `섹션 4` 가 두 번 있어도 조용히 넘어갔다. 실제로 00단원을 고치다 났다.
//   번호가 겹치면 학생은 "아까 그 섹션 4 아니었나?" 하고 위로 되돌아간다.
//
//   두 가지를 받아 줘야 오탐이 안 난다. 자료를 세어 보고 알았다.
//     · 곁가지 섹션 `4-2` — 05·06·07단원에 실제로 있다 (3곳)
//     · 섹션 0 부터 시작 — 03단원 개념04 가 그렇다 (일부러)
function 섹션번호검사(소스) {
  const 줄들 = 소스.match(섹션줄표시) || [];
  if (줄들.length === 0) return null;          // 섹션 유무는 앞에서 이미 본다

  const 본줄기 = [];
  const 곁가지 = [];
  const 번호없음 = [];

  for (const 줄 of 줄들) {
    const 맞음 = 줄.match(/──\s*섹션\s*(\d+)(?:-(\d+))?\s*:/);
    if (!맞음) {
      번호없음.push(줄.trim().slice(0, 40));
    } else if (맞음[2] === undefined) {
      본줄기.push(Number(맞음[1]));
    } else {
      곁가지.push(`${맞음[1]}-${맞음[2]}`);
    }
  }

  if (번호없음.length) return `섹션에 번호가 없습니다: ${번호없음.join(" / ")}`;

  const 어긋남 = 이어지는가(본줄기);
  if (어긋남) return `섹션 번호 — ${어긋남}`;

  const 곁겹침 = 곁가지.filter((이름, i) => 곁가지.indexOf(이름) !== i);
  if (곁겹침.length) return `섹션 번호가 겹칩니다: ${[...new Set(곁겹침)].join(", ")}`;

  const 있는본줄기 = new Set(본줄기);
  const 뜬것 = 곁가지.filter((이름) => !있는본줄기.has(Number(이름.split("-")[0])));
  if (뜬것.length) return `섹션 ${뜬것.join(", ")} 의 본줄기 섹션이 없습니다`;

  return null;
}


function 개념파일검사(폴더, 이름, 문제담기) {
  const 소스 = 읽기(path.join(폴더, 이름));
  const 무시 = 무시목록(소스);

  const 있어야할것 = [
    ["섹션", 섹션표시, "── 섹션 N: ... ── 이 하나도 없습니다"],
    ["실수", 실수표시, "자주 하는 실수 가 없습니다"],
    ["정리", 정리표시, "── 정리 ── 가 없습니다"],
  ];

  for (const [항목, 표시, 설명] of 있어야할것) {
    if (무시.has(항목)) continue;
    if (!표시.test(소스)) 문제담기(이름, `${설명}`);
  }

  if (!무시.has("섹션")) {
    const 섹션탈 = 섹션번호검사(소스);
    if (섹션탈) 문제담기(이름, 섹션탈);
  }

  const 실습번호 = [...소스.matchAll(실습표시)].map((맞음) => Number(맞음[1]));

  if (!무시.has("실습")) {
    if (실습번호.length === 0) {
      문제담기(이름, "✏️ 직접 해보기 가 하나도 없습니다");
    } else {
      const 어긋남 = 이어지는가(실습번호);
      if (어긋남) 문제담기(이름, `✏️ 번호 — ${어긋남}`);
    }
  }

  // ── ✏️ 마다 답이 있는가 ──
  //
  // ★ 답은 파일 끝 `직접 해보기 정답` 블록에 N) 으로 단다.
  //   ✏️ 만 있고 답이 없으면 학생은 막힌 채로 끝납니다.
  if (!무시.has("실습정답") && 실습번호.length > 0) {
    const 자리 = 소스.search(실습정답표시);

    if (자리 < 0) {
      문제담기(이름, `직접 해보기 정답 블록이 없습니다 (✏️ ${실습번호.length}개가 답 없이 남습니다)`);
    } else {
      const 블록 = 소스.slice(자리);
      const 답번호 = new Set([...블록.matchAll(실습정답항목)].map((맞음) => Number(맞음[1])));
      const 빠진것 = [...new Set(실습번호)].sort((가, 나) => 가 - 나).filter((n) => !답번호.has(n));

      if (빠진것.length) {
        문제담기(이름, `직접 해보기 정답에 ${빠진것.join(", ")} 번이 없습니다`);
      }
    }
  }
}


function 문제번호들(소스) {
  const 정식 = [];
  const 어긋남 = [];

  소스.split(/\r?\n/).forEach((줄, 자리) => {
    const 맞음 = 정식문제.exec(줄);
    if (맞음) {
      정식.push(Number(맞음[1]));
      return;
    }

    const 이상함 = 어긋난문제.exec(줄);
    if (이상함) 어긋남.push({ 행: 자리 + 1, 번호: Number(이상함[1]), 줄: 줄.trim() });
  });

  return { 정식, 어긋남 };
}


function 연습문제검사(폴더, 이름, 문제담기) {
  const 소스 = 읽기(path.join(폴더, 이름));
  const 무시 = 무시목록(소스);

  const 정답이름 = 이름.replace(/\.js$/, "_정답.js");
  const 정답경로 = path.join(폴더, 정답이름);

  if (!fs.existsSync(정답경로)) {
    문제담기(이름, `짝이 되는 ${정답이름} 이 없습니다`);
    return;
  }

  const { 정식, 어긋남 } = 문제번호들(소스);

  for (const 하나 of 어긋남) {
    문제담기(
      이름,
      `${하나.행}행  문제 마커 형식이 다릅니다 — "${하나.줄}"\n` +
        `        정식은 // ───── 문제 ${하나.번호} ───── 입니다. ` +
        `이대로 두면 세는 도구가 이 문제를 못 봅니다.`
    );
  }

  if (정식.length === 0 && 어긋남.length === 0) {
    // 서버를 미리 만들어 주고 화면만 만들게 하는 문제도 있다(10단원).
    // 그런 파일은 // 감사무시: 문제 — 이유 를 적어 둔다.
    if (!무시.has("문제")) 문제담기(이름, "문제 마커가 하나도 없습니다");
    return;
  }

  if (!무시.has("번호")) {
    const 전체 = [...정식, ...어긋남.map((하나) => 하나.번호)];
    const 어긋난것 = 이어지는가(전체);
    if (어긋난것) 문제담기(이름, `문제 번호 — ${어긋난것}`);
  }

  // 정답에 같은 번호가 다 있는지
  //
  // ★ 서버 정답 파일은 '완성된 서버 한 벌' 로 두는 곳이 있다(06·07·10단원).
  //   그런 파일은 번호 블록이 아예 없으므로 번호 대조를 하면 전부 빠진 것으로 나온다.
  //   그래서 정답에 마커가 하나도 없으면 그 사실만 한 줄로 알리고 대조는 건너뛴다.
  const 정답소스 = 읽기(정답경로);
  const 정답무시 = 무시목록(정답소스);
  if (정답무시.has("대조")) return;

  const 정답 = 문제번호들(정답소스);
  const 정답번호 = new Set([...정답.정식, ...정답.어긋남.map((하나) => 하나.번호)]);

  if (정답번호.size === 0) {
    문제담기(
      이름,
      `${정답이름} 에 문제 마커가 하나도 없어 번호를 대조할 수 없습니다.\n` +
        `        완성본 한 벌로 두는 것이 의도라면 그 파일에 // 감사무시: 대조 를 적어 두세요.`
    );
    return;
  }

  const 빠진것 = [...정식, ...어긋남.map((하나) => 하나.번호)]
    .filter((n) => !정답번호.has(n))
    .sort((가, 나) => 가 - 나);

  if (빠진것.length) {
    문제담기(이름, `${정답이름} 에 문제 ${빠진것.join(", ")} 번의 정답이 없습니다`);
  }
}


function 단원검사(단원) {
  const 폴더 = path.join(자료뿌리, 단원);
  const 문제들 = [];
  const 문제담기 = (파일, 내용) => 문제들.push({ 파일, 내용 });

  // ★ macOS 는 한글 파일 이름을 자소 분리(NFD)로 돌려줍니다.
  //   합친 형태(NFC)로 바꿔야 "개념"·"연습문제" 정규식이 맞습니다.
  const 파일들 = fs.existsSync(폴더)
    ? fs.readdirSync(폴더).map((이름) => 이름.normalize("NFC"))
    : [];

  // ── 개념 파일 ──
  const 개념들 = 파일들.filter((이름) => /^개념\d\d_.*\.js$/.test(이름)).sort();

  if (개념들.length > 0) {
    const 번호들 = 개념들.map((이름) => Number(이름.slice(2, 4)));
    const 어긋남 = 이어지는가(번호들);
    if (어긋남) 문제담기("(개념 파일)", `개념 번호 — ${어긋남}`);

    for (const 이름 of 개념들) 개념파일검사(폴더, 이름, 문제담기);
  }

  // ── 연습문제 ──
  const 연습들 = 파일들
    .filter((이름) => /^연습문제(_서버)?\.js$/.test(이름))
    .sort();

  for (const 이름 of 연습들) 연습문제검사(폴더, 이름, 문제담기);

  // ── 분량 세기 ──
  let 줄 = 0;
  let 섹션 = 0;
  let 실습 = 0;
  let 문항 = 0;

  function 훑기(현재) {
    for (const 항목 of fs.readdirSync(현재, { withFileTypes: true })) {
      const 이름 = 항목.name.normalize("NFC"); // macOS 자소 분리(NFD) 대응
      if (["node_modules", "uploads", "data", "시험파일"].includes(이름)) continue;

      const 경로 = path.join(현재, 이름);

      if (항목.isDirectory()) {
        훑기(경로);
        continue;
      }
      if (!/\.(js|html|css|md)$/.test(이름)) continue;

      const 소스 = 읽기(경로);
      줄 += 소스.split(/\r?\n/).filter((하나) => 하나.trim()).length;
      섹션 += (소스.match(/──\s*섹션/g) || []).length;
      // ★ ✏️ 글자를 세면 안 된다.
      //   정답 블록에서 다른 문제를 가리킬 때 (개념02 ✏️1) 처럼 쓰기 때문에
      //   글자를 세면 문항 수가 부풀어 오른다. 실제로 그렇게 나왔다.
      //   위에서 쓰는 것과 같은 마커 규칙으로 센다.
      실습 += (소스.match(/✏️\s*직접 해보기\s*\d+/g) || []).length;

      if (/^연습문제(_서버)?\.js$/.test(이름)) {
        const { 정식, 어긋남 } = 문제번호들(소스);
        문항 += 정식.length + 어긋남.length;
      }
    }
  }

  if (fs.existsSync(폴더)) 훑기(폴더);

  return { 단원, 개념수: 개념들.length, 줄, 섹션, 실습, 문항, 문제들 };
}


function 단원목록() {
  return fs
    .readdirSync(자료뿌리, { withFileTypes: true })
    .filter((항목) => 항목.isDirectory() && /^\d\d_/.test(항목.name))
    .map((항목) => 항목.name.normalize("NFC"))
    .sort();
}



// ── 섹션 4: 실제로 쓰는 상태코드 ──

// 수십 개가 있지만 이 여덟 개면 충분합니다.
//
//   200 OK                   잘 됐다. 조회·수정·삭제 성공
//   201 Created              새로 만들었다. POST 성공
//   204 No Content           잘 됐는데 돌려줄 내용이 없다. 삭제 후에 씁니다
//
//   400 Bad Request          요청이 잘못됐다. 필수 값이 없거나 형식이 틀림
//   401 Unauthorized         로그인이 안 되어 있다
//   403 Forbidden            로그인은 했는데 권한이 없다
//   404 Not Found            그런 것이 없다
//
//   500 Internal Server Error 서버에서 에러가 났다
//
// 401 과 403 의 차이
//   401  "당신이 누군지 모르겠습니다"        → 로그인하세요
//   403  "누군지는 아는데 안 됩니다"          → 관리자만 가능한 기능입니다
//
// 우리가 만들 문서 서버에 붙이면 이렇게 됩니다.

function 응답코드(상황) {
  const 표 = {
    "목록 조회 성공": 200,
    "문서 생성 성공": 201,
    "문서 삭제 성공": 204,
    "제목이 비어 있음": 400,
    "없는 문서 번호": 404,
    "코드에서 에러": 500,
  };
  return 표[상황] ?? 500;
}


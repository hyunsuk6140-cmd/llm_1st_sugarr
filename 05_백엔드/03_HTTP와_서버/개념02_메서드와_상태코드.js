// ── 섹션 3: 상태코드 — 결과를 숫자로 ──

// 서버는 응답할 때 세 자리 숫자를 함께 보냅니다. 첫 자리가 성격을 정합니다.
//
//     2xx   성공했다
//     3xx   다른 데로 가라 (리다이렉트)
//     4xx   ★ 요청한 쪽 잘못이다
//     5xx   ★ 서버 잘못이다
//
// 4 와 5 를 구분하는 것이 중요합니다.
//   4xx 가 나오면 요청을 고쳐야 하고,
//   5xx 가 나오면 서버 코드를 고쳐야 합니다.

function 상태설명(code) {
  if (code >= 500) {
    return "서버 잘못";
  }
  if (code >= 400) {
    return "요청한 쪽 잘못";
  }
  if (code >= 300) {
    return "다른 데로 이동";
  }
  if (code >= 200) {
    return "성공";
  }
  return "그 밖";
}

console.log(상태설명(200));
// 출력: 성공
console.log(상태설명(404));
// 출력: 요청한 쪽 잘못
console.log(상태설명(500));
// 출력: 서버 잘못

// 12단원(JS자료)에서 배운 것을 다시 짚고 갑시다.
//
//     fetch 는 404 나 500 을 '실패' 로 치지 않습니다.
//     서버가 대답을 했으니 성공으로 봅니다.
//     그래서 res.ok 를 직접 확인해야 했습니다.
//
// res.ok 는 사실 이 한 줄입니다.

function isOk(code) {
  return code >= 200 && code < 300;
}

console.log(isOk(200), isOk(201), isOk(404), isOk(500));
// 출력: true true false false


// ── 섹션 1: 메서드 — 무엇을 할 것인가 ──

// 같은 /documents 경로라도 메서드에 따라 하는 일이 다릅니다.
//
//     GET    /documents        목록을 달라        (읽기)
//     POST   /documents        새로 만들어 달라   (생성)
//     GET    /documents/12     12번을 달라        (읽기)
//     PUT    /documents/12     12번을 통째로 바꿔  (수정)
//     PATCH  /documents/12     12번의 일부만 바꿔  (부분 수정)
//     DELETE /documents/12     12번을 지워 달라   (삭제)
//
// 이 다섯 개면 거의 다 됩니다. 실무에서도 이것만 씁니다.
//
// 우리가 만들 서버가 하는 일을 함수로 표현하면 이렇습니다.

function 무슨일인가(method, path) {
  const 조각 = path.split("/").filter((s) => s !== "");
  const 개별 = 조각.length > 1; // /documents/12 처럼 뒤에 번호가 있는가

  if (method === "GET") {
    return 개별 ? "하나 조회" : "목록 조회";
  }
  if (method === "POST") {
    return "새로 만들기";
  }
  if (method === "PUT" || method === "PATCH") {
    return "수정";
  }
  if (method === "DELETE") {
    return "삭제";
  }
  return "모르는 메서드";
}


const 설비수 = 30;
const 일하는날 = 250; // 1년

// ★★ 문서는 두 갈래입니다. 이걸 섞어서 더하면 숫자가 뜻을 잃습니다.
//
//   ① 해마다 새로 쌓이는 것 — 작년 것과 올해 것이 둘 다 남습니다
//   ② 한 번 만들고 고쳐 쓰는 것 — 장수가 거의 안 늘어납니다

const 해마다쌓이는것 = {
  점검일지: 설비수 * 일하는날, // 설비마다 매일 한 장
  불량보고서: 12 * 30, // 월 30건쯤
  자재출납: 일하는날 * 8, // 하루 8건쯤
};

const 늘지않는것 = {
  작업표준서: 45, // 공정마다 하나. 개정될 때만 판이 바뀝니다
  설비이력카드: 설비수, // 설비마다 한 장에 계속 덧붙입니다
};

let 해마다합 = 0;
console.log("");

for (const 이름 in 해마다쌓이는것) {
  const 수 = 해마다쌓이는것[이름];
  해마다합 += 수;
  console.log(`${이름.padEnd(12, " ")} ${String(수).padStart(6, " ")} 건/년`);
}
console.log(`${"해마다 합".padEnd(12, " ")} ${String(해마다합).padStart(6, " ")} 건/년`);

console.log("");
for (const 이름 in 늘지않는것) {
  console.log(`${이름.padEnd(12, " ")} ${String(늘지않는것[이름]).padStart(6, " ")} 건 (안 늘어남)`);
}

console.log("");
console.log(`5년이면 ${(해마다합 * 5).toLocaleString("ko-KR")} 건이 쌓입니다.`);
// 출력:
// 출력: 점검일지           7500 건/년
// 출력: 불량보고서           360 건/년
// 출력: 자재출납           2000 건/년
// 출력: 해마다 합          9860 건/년
// 출력:
// 출력: 작업표준서            45 건 (안 늘어남)
// 출력: 설비이력카드           30 건 (안 늘어남)
// 출력:
// 출력: 5년이면 49,300 건이 쌓입니다.


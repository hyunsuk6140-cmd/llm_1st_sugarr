function 빈칸찾기(기록) {
  const 빈것 = [];
  for (const 칸 in 기록) {
    if (기록[칸] === "" || 기록[칸] === null || 기록[칸] === undefined) 빈것.push(칸);
  }
  return 빈것;
}


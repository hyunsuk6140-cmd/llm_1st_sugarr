// 출력: 03 이력 한 줄: 2 칸

// ★ 둘 다 날짜로 시작하는데 칸 수가 다릅니다.
//   표는 칸이 여러 개로 갈리고, 이력은 "날짜 + 글" 두 덩어리입니다.
//   ★★ 이 차이로 둘을 가를 수 있습니다.

function 모양판별2(글) {
  const 줄들 = 글.split("\n").filter((줄) => 줄.trim() !== "");

  // ★ 먼저 옛 규칙대로 선 글자를 봅니다.
  const 표문자 = (글.match(/[│┌┐└┘├┤┬┴┼─]/g) ?? []).length;
  if (표문자 >= 5) return "표형";

  // ★★ 새로 넣은 규칙 — 공백으로 줄을 맞춘 표를 잡습니다.
  //   칸이 셋 이상으로 갈리는 줄이 절반을 넘으면 표로 봅니다.
  const 칸많은줄 = 줄들.filter((줄) => 칸수(줄) >= 3).length;
  if (칸많은줄 >= 2 && 칸많은줄 > 줄들.length / 2) return "표형";

  const 날짜줄 = 줄들.filter((줄) => /^\d{4}-\d{2}-\d{2}/.test(줄.trim())).length;
  if (날짜줄 >= 2 && 날짜줄 >= 줄들.length / 2) return "덧붙임형";

  const 번호줄 = 줄들.filter((줄) => /^\s*\d+(\.\d+)*\.?\s/.test(줄)).length;
  if (번호줄 >= 2) return "서식형";

  return "모르겠음";
}


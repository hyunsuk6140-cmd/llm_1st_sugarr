// 글만 보고 어떤 모양인지 알 수 있을까요? 규칙을 만들어 봅니다.

function 모양판별(글) {
  const 줄들 = 글.split("\n");

  // ★ 표 그리는 문자가 많으면 표형
  const 표문자 = (글.match(/[│┌┐└┘├┤┬┴┼─]/g) ?? []).length;
  if (표문자 >= 5) return "표형";

  // ★ 날짜로 시작하는 줄이 절반을 넘으면 덧붙임형
  const 날짜줄 = 줄들.filter((줄) => /^\d{4}-\d{2}-\d{2}/.test(줄.trim())).length;
  if (날짜줄 >= 2 && 날짜줄 >= 줄들.length / 2) return "덧붙임형";

  // ★ "1." "4.2" 같은 번호가 붙은 줄이 있으면 서식형
  const 번호줄 = 줄들.filter((줄) => /^\s*\d+(\.\d+)*\.?\s/.test(줄)).length;
  if (번호줄 >= 2) return "서식형";

  return "모르겠음";
}


//     규칙은 자기가 틀렸다는 걸 모릅니다.
//     ★ 그래서 규칙은 반드시 **진짜 파일로** 시험해 봐야 합니다.
//       머릿속으로 만든 예시로만 시험하면 이런 것이 안 걸립니다.

// 표인지 아닌지를 선 말고 다른 것으로도 볼 수 있습니다.
// **한 줄이 몇 칸으로 갈리는가** 를 셉니다. 공백 두 칸 이상을 칸 경계로 봅니다.

function 칸수(줄) {
  return 줄.trim().split(/ {2,}/).length;
}


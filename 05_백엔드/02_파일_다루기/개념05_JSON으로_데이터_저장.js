// 그냥 읽으면 ENOENT 로 서버가 죽습니다.

function 불러오기() {
  if (!fs.existsSync(데이터파일)) {
    return []; // 없으면 빈 목록으로 시작
  }
  return JSON.parse(fs.readFileSync(데이터파일, "utf-8"));
}

function 저장하기(목록) {
  fs.writeFileSync(데이터파일, JSON.stringify(목록, null, 2), "utf-8");
}


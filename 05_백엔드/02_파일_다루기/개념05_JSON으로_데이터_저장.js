// [추가] — id 를 어떻게 정할까요?
function 추가하기(title, writer) {
  const 목록 = 불러오기();

  // 지금까지 쓴 id 중 가장 큰 것 + 1
  const 다음id = 목록.length === 0 ? 1 : Math.max(...목록.map((d) => d.id)) + 1;

  const 새문서 = { id: 다음id, title, writer, size: 0 };

  저장하기([...목록, 새문서]); // 원본을 바꾸지 않고 새 배열로 (JS자료 09단원)
  return 새문서;
}


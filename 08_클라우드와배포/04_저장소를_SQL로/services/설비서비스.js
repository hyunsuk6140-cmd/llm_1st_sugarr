// 이 파일에 담긴 다섯 가지 규칙
// ============================================================
//
//   ① 이름은 2글자 이상, 라인은 A/B/C
//   ② 같은 이름의 설비는 못 만든다
//   ③ 새 설비는 언제나 '정지' 로 시작한다
//   ④ 점검중 → 가동 으로 바로 못 간다
//   ⑤ 가동 중인 설비는 못 지운다
//
// 이 다섯 개가 '이 회사의 업무 규칙' 입니다.
// 화면이 웹이든 앱이든, 관리자 도구든 배치 작업이든 똑같이 지켜져야 합니다.
// 그래서 한 곳에 모아 두는 것입니다.
//
// ★ 규칙이 흩어지면 무슨 일이 생기나
//   웹에서는 가동 중인 설비를 못 지우는데, 관리자 도구에서는 지워집니다.
//   두 코드가 따로 만들어졌기 때문입니다.
//   그러다 데이터가 이상해지고, 아무도 원인을 못 찾습니다.
//
// ★ 이 파일이 status 를 안 받는 이유 (규칙 ③)
//   보낸 쪽이 { "status": "가동" } 을 넣어도 무시합니다.
//   상태는 상태바꾸기 함수로만 바꿀 수 있습니다.
//   그래야 규칙 ④가 반드시 지켜집니다.
//   등록에서 status 를 받으면, 처음부터 "가동" 으로 만들어 규칙을 피해 갈 수 있습니다.


// ============================================================
// AppError 에 status 가 들어 있는 것에 대하여
// ============================================================
//
// 이 파일은 "HTTP 를 모른다" 고 해 놓고, 던지는 에러에는 404·409 가 들어 있습니다.
// 엄밀히 따지면 어긋납니다.
//
// 더 깔끔한 방법은 이렇습니다.
//   서비스는 code 만 던진다      → throw new DomainError("NOT_FOUND")
//   컨트롤러가 코드를 상태로 바꾼다 → NOT_FOUND 면 404
//
// 그런데 층이 하나 더 생기고, 코드가 눈에 띄게 길어집니다.
// 실무 Node 프로젝트에서도 지금 방식(에러에 status 를 함께 담기)을 많이 씁니다.
//
// ★ 무엇이 정답인지보다, "왜 이렇게 했는지" 를 설명할 수 있는 게 중요합니다.
//   팀에서 이 이야기가 나오면 두 방법의 차이를 말할 수 있어야 합니다.

// ============================================================
// services/설비서비스.js — 업무 규칙이 있는 곳
// ------------------------------------------------------------
// "무엇을 해도 되고 무엇을 하면 안 되는가" 를 정하는 층입니다.
// ============================================================
//
// ★★ 이 파일의 규칙
//
//   HTTP 를 모릅니다        req, res 를 쓰지 않습니다
//   파일을 모릅니다         readFile 을 부르지 않습니다. 저장소에게 시킵니다
//   업무 규칙만 압니다      "가동 중인 설비는 못 지운다" 같은 것
//
// 이 층이 왜 필요한가
//   저장소는 "시키면 저장한다" 만 합니다. 되는지 안 되는지는 판단하지 않습니다.
//   컨트롤러는 "요청을 받아 응답한다" 만 합니다.
//   그럼 "가동 중이면 못 지운다" 는 규칙은 누가 알고 있어야 할까요?
//
//   컨트롤러에 두면, 나중에 배치 작업에서 설비를 지울 때 그 규칙이 안 지켜집니다.
//   저장소에 두면, 저장소가 업무를 알게 되어 다른 곳에서 못 씁니다.
//   그래서 가운데 층을 하나 둡니다.

const 설비저장소 = require("../repositories/설비저장소");
const { 에러 } = require("../utils/AppError");

const 라인값들 = ["A", "B", "C"];
const 상태값들 = ["가동", "정지", "점검중"];


async function 목록() {
  return 설비저장소.전부();
}

async function 하나(id) {
  const 설비 = await 설비저장소.하나(id);

  // ★ 저장소는 null 을 줍니다. 여기서 에러로 바꿉니다.
  //   이렇게 해 두면 이 함수를 부르는 쪽은 null 확인을 안 해도 됩니다.
  //   "없으면 에러가 날 것" 이라고 믿고 쓰면 됩니다.
  if (설비 === null) {
    throw 에러.없음("설비");
  }

  return 설비;
}


async function 등록(값) {
  // ── 규칙 1: 모양이 맞아야 한다 ──
  const 항목 = [];

  if (!값.name) 항목.push({ 키: "name", 이유: "필수입니다" });
  else if (값.name.length < 2) 항목.push({ 키: "name", 이유: "2글자 이상이어야 합니다" });

  if (!값.line) 항목.push({ 키: "line", 이유: "필수입니다" });
  else if (!라인값들.includes(값.line))
    항목.push({ 키: "line", 이유: `${라인값들.join(", ")} 중 하나여야 합니다` });

  if (항목.length > 0) {
    throw 에러.검증실패(항목);
  }

  // ── 규칙 2: 이름이 겹치면 안 된다 ──
  //
  // ★ 이건 저장소가 못 하는 판단입니다.
  //   저장소는 "이름이 겹치면 안 된다" 는 규칙을 모릅니다. 시키면 저장할 뿐입니다.
  //   그리고 데이터를 봐야 알 수 있으니 미들웨어에서도 못 합니다.
  //   딱 이 층이 할 일입니다.
  const 전부 = await 설비저장소.전부();

  if (전부.some((설비) => 설비.name === 값.name)) {
    throw 에러.중복("설비 이름");
  }

  // ── 규칙 3: 새 설비는 언제나 '정지' 로 시작한다 ──
  return 설비저장소.추가({
    name: 값.name,
    line: 값.line,
    status: "정지", // 보낸 값을 안 씁니다
  });
}


async function 상태바꾸기(id, 새상태) {
  if (!상태값들.includes(새상태)) {
    throw 에러.검증실패([
      { 키: "status", 이유: `${상태값들.join(", ")} 중 하나여야 합니다` },
    ]);
  }

  const 설비 = await 하나(id); // 없으면 여기서 에러가 납니다

  // ── 규칙 4: 점검중인 설비는 바로 가동으로 못 바꾼다 ──
  //
  // 점검이 끝났는지 확인하지 않고 돌리면 사고가 납니다.
  // 점검중 → 정지 → 가동 순서로만 가게 막습니다.
  if (설비.status === "점검중" && 새상태 === "가동") {
    throw 에러.상태충돌("점검중인 설비는 정지를 거쳐야 가동할 수 있습니다");
  }

  return 설비저장소.수정(id, { status: 새상태 });
}


async function 삭제(id) {
  const 설비 = await 하나(id); // 없으면 여기서 404

  // ── 규칙 5: 가동 중인 설비는 못 지운다 ──
  if (설비.status === "가동") {
    throw 에러.상태충돌("가동 중인 설비는 삭제할 수 없습니다. 먼저 정지시키세요");
  }

  await 설비저장소.삭제(id);
}


module.exports = { 목록, 하나, 등록, 상태바꾸기, 삭제 };



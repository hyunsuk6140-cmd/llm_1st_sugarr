// ============================================================
//
// 개념02 의 라우트와 비교해 보세요.
//
//   개념02 (섞여 있을 때)                이 파일 (나눴을 때)
//   ─────────────────────────────────────────────────────
//   검증 코드 4줄                        없음 (서비스가 함)
//   null 확인 + 404 응답 3줄             없음 (서비스가 던짐)
//   저장소 부르기                         서비스 부르기
//   응답 만들기                           응답 만들기
//
//   10~15줄  →  2~3줄
//
// ★ 짧아진 게 목적이 아닙니다.
//   "이 파일을 열면 HTTP 이야기만 보인다" 가 목적입니다.
//   업무 규칙이 궁금하면 서비스를, 저장 방법이 궁금하면 저장소를 엽니다.
//   찾을 곳이 분명해지는 것이 진짜 이득입니다.
//
// ★ Number(req.params.id) 는 왜 여기 있나
//   "주소에서 온 값은 글자다" 는 HTTP 의 사정입니다.
//   서비스는 숫자를 받는 게 당연하다고 생각합니다.
//   경계에서 타입을 맞춰 주는 것도 컨트롤러의 일입니다.

// ============================================================
// controllers/설비컨트롤러.js — HTTP 와 업무를 잇는 곳
// ------------------------------------------------------------
// 요청에서 값을 꺼내고, 서비스를 부르고, 응답을 만듭니다.
// ============================================================
//
// ★★ 이 파일의 규칙
//
//   HTTP 를 압니다          req 에서 꺼내고 res 로 보냅니다
//   업무 규칙은 모릅니다     "가동 중이면 못 지운다" 를 여기 쓰면 안 됩니다
//   저장을 모릅니다         파일인지 데이터베이스인지 모릅니다
//
// 컨트롤러가 하는 일은 딱 세 가지입니다.
//
//   ① 요청에서 값을 꺼낸다        req.params, req.query, req.body
//   ② 서비스를 부른다             await 서비스.등록(값)
//   ③ 응답을 만든다               상태코드 + { data }
//
// 이 세 줄이 넘어가면 뭔가를 잘못 넣은 것입니다.

const 설비서비스 = require("../services/설비서비스");


// 목록 보기
async function 목록(req, res) {
  const 설비들 = await 설비서비스.목록();

  res.json({ data: 설비들 });
}

// 하나 보기
async function 하나(req, res) {
  const 설비 = await 설비서비스.하나(Number(req.params.id));

  res.json({ data: 설비 });
}

// ★ 여기에 if (설비 === null) 이 없습니다.
//   서비스가 없으면 에러를 던지기 때문입니다.
//   던져진 에러는 Express 5 가 잡아서 에러 처리기로 보냅니다. (04단원 개념04)
//
//   컨트롤러가 "잘된 경우" 만 적으면 되니 아주 짧아집니다.


// 등록
async function 등록(req, res) {
  const { name, line } = req.body || {};

  const 새설비 = await 설비서비스.등록({ name, line });

  res.status(201).location(`/equipments/${새설비.id}`).json({ data: 새설비 });
}

// ★ 검증을 여기서 안 합니다.
//   "name 이 2글자 이상" 은 업무 규칙입니다. 서비스가 압니다.
//   컨트롤러는 값을 꺼내서 넘기기만 합니다.
//
// ★ 그런데 || {} 는 여기 있습니다.
//   "본문이 아예 안 왔다" 는 HTTP 사정이지 업무 규칙이 아니기 때문입니다.
//   이런 게 층을 나눌 때 판단이 필요한 부분입니다.


// 상태 바꾸기
async function 상태바꾸기(req, res) {
  const { status } = req.body || {};

  const 고쳐진것 = await 설비서비스.상태바꾸기(Number(req.params.id), status);

  res.json({ data: 고쳐진것 });
}


// 지우기
async function 삭제(req, res) {
  await 설비서비스.삭제(Number(req.params.id));

  res.sendStatus(204);
}


module.exports = { 목록, 하나, 등록, 상태바꾸기, 삭제 };



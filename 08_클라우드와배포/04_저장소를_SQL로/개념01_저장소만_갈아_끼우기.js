// 4. 그럼 저장소 안은 얼마나 달라졌나
// ============================================================

function 정리() {
  const 파일본 = 코드만("repositories/파일저장소.js");
  const SQL본 = 코드만("repositories/설비저장소.js");

  console.log("파일 저장소에 readFile 이 있나:", /readFile/.test(파일본));
  // 출력: 파일 저장소에 readFile 이 있나: true
  console.log("SQL 저장소에 readFile 이 있나:", /readFile/.test(SQL본));
  // 출력: SQL 저장소에 readFile 이 있나: false

  console.log("파일 저장소에 줄 세우기가 있나:", /줄서서/.test(파일본));
  // 출력: 파일 저장소에 줄 세우기가 있나: true
  console.log("SQL 저장소에 줄 세우기가 있나:", /줄서서/.test(SQL본));
  // 출력: SQL 저장소에 줄 세우기가 있나: false

  // ★★ 07단원 개념04 에서 만든 그 줄 세우기 코드가 통째로 사라졌습니다.
  //
  //   파일 저장소는 "읽고 → 고치고 → 쓰기" 라서 요청이 겹치면 유실됐습니다.
  //   그래서 쓰는 작업을 한 줄로 세워야 했습니다.
  //
  //   SQL 저장소는 UPDATE 한 문장입니다. 겹칠 틈이 없습니다.
  //   (02단원 개념05 에서 20건 실험으로 확인했습니다)
  //
  //   임시 파일에 쓰고 rename 하는 것도 없어졌습니다. SQLite 가 해 줍니다.

  console.log("SQL 저장소에 트랜잭션이 있나:", /BEGIN/.test(SQL본));
  // 출력: SQL 저장소에 트랜잭션이 있나: true

  // 초기화() 에만 있습니다. "비우고 다시 채우기" 가 중간에 실패하면 안 되니까요.

  // ============================================================
  // 5. 정리
  // ============================================================
  //
  //   갈아 끼우기의 조건
  //     ① 내보내는 함수 이름이 같아야 한다
  //     ② 돌려주는 모양이 같아야 한다 (없으면 null, 삭제는 true/false)
  //     ③ 안 바뀌어야 할 것이 안 바뀌어야 한다 (id, 안 보낸 칸)
  //
  //   갈아 끼울 때 실수하는 곳
  //     .get() 이 주는 undefined 를 null 로 안 바꿈  → 404 가 500 이 됨
  //     AUTOINCREMENT 를 안 붙임                   → 지운 id 가 재활용됨
  //     UPDATE 에 모든 칸을 넣음                    → 안 보낸 칸이 지워짐
  //     changes 를 안 봄                           → 없는 걸 지워도 성공
  //
  //   먼저 시험을 만들고 갈아 끼우세요. 손으로 눌러 보면 놓칩니다.
  //
  // 다음(개념02) 에서 표 구조를 바꿔야 할 때 어떻게 하는지 봅니다.
  //
  // ★ 이 파일이 만든 data 폴더의 파일들은 서버와 공유합니다.
  //   서버를 켜면 처음데이터로 다시 초기화됩니다.
  console.log("data 폴더에 파일이 생겼나:", fs.readdirSync(path.join(__dirname, "data")).length > 0);
  // 출력: data 폴더에 파일이 생겼나: true
}


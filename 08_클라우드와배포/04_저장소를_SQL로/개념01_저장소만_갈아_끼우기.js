// 2-2. 이 시험에서 걸리는 것들
// ============================================================
//
// 열 줄뿐이지만 갈아 끼울 때 실수하는 곳을 다 짚습니다.
//
//   하나(9999) 가 null (object)
//     .get() 은 undefined 를 줍니다. ?? null 을 빼먹으면 undefined 가 됩니다.
//     그러면 서비스의 if (설비 === null) 이 안 걸려서
//     404 가 나가야 할 자리에서 500 이 납니다.
//     타입까지 찍은 이유입니다. null 과 undefined 는 눈으로 구분이 안 됩니다.
//
//   추가 뒤 id=3
//     AUTOINCREMENT 를 안 붙이면 지운 번호가 재활용됩니다. (02단원 개념01)
//     파일 판은 Math.max + 1 이라 재활용되지 않았습니다.
//     초기화에서 sqlite_sequence 를 안 지우면 3 이 아니라 5, 7 로 늘어납니다.
//
//   수정 뒤 name 이 그대로
//     UPDATE SET 에 온 칸만 넣어야 합니다.
//     전부 다 넣으면 안 보낸 칸이 NULL 이나 undefined 로 덮입니다.
//
//   id 를 777 로 바꾸려 하면 id=3
//     바꿀 수 있는 칸을 목록으로 정해 뒀기 때문입니다.
//     이걸 안 하면 클라이언트가 id 를 바꿔 버릴 수 있습니다.
//
//   삭제(9999) 가 false
//     changes 를 안 보고 그냥 true 를 주면
//     없는 걸 지워도 204 가 나갑니다.
//
// ★★ 이런 시험을 **먼저 만들고** 갈아 끼우세요.
//   그러면 뭘 빠뜨렸는지 바로 알 수 있습니다.
//   서버를 켜서 손으로 눌러 보는 방식으로는 이 열 개를 다 못 짚습니다.

// ============================================================
// 3. 위층은 정말 안 고쳤나
// ============================================================

function 읽기(상대경로) {
  return fs.readFileSync(path.join(__dirname, 상대경로), "utf-8");
}

function 줄수(상대경로) {
  return 읽기(상대경로).split(/\r?\n/).length;
}

// ★★ 주석을 걷어 낸 '진짜 코드' 만 봅니다.
//
//   왜 필요한가 — 처음에는 파일 전체에서 SELECT 나 readFile 을 찾았습니다.
//   그런데 설비저장소.js 의 맨 아래 비교표에 이런 주석이 있습니다.
//
//     //   전부()  readFile + JSON.parse  →  SELECT ... ORDER BY id
//
//   그래서 "SQL 저장소에 readFile 이 있다" 는 잘못된 결과가 나왔습니다.
//   설명하려고 적어 둔 글자를 코드로 세어 버린 것입니다.
//
//   _검증도구 의 정합성검사와 출력검증에서도 똑같은 오탐이 났고,
//   같은 방식으로 고쳤습니다. 자료를 검사하는 도구를 만들 때 늘 만나는 문제입니다.
function 코드만(상대경로) {
  return 읽기(상대경로)
    .replace(/\/\*[\s\S]*?\*\//g, " ") // 여러 줄 주석
    .replace(/(^|[^:])\/\/.*$/gm, "$1"); // 한 줄 주석 (://  은 건드리지 않음)
}

const 위층들 = [
  "routes/설비라우트.js",
  "controllers/설비컨트롤러.js",
  "services/설비서비스.js",
  "utils/AppError.js",
  "utils/한국어.js",
];

function 마무리() {
  for (const 파일 of 위층들) {
    console.log(`${줄수(파일)}줄  ${파일}`);
  }
  // 출력: 44줄  routes/설비라우트.js
  // 출력: 108줄  controllers/설비컨트롤러.js
  // 출력: 161줄  services/설비서비스.js
  // 출력: 36줄  utils/AppError.js
  // 출력: 27줄  utils/한국어.js

  console.log("SQL 이 들어간 위층 파일이 있나:", 위층들.some((파일) =>
    /\b(SELECT|INSERT|UPDATE|DELETE|prepare|DatabaseSync)\b/.test(코드만(파일))
  ));
  // 출력: SQL 이 들어간 위층 파일이 있나: false

  console.log("서비스가 저장소를 부르나:", /require\(["'].*저장소/.test(코드만("services/설비서비스.js")));
  // 출력: 서비스가 저장소를 부르나: true

  console.log("컨트롤러·라우트가 저장소를 직접 부르나:",
    ["routes/설비라우트.js", "controllers/설비컨트롤러.js"]
      .some((파일) => /require\(["'].*저장소/.test(코드만(파일))));
  // 출력: 컨트롤러·라우트가 저장소를 직접 부르나: false

  // ★★ 이게 층을 나눈 값어치입니다.
  //
  //   컨트롤러는 서비스만 압니다.
  //   서비스는 저장소만 압니다.
  //   저장소만 SQL 을 압니다.
  //
  //   그래서 저장소를 바꿀 때 고칠 파일이 하나입니다.
  //
  // ★ 07단원 폴더가 옆에 있다면 직접 대조해 보세요. 아무 차이도 안 나옵니다.
  //
  //     Compare-Object (Get-Content 백엔드자료\07_데이터_저장하기\services\설비서비스.js) `
  //                    (Get-Content 클라우드자료\04_저장소를_SQL로\services\설비서비스.js)
  //
  //   Bash 라면:
  //     diff 백엔드자료/07_데이터_저장하기/services/설비서비스.js \
  //          클라우드자료/04_저장소를_SQL로/services/설비서비스.js

  정리();
}


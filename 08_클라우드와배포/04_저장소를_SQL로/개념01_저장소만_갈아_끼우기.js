const 파일것들 = Object.keys(파일저장소).sort();
const SQL것들 = Object.keys(SQL저장소).sort();

console.log("파일 저장소:", 파일것들.join(", "));
// 출력: 파일 저장소: 삭제, 수정, 전부, 초기화, 추가, 하나
console.log("SQL  저장소:", SQL것들.join(", "));

// ★ 이게 첫 번째 조건입니다. 이름이 같아야 갈아 끼울 수 있습니다.
//   하나라도 이름이 다르면 부르는 쪽을 고쳐야 합니다.

// ============================================================
// 2. 같은 시험을 두 저장소에 똑같이 돌립니다
// ============================================================
//
// 이름만 같으면 안 됩니다. **똑같이 동작해야** 합니다.
// 시험 하나를 만들어서 두 저장소에 그대로 돌립니다.

// ★ 07단원의 서버가 넘겨 주던 것과 똑같이 id 를 붙였습니다.
//   파일 저장소는 준 것을 그대로 파일에 씁니다. id 가 없으면 id 없는 줄이 됩니다.
//   SQL 저장소도 그 동작을 맞춰야 갈아 끼울 수 있습니다.
const 처음자료 = [
  { id: 1, name: "컨베이어 1호", line: "A", status: "가동" },
  { id: 2, name: "프레스 1호", line: "B", status: "정지" },
];

async function 시험하기(저장소) {
  const 기록 = [];

  await 저장소.초기화(처음자료);

  // ── 전부() ──
  const 목록 = await 저장소.전부();
  기록.push(`전부: ${목록.length}개, 첫째=${목록[0].name}, id=${목록[0].id}`);

  // ── 하나() 있는 것 ──
  const 있는것 = await 저장소.하나(1);
  기록.push(`하나(1): ${있는것.name} / ${있는것.status}`);

  // ── 하나() 없는 것 ── ★ 여기가 가장 중요합니다
  const 없는것 = await 저장소.하나(9999);
  기록.push(`하나(9999): ${없는것} (${typeof 없는것})`);

  // ── 추가() ──
  const 만든것 = await 저장소.추가({ name: "용접로봇 1호", line: "C", status: "정지" });
  기록.push(`추가: id=${만든것.id}, name=${만든것.name}`);

  // ── 수정() ──
  const 고친것 = await 저장소.수정(만든것.id, { status: "점검중" });
  기록.push(`수정: ${고친것.status}, name 은 그대로=${고친것.name}`);

  // ── 수정() 없는 것 ──
  기록.push(`수정(9999): ${await 저장소.수정(9999, { status: "가동" })}`);

  // ── 수정() 으로 id 를 바꾸려 하면 ──
  const id바꾸기 = await 저장소.수정(만든것.id, { id: 777, status: "정지" });
  기록.push(`id 를 777 로 바꾸려 하면: id=${id바꾸기.id}`);

  // ── 삭제() ──
  기록.push(`삭제(${만든것.id}): ${await 저장소.삭제(만든것.id)}`);
  기록.push(`삭제(9999): ${await 저장소.삭제(9999)}`);

  // ── 남은 개수 ──
  기록.push(`남은 개수: ${(await 저장소.전부()).length}`);

  return 기록;
}

async function 나란히() {
  const 파일결과 = await 시험하기(파일저장소);
  const SQL결과 = await 시험하기(SQL저장소);

  for (let i = 0; i < 파일결과.length; i++) {
    const 같나 = 파일결과[i] === SQL결과[i] ? "○" : "✗";
    console.log(`${같나} ${파일결과[i]}`);
  }
  // 출력: ○ 전부: 2개, 첫째=컨베이어 1호, id=1
  // 출력: ○ 하나(1): 컨베이어 1호 / 가동
  // 출력: ○ 하나(9999): null (object)
  // 출력: ○ 추가: id=3, name=용접로봇 1호
  // 출력: ○ 수정: 점검중, name 은 그대로=용접로봇 1호
  // 출력: ○ 수정(9999): null
  // 출력: ○ id 를 777 로 바꾸려 하면: id=3
  // 출력: ○ 삭제(3): true
  // 출력: ○ 삭제(9999): false
  // 출력: ○ 남은 개수: 2

  console.log("모두 같은가:", JSON.stringify(파일결과) === JSON.stringify(SQL결과));
  // 출력: 모두 같은가: true

  마무리();
}


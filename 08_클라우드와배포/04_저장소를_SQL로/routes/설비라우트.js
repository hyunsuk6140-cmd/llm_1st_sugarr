//
//     router.post("/", 인증, 역할확인("admin"), 설비컨트롤러.등록);
//     router.delete("/:id", 인증, 역할확인("admin"), 설비컨트롤러.삭제);
//
//   "누가 할 수 있는가" 가 이 파일에 한눈에 보입니다.

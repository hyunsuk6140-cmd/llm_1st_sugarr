// ============================================================
// 4. 방법 ① 서비스가 트랜잭션을 연다
// ============================================================
//
// 트랜잭션의 범위는 "업무 하나" 입니다.
// 업무를 아는 층은 서비스입니다. 그래서 서비스가 여는 게 자연스럽습니다.
//
// 그런데 서비스가 db.exec("BEGIN") 을 부르면 SQL 을 알게 됩니다.
// 그래서 감싸는 함수를 하나 만들어 둡니다.

// ── repositories/트랜잭션.js 에 둘 만한 것 ──

function 한묶음으로(하기) {
  if (db.isTransaction) {
    // ★ 이미 트랜잭션 안이면 새로 열지 않습니다.
    //   겹쳐서 BEGIN 하면 오류가 납니다. (02단원 개념05)
    return 하기();
  }

  db.exec("BEGIN");
  try {
    const 결과 = 하기();
    db.exec("COMMIT");
    return 결과;
  } catch (에러) {
    db.exec("ROLLBACK");
    throw 에러;
  }
}

// ★★ 이 함수에는 SQL 이 있지만 저장소 폴더에 있습니다.
//   서비스는 "한묶음으로(() => {...})" 만 씁니다. BEGIN 을 모릅니다.
//   "DB 를 아는 코드는 저장소 폴더 안에" 라는 규칙이 지켜집니다.

// ── 서비스 ──

function 점검기록하기(설비id, 결과) {
  return 한묶음으로(() => {
    // ★ 안쪽은 **동기**로만 씁니다. await 를 쓰면 안 됩니다.
    //   트랜잭션 중에 await 하면 다른 요청이 끼어듭니다. (02단원 개념05)
    //   그래서 여기서는 저장소의 동기 버전을 씁니다.

    const 점검 = db.prepare("INSERT INTO 점검 (설비id, 결과) VALUES (?, ?) RETURNING id")
      .get(설비id, 결과);

    if (결과 === "이상") {
      db.prepare("UPDATE 설비 SET status = ? WHERE id = ?").run("점검중", 설비id);
    }

    db.prepare("INSERT INTO 이력 (설비id, 내용) VALUES (?, ?)").run(설비id, `점검 ${결과}`);

    return 점검;
  });
}

async function 실험3() {
  const 전_점검 = db.prepare("SELECT COUNT(*) AS n FROM 점검 WHERE 설비id = 2").get().n;
  const 전_이력 = await 이력저장소.개수();

  console.log("성공하는 경우:", 점검기록하기(2, "이상").id > 0);
  // 출력: 성공하는 경우: true
  console.log("설비 상태:", (await 설비저장소.하나(2)).status);
  // 출력: 설비 상태: 점검중

  // 이제 실패하는 경우를 봅시다.
  try {
    한묶음으로(() => {
      db.prepare("INSERT INTO 점검 (설비id, 결과) VALUES (?, ?)").run(2, "이상");
      db.prepare("UPDATE 설비 SET status = ? WHERE id = ?").run("없는상태", 2);
    });
  } catch (에러) {
    console.log("실패 잡음:", /CHECK/.test(에러.message));
    // 출력: 실패 잡음: true
  }

  console.log("점검이 늘었나:", db.prepare("SELECT COUNT(*) AS n FROM 점검 WHERE 설비id = 2").get().n - 전_점검);
  // 출력: 점검이 늘었나: 1
  console.log("이력이 늘었나:", (await 이력저장소.개수()) - 전_이력);
  // 출력: 이력이 늘었나: 1

  // ★★ 성공한 것 1건만 남았습니다. 실패한 쪽은 통째로 되돌아갔습니다.
  //   실험2 에서는 반쯤 된 상태가 남았습니다. 그 차이입니다.

  console.log("트랜잭션 안 열려 있나:", db.isTransaction === false);
  // 출력: 트랜잭션 안 열려 있나: true

  // ★ ROLLBACK 이 제대로 됐다는 뜻입니다.
  //   catch 에 ROLLBACK 을 안 쓰면 여기가 true 가 되고,
  //   그 뒤 모든 요청이 "cannot start a transaction within a transaction" 으로 죽습니다.

  await 실험4();
}


// ============================================================
// 7. 그럼 저장소의 함수를 못 쓰나
// ============================================================
//
// 위 서비스 코드에서 db.prepare 를 직접 불렀습니다.
// 저장소를 안 쓴 셈입니다. 계층이 무너진 것 아닌가요?
//
// ★ 맞습니다. 이게 트랜잭션의 어려운 점입니다.
//
//   저장소 함수들이 async 라서 트랜잭션 안에서 await 로 부를 수 없습니다.
//   그렇다고 async 를 떼면 05단원의 Supabase 로 못 갑니다. (그쪽은 진짜 비동기)
//
// ★★ 실무에서 쓰는 세 가지 방법
//
//   ① 저장소에 동기 버전을 같이 둔다
//
//        module.exports = {
//          하나, 추가, 수정,              // async — 보통 쓰는 것
//          동기: { 하나, 추가, 수정 },     // 트랜잭션 안에서 쓰는 것
//        };
//
//      코드가 두 벌이 되지만 계층은 지켜집니다.
//      SQLite 를 쓰는 동안에는 이게 제일 깔끔합니다.
//
//   ② 트랜잭션이 필요한 업무를 저장소에 하나의 함수로 둔다
//
//        점검저장소.기록하고_상태바꾸기(설비id, 결과)
//
//      저장소가 업무를 조금 알게 됩니다. 대신 트랜잭션이 한 곳에 갇힙니다.
//      업무 규칙이 단순하면 이게 가장 실용적입니다.
//
//   ③ 트랜잭션 객체를 넘긴다 (다른 DB 라이브러리에서 흔한 방식)
//

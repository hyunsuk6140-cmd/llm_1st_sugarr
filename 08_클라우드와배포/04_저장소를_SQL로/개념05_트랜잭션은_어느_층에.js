// 5. ★★ 왜 안쪽을 동기로 써야 하나
// ============================================================

async function 실험4() {
  let 오류 = "";

  // ★ 실패할 Promise 를 미리 만들어 둡니다.
  //   .catch 를 붙여 두는 이유: 아무도 처리하지 않은 Promise 실패는
  //   Node 프로세스를 죽입니다. (실제로 이 파일을 쓰다가 죽었습니다)
  const 나중에실패할것 = Promise.reject(new Error("나중에 실패"));
  나중에실패할것.catch(() => {});

  try {
    한묶음으로(() => {
      db.prepare("INSERT INTO 이력 (설비id, 내용) VALUES (?, ?)").run(1, "시험");
      // ★ Promise 를 돌려주면 한묶음으로 가 기다려 주지 않습니다
      return 나중에실패할것;
    });
  } catch (에러) {
    오류 = 에러.message;
  }

  console.log("catch 가 잡았나:", 오류 === "나중에 실패");
  // 출력: catch 가 잡았나: false

  // ★★★ 못 잡았습니다.
  //
  //   한묶음으로 는 동기 함수입니다.
  //   안쪽이 Promise 를 돌려주면 "성공했다" 고 보고 COMMIT 을 해 버립니다.
  //   그 Promise 가 나중에 실패해도 이미 커밋된 뒤입니다.
  //
  //   그래서 규칙이 이렇게 됩니다.

  console.log("커밋됐나:", db.isTransaction === false);
  // 출력: 커밋됐나: true

  // ★★ 트랜잭션 안에서는
  //
  //   ○ 동기 DB 호출만 한다
  //   ✗ await 를 쓰지 않는다
  //   ✗ fetch, 파일 쓰기, 이메일 보내기를 넣지 않는다
  //
  // ★ 밖에서 받아야 할 것이 있으면 **먼저 받아 둡니다.**
  //
  //     const 환율 = await 환율API가져오기();     ← 트랜잭션 밖에서
  //     한묶음으로(() => {
  //       ... 환율을 써서 DB 작업만 ...
  //     });
  //
  // ★★ 이걸 어기면 무슨 일이 생기나
  //   트랜잭션이 열린 채로 외부 API 를 기다립니다.
  //   그 사이 SQLite 의 쓰기 잠금을 붙잡고 있습니다.
  //   다른 요청은 전부 "database is locked" 로 실패합니다. (02단원 개념05)
  //
  //   외부 API 가 3초 걸리면 3초 동안 서버가 멈춥니다.

  await 실험5();
}


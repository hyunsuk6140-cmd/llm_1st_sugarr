// 04단원에서는 층이 나뉘어 있습니다. 그럼 BEGIN 을 어디에 쓸까요?
//
//   저장소에?    → 저장소 두 개를 묶을 수 없습니다
//   서비스에?    → 서비스가 SQL 을 알게 됩니다
//   컨트롤러에?  → HTTP 층이 DB 를 알게 됩니다
//
// 정답이 하나는 아니지만, 어떤 문제가 생기는지는 정해져 있습니다.
// 하나씩 해 보고 정리합니다.
//
// 실행: node 개념05_트랜잭션은_어느_층에.js
// ============================================================

const { DatabaseSync } = require("node:sqlite");

const db = new DatabaseSync(":memory:");

db.exec(`
  CREATE TABLE 설비 (
    id     INTEGER PRIMARY KEY AUTOINCREMENT,
    name   TEXT    NOT NULL UNIQUE,
    status TEXT    NOT NULL DEFAULT '정지'
                   CHECK (status IN ('가동', '정지', '점검중'))
  ) STRICT;

  CREATE TABLE 점검 (
    id     INTEGER PRIMARY KEY AUTOINCREMENT,
    설비id INTEGER NOT NULL REFERENCES 설비(id),
    결과   TEXT    NOT NULL CHECK (결과 IN ('정상', '이상'))
  ) STRICT;

  CREATE TABLE 이력 (
    id     INTEGER PRIMARY KEY AUTOINCREMENT,
    설비id INTEGER NOT NULL,
    내용   TEXT    NOT NULL
  ) STRICT;
`);

db.exec("INSERT INTO 설비 (name, status) VALUES ('용접로봇 1호', '가동'), ('프레스 1호', '정지')");

// ============================================================
// 1. 왜 필요한가 — 두 표를 같이 고치는 업무
// ============================================================
//
// "점검을 기록하고, 결과가 '이상' 이면 설비를 점검중으로 바꾼다"
//
// 이건 두 표를 건드립니다. 둘 다 되거나 둘 다 안 되어야 합니다.
//
//   점검만 기록되고 설비 상태가 안 바뀌면
//   → 이상이 있는 설비가 계속 가동 중으로 보입니다. 사고로 이어집니다.

// ── 먼저 저장소들 (각자 자기 표만 압니다) ──

const 설비저장소 = {
  하나: async (id) => db.prepare("SELECT id, name, status FROM 설비 WHERE id = ?").get(id) ?? null,
  상태바꾸기: async (id, 상태) =>
    db.prepare("UPDATE 설비 SET status = ? WHERE id = ? RETURNING id, name, status")
      .get(상태, id) ?? null,
};

const 점검저장소 = {
  추가: async (설비id, 결과) =>
    db.prepare("INSERT INTO 점검 (설비id, 결과) VALUES (?, ?) RETURNING id, 설비id, 결과")
      .get(설비id, 결과),
  개수: async (설비id) =>
    db.prepare("SELECT COUNT(*) AS n FROM 점검 WHERE 설비id = ?").get(설비id).n,
};

const 이력저장소 = {
  추가: async (설비id, 내용) =>
    db.prepare("INSERT INTO 이력 (설비id, 내용) VALUES (?, ?)").run(설비id, 내용).changes,
  개수: async () => db.prepare("SELECT COUNT(*) AS n FROM 이력").get().n,
};

// ============================================================
// 2. 트랜잭션 없이 하면
// ============================================================

async function 트랜잭션없이(설비id, 결과) {
  await 점검저장소.추가(설비id, 결과);

  if (결과 === "이상") {
    await 설비저장소.상태바꾸기(설비id, "점검중");
  }

  await 이력저장소.추가(설비id, `점검 ${결과}`);
}


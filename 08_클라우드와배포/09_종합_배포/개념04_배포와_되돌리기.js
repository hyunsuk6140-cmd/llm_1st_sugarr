const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");

const 연습폴더 = path.join(os.tmpdir(), "배포04연습");
fs.rmSync(연습폴더, { recursive: true, force: true });
fs.mkdirSync(연습폴더, { recursive: true });

function 문법검사(경로) {
  try {
    execFileSync("bash", ["-n", 경로], { stdio: ["ignore", "pipe", "pipe"] });
    return "통과";
  } catch (에러) {
    return `오류: ${(에러.stderr ?? "").toString().trim().split("\n")[0]}`;
  }
}

// ============================================================
// 1. 완성한 배포 스크립트
// ============================================================

const 배포 = `#!/bin/bash
# 배포.sh — 새 코드를 올립니다
set -euo pipefail

APP_DIR=\${APP_DIR:-/home/ubuntu/앱}
APP_NAME=\${APP_NAME:-설비api}
HEALTH_URL=\${HEALTH_URL:-http://127.0.0.1:3000/health}
SHA_FILE=/home/ubuntu/.이전커밋

echo "== 배포 시작 $(date '+%F %T')"

cd "$APP_DIR"

# ── 1. 되돌릴 지점을 기억 ★ 파일에 쓰는 건 맨 뒤에서 합니다 ──
PREV_SHA=$(git rev-parse HEAD)
echo "이전 커밋: $PREV_SHA"

# ── 2. 새 코드 ──
git fetch origin
git reset --hard origin/main
NEW_SHA=$(git rev-parse HEAD)

if [ "$PREV_SHA" = "$NEW_SHA" ]; then
  echo "바뀐 게 없습니다"
  exit 0
fi

# ── 3. ★ 배포 전 점검 (개념02) ──
node 배포/배포점검.js .

# ── 4. 패키지 (lock 이 바뀌었거나 node_modules 가 없으면) ──
if [ ! -d node_modules ] || ! git diff --quiet "$PREV_SHA" "$NEW_SHA" -- package-lock.json; then
  echo "의존성을 다시 깝니다"
  npm ci --omit=dev
fi

# ── 5. 표 구조 (04단원 개념02) ──
npm run migrate

# ── 6. 교체 ★ 클러스터 + wait_ready 일 때만 무중단입니다 (07단원 개념02) ──
pm2 reload "$APP_NAME" --update-env

# ── 7. ★ 진짜 되는지 확인 ──
sleep 3
for i in 1 2 3 4 5; do
  if curl -fsS "$HEALTH_URL" > /dev/null; then
    # ★★ 여기까지 와야 "돌아갈 수 있는 커밋" 입니다. 그래서 지금 씁니다.
    echo "$PREV_SHA" > "$SHA_FILE"
    echo "== 배포 끝 ($NEW_SHA)"
    exit 0
  fi
  echo "확인 실패 ($i/5). 2초 뒤 다시"
  sleep 2
done

echo "!! health 확인이 5번 다 실패했습니다"
echo "!! 되돌리려면: bash 배포/되돌리기.sh"
exit 1
`;

const 배포경로 = path.join(연습폴더, "배포.sh");
fs.writeFileSync(배포경로, 배포, "utf-8");

console.log("배포.sh 문법:", 문법검사(배포경로));
// 출력: 배포.sh 문법: 통과

// ★★ 07단원 개념05 에서 더한 것 네 가지
//
//   ① 이전 커밋을 **파일에 저장**합니다
//      되돌리기 스크립트가 그걸 읽습니다. HEAD~1 보다 정확합니다.
//      ★★★ 쓰는 자리가 중요합니다. **health 가 통과한 뒤에** 씁니다.
//        맨 앞에서 쓰면 이런 일이 생깁니다.
//          배포 → 실패(깨진 코드가 HEAD) → 고쳐서 배포.sh 를 다시 실행
//          → 맨 앞의 git rev-parse HEAD 가 **깨진 커밋**을 읽습니다
//          → .이전커밋 이 깨진 커밋으로 덮입니다
//          → 나중에 되돌리기.sh 가 **깨진 버전으로 되돌립니다**
//        "돌아가도 되는 곳" 은 health 로 확인된 곳뿐입니다.
//
//   ② 바뀐 게 없으면 일찍 끝냅니다
//      같은 커밋인데 reload 하면 괜히 끊길 위험만 있습니다.
//
//   ③ 배포점검을 끼워 넣었습니다 (개념02)
//      막음이 있으면 종료 코드 1 → set -e 가 배포를 멈춥니다.
//
//   ④ health 확인을 **다섯 번 다시** 합니다
//      한 번만 하면 아직 준비 중일 때 실패로 봅니다.
//      07단원 개념02 의 process.send("ready") 와 짝입니다.
//
// ★★★ ④ 가 없으면 어떻게 되나
//   앱이 3.5초에 준비되는데 3초에 확인하면 실패합니다.
//   배포는 잘 됐는데 실패로 나옵니다. 그러면 사람이 도구를 안 믿게 됩니다.
//   "될 때까지 몇 번 본다" 가 필요합니다.

// ★★★ `pm2 reload` 가 **항상** 무중단인 것은 아닙니다.
//
//   조건이 두 가지 있습니다. 둘 다 있어야 "무중단" 입니다.
//
//   ① **클러스터 모드여야 합니다.**
//      `pm2 start 앱.js` 의 기본값은 fork 모드입니다. 프로세스가 하나뿐이라
//      바꿀 게 하나뿐이고, 그 시간이 **통째로 빕니다.** restart 와 같습니다.
//      (07단원 개념02 에서 직접 재 봤습니다)
//      → ecosystem.config.js 에 exec_mode: "cluster", instances 2 이상
//
//   ② **wait_ready 가 있어야 합니다.**
//      없으면 PM2 는 새 프로세스가 뜨자마자 "됐다" 고 보고 옛것을 죽입니다.
//      앱이 아직 listen 전이면 그 사이 요청이 nginx 에서 **502** 가 됩니다.
//      → 설정에 wait_ready: true, 앱에서 process.send("ready")
//        (07단원 개념01 의 ecosystem.config.js, 개념02 의 우아한 종료)
//
//   ★ 그래서 스크립트에 `pm2 reload` 를 써 놓았다고 무중단이 되는 게 아닙니다.
//     ecosystem.config.js 를 먼저 확인하세요.

// ★★ 4번 단계의 `[ ! -d node_modules ] ||` 도 일부러 넣은 것입니다.
//   lock 이 안 바뀌면 npm ci 를 건너뛰는데, node_modules 자체가 없는 때가
//   있습니다 — 첫 배포, 디스크가 차서 지운 뒤, npm ci 를 중간에 끊은 뒤.
//   그때 그냥 넘어가면 의존성 없이 reload 해서 앱이 못 뜹니다.

// ============================================================
// 2. 되돌리기 스크립트
// ============================================================

const 되돌리기 = `#!/bin/bash
# 되돌리기.sh — 배포 직전 커밋으로 돌아갑니다
set -euo pipefail

APP_DIR=\${APP_DIR:-/home/ubuntu/앱}
APP_NAME=\${APP_NAME:-설비api}
HEALTH_URL=\${HEALTH_URL:-http://127.0.0.1:3000/health}
SHA_FILE=/home/ubuntu/.이전커밋

TARGET_SHA=\${1:-}

if [ -z "$TARGET_SHA" ]; then
  if [ ! -f "$SHA_FILE" ]; then
    echo "!! 돌아갈 곳을 모릅니다. 커밋을 인자로 주세요"
    echo "   bash 되돌리기.sh <커밋>"
    exit 1
  fi
  TARGET_SHA=$(cat "$SHA_FILE")
fi

echo "== $TARGET_SHA 으로 되돌립니다"

cd "$APP_DIR"
NOW_SHA=$(git rev-parse HEAD)
git reset --hard "$TARGET_SHA"

# ★ lock 이 그대로면 npm ci 를 건너뜁니다. 되돌리기는 빨라야 합니다.
if [ ! -d node_modules ] || ! git diff --quiet "$NOW_SHA" "$TARGET_SHA" -- package-lock.json; then
  echo "의존성을 되돌립니다"
  npm ci --omit=dev
fi

pm2 reload "$APP_NAME" --update-env

sleep 3
for i in 1 2 3 4 5; do
  if curl -fsS "$HEALTH_URL" > /dev/null; then
    echo "== 되돌렸습니다"
    exit 0
  fi
  sleep 2
done

echo "!! 되돌렸는데도 health 가 안 됩니다. DB 나 설정을 보세요"
exit 1
`;

const 되돌리기경로 = path.join(연습폴더, "되돌리기.sh");
fs.writeFileSync(되돌리기경로, 되돌리기, "utf-8");

console.log("되돌리기.sh 문법:", 문법검사(되돌리기경로));
// 출력: 되돌리기.sh 문법: 통과

// ★★★ 마지막 메시지가 중요합니다.
//
//   "되돌렸는데도 안 되면 코드 문제가 아닙니다."
//
//   코드는 확실히 예전 것으로 돌아갔습니다.
//   그런데도 안 되면 DB 나 .env 나 외부 서비스 쪽입니다.
//   그걸 알려 줘야 사람이 엉뚱한 데를 안 뒤집니다.
//
// ★★ npm ci 를 조건부로 바꾼 이유
//
//   무조건 돌리면 t3.micro(1GB) 에서 수십 초에서 몇 분이 걸립니다.
//   그러면 **되돌리기가 배포보다 느려집니다.** 개념05 에서 "되돌리기.sh 가
//   있으면 30초" 라고 한 것과 어긋납니다. 급할 때 쓰는 도구인데요.
//   되돌리는 커밋과 lock 이 같으면 node_modules 는 이미 맞습니다.
//
// ★★★ 더 빠르게 하는 방법도 있습니다 — 릴리스 디렉터리 + 심볼릭 링크
//
//     /home/ubuntu/릴리스/2026-08-26-1430/   ← 커밋마다 폴더를 따로
//     /home/ubuntu/릴리스/2026-08-26-1615/
//     /home/ubuntu/앱 -> 릴리스/2026-08-26-1615   ← current 링크
//
//   배포는 새 폴더를 만들어 npm ci 까지 마친 뒤 **링크만 바꿉니다.**
//   되돌리기는 링크를 옛 폴더로 되돌리는 것뿐이라 **1초**입니다.
//   node_modules 가 폴더마다 이미 있으니 npm ci 가 아예 없습니다.
//
//   ★ 대신 폴더가 계속 쌓입니다. 최근 3~5개만 남기고 지우는 정리가 필요하고,
//     PM2 의 cwd 와 nginx 경로도 링크를 가리키게 맞춰야 합니다.
//   이 수업은 git reset 방식으로 갑니다. 구조가 단순해서 먼저 익히기 좋습니다.
//   ★★ 실무에서 "무중단 롤백" 이라고 하면 대개 이 링크 교체 방식입니다.

// ★★ 마이그레이션은 안 되돌립니다.
//
//   04단원 개념02, 07단원 개념05 에서 이야기한 것입니다.
//   칸을 지웠다 되살리면 자료가 안 돌아옵니다.
//
//   ★ 그래서 마이그레이션을 **뒤로 호환되게** 만들어야 합니다.
//     새 칸을 추가만 하면, 옛 코드는 그 칸을 모르고 잘 돕니다.
//     그러면 코드만 되돌려도 서비스가 됩니다.
//
//     ✗ 칸 이름 바꾸기      → 옛 코드가 못 찾습니다
//     ○ 새 칸 추가 → 새 코드가 씀 → 한참 뒤 옛 칸 삭제

// ============================================================
// 3. 스크립트를 기계로 검사합니다
// ============================================================
//
// 09단원 배포점검.js 의 항목 중 스크립트 관련 것들을 직접 확인해 봅니다.

function 스크립트검사(내용) {
  const 검사들 = [
    // ★ set -e 와 set -o errexit 는 같은 뜻입니다. 둘 다 봐야 합니다.
    ["set -e", /set\s+-[a-z]*e|set\s+-o\s+errexit/],
    // ★★ pipefail 은 -e 에 안 들어 있습니다. 따로 봅니다.
    ["pipefail", /set\s+-[a-zA-Z]*o\s+pipefail/],
    ["git reset --hard", /git\s+reset\s+--hard/],
    ["npm ci", /npm\s+ci/],
    ["pm2 reload", /pm2\s+reload/],
    // ★ curl 은 -f 와 --fail 이 같습니다. 긴 형식도 봐야 합니다.
    ["health 확인", /curl\s+-[a-zA-Z]*f|curl\s+--fail/],
    ["되돌릴 지점 기억", /rev-parse|이전커밋/],
  ];

  return 검사들.filter(([, 무늬]) => !무늬.test(내용)).map(([이름]) => 이름);
}

console.log("배포.sh 에 빠진 것:", 스크립트검사(배포).join(", ") || "없음");
// 출력: 배포.sh 에 빠진 것: 없음
console.log("되돌리기.sh 에 빠진 것:", 스크립트검사(되돌리기).join(", ") || "없음");
// 출력: 되돌리기.sh 에 빠진 것: 없음

// 나쁜 스크립트와 비교
const 나쁜배포 = [
  "#!/bin/bash",
  "cd /home/ubuntu/앱",
  "git pull",
  "npm install",
  "pm2 restart 앱",
].join("\n");

console.log("나쁜 배포에 빠진 것:", 스크립트검사(나쁜배포).join(", "));
// 출력: 나쁜 배포에 빠진 것: set -e, pipefail, git reset --hard, npm ci, pm2 reload, health 확인, 되돌릴 지점 기억

// ★★ 일곱 개가 다 빠졌습니다. 그런데 이 스크립트도 **동작은 합니다.**
//   평소에는 잘 됩니다. 문제가 생긴 날에 무너집니다.
//
//   그게 이 수업의 방식입니다 — 잘 될 때가 아니라
//   **안 될 때 어떻게 되는가**로 판단합니다.

// ★★★ 검사 항목을 만들 때 조심할 것 세 가지 — 위 코드에 다 들어 있습니다.
//
//   ① **같은 뜻의 다른 형식**을 빠뜨리지 마세요.
//      `set -o errexit` 는 `set -e` 와 완전히 같습니다.
//      정규식을 `/set\s+-[a-z]*e/` 하나로 두면 올바른 스크립트를
//      "set -e 가 없습니다" 로 **막아 버립니다.** 오탐은 도구를 죽입니다.
//      `curl --fail` 과 `curl -f` 도 같은 관계입니다.
//
//   ② **pipefail 을 set -e 에 묻어 두지 마세요.**
//      `set -e` 만 있는 스크립트에서 `curl … | bash -` 는 curl 이 실패해도
//      파이프 전체가 성공으로 끝납니다. 반쯤 받은 것을 그대로 실행합니다.
//      항목을 따로 나눠야 "-e 는 있는데 pipefail 이 없다" 가 보입니다.
//
//   ③ **본문이 가르치는 것과 검사가 어긋나면 안 됩니다.**
//      이 자료는 스물다섯 곳에서 `set -euo pipefail` 을 씁니다.
//      그런데 검사는 `-e` 만 봤습니다. 도구가 자료보다 느슨했던 것입니다.

// ============================================================
// 4. 내 컴퓨터에서 한 줄로
// ============================================================

const package스크립트 = {
  scripts: {
    검증: "node _검증도구/전체검증.js",
    점검: "node 배포/배포점검.js .",
    배포: "npm run 점검 && git push && ssh 설비서버 'bash /home/ubuntu/앱/배포/배포.sh'",
    되돌리기: "ssh 설비서버 'bash /home/ubuntu/앱/배포/되돌리기.sh'",
    로그: "ssh 설비서버 'pm2 logs 설비api --lines 100'",
    상태: "ssh 설비서버 'pm2 list; df -h /; free -h'",
  },
};

for (const [이름, 명령] of Object.entries(package스크립트.scripts)) {
  console.log(`npm run ${이름}`);
}
// 출력: npm run 검증
// 출력: npm run 점검
// 출력: npm run 배포
// 출력: npm run 되돌리기
// 출력: npm run 로그
// 출력: npm run 상태

// ★★ 배포 앞에 점검을 붙였습니다.
//     "npm run 점검 && git push && ssh ..."
//   && 는 앞이 성공해야 뒤가 돕니다. 점검이 막으면 SSH 도 안 갑니다.
//   내 컴퓨터에서 먼저 걸러지니 더 빠릅니다.
//
// ★★★ `git push` 를 가운데 넣은 것이 중요합니다.
//   서버의 배포.sh 는 `git reset --hard origin/main` 을 합니다.
//   **origin** 을 봅니다. 내 컴퓨터의 커밋이 아닙니다.
//   push 를 잊으면 방금 점검한 코드와 배포된 코드가 **다릅니다.**
//   그러고는 "고쳤는데 왜 그대로죠?" 를 한참 찾게 됩니다.
//   사람이 기억할 일이 아니라 별칭이 대신하게 하세요.
//

const fs = require("node:fs");
const path = require("node:path");

// ── 백틱 템플릿 문자열을 찾는 정규식 ──
//
// ★ 정규식을 한 곳에 적고 이름을 붙였습니다.
//   여러 곳에 복사해 두면 한쪽만 고치는 실수가 생깁니다.
const 템플릿찾기 = /`(?:[^`\\]|\\.)*`/g;

// ── 주석과 글자를 걷어 낸 '진짜 코드' ──
//
// _검증도구 들과 같은 함수입니다.
// 설명하려고 주석에 적어 둔 코드를 진짜로 착각하면 안 됩니다.
function 코드만남기기(소스) {
  return 소스
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/.*$/gm, "$1")
    .replace(/"(?:[^"\\]|\\.)*"/g, '""')
    .replace(/'(?:[^'\\]|\\.)*'/g, "''")
    .replace(템플릿찾기, "``");
}

// 주석만 걷어 냅니다. 글자는 남깁니다 (SQL 이 글자 안에 있으니까요).
function 주석만걷기(소스) {
  return 소스.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/.*$/gm, "$1");
}

// ★ 줄번호는 **원본** 기준이어야 합니다.
//   주석을 걷어 낸 소스에서 세면 블록 주석이 접힌 만큼 줄이 밀립니다.
//   원본에서 다시 찾아 세고, 못 찾으면 걷어 낸 쪽 값을 씁니다.
// ★ 검사에서 일부러 빼는 표시입니다. (_검증도구/정합성검사.js 와 같은 규칙)
//
//   교육 자료에는 "이렇게 하면 안 됩니다" 를 보여 주는 코드가 있습니다.
//   그것까지 막으면 도구가 늑대소년이 됩니다. 사람이 도구를 꺼 버립니다.
//
//     const 위험 = `SELECT * FROM 설비 WHERE id = ${입력}`;  // 검증무시: 인젝션 시연
const 무시표시 = /\/\/\s*검증무시/;

// ★ "EXAMPLE 이 들어 있으면 예시겠지" 같은 자동 판단은 **하지 않습니다.**
//
//   그렇게 만들었다가 09단원 개념02 가 깨졌습니다.
//   그 파일은 AKIAIOSFODNN7EXAMPLE 을 **일부러** 두고   // 검증무시: 설명에 적은 예시입니다
//   "도구가 이걸 잡습니다" 를 보여 주는데, 도구가 알아서 봐 줘 버린 겁니다.
//
//   빼려면 사람이 그 줄에 // 검증무시: 라고 적습니다. 그게 분명합니다.
//   표시는 그 줄 끝에 달아도 되고, 바로 윗줄에 달아도 됩니다.
//   (SQL 검사도 같은 규칙입니다)
function 무시할줄인가(줄들, 자리) {
  if (무시표시.test(줄들[자리] ?? "")) return true;
  if (자리 > 0 && 무시표시.test(줄들[자리 - 1] ?? "")) return true;
  return false;
}

function 줄번호(소스, 조각, 원본) {
  if (원본) {
    const 원본자리 = 원본.indexOf(조각);
    if (원본자리 >= 0) return 원본.slice(0, 원본자리).split("\n").length;
  }

  const 자리 = 소스.indexOf(조각);
  if (자리 < 0) return 0;
  return 소스.slice(0, 자리).split("\n").length;
}

function 파일들찾기(뿌리, 확장자 = ".js") {
  const 결과 = [];
  const 건너뛸폴더 = new Set(["node_modules", ".git", "dist", "build", "coverage", "실험용", "data"]);

  function 훑기(폴더) {
    let 목록;
    try {
      목록 = fs.readdirSync(폴더, { withFileTypes: true });
    } catch {
      return;
    }

    for (const 항목 of 목록) {
      if (항목.isDirectory()) {
        if (!건너뛸폴더.has(항목.name)) 훑기(path.join(폴더, 항목.name));
      } else if (항목.name.endsWith(확장자)) {
        결과.push(path.join(폴더, 항목.name));
      }
    }
  }

  훑기(뿌리);
  return 결과;
}

function 읽기(경로) {
  try {
    return fs.readFileSync(경로, "utf-8");
  } catch {
    return null;
  }
}

// SQL 이 든 템플릿만 골라 냅니다
// ★ 그 템플릿이 걸쳐 있는 줄들 안에 // 검증무시: 가 있으면 건너뜁니다.
//   교육 자료의 "일부러 뚫는" 시연을 막지 않기 위한 탈출구입니다.
function 무시대상인가(원본, 조각, 시작줄) {
  const 줄수 = 조각.split("\n").length;
  // ★ 바로 윗줄도 봅니다. 표시는 보통 그 코드 위에 답니다.
  const 처음 = Math.max(0, 시작줄 - 2);
  const 줄들 = 원본.split(/\r?\n/).slice(처음, 시작줄 + 줄수);
  return 줄들.some((줄) => 무시표시.test(줄));
}

function SQL템플릿들(소스) {
  const 주석없이 = 주석만걷기(소스);
  const 원본 = 소스;
  const 전부 = 주석없이.match(템플릿찾기) ?? [];

  const 템플릿결과 = 전부
    .filter((템플릿) => /(SELECT|INSERT|UPDATE|DELETE)\s/i.test(템플릿))
    .filter((템플릿) => /\$\{/.test(템플릿))
    .map((템플릿) => ({ 템플릿, 자리: 줄번호(주석없이, 템플릿, 원본) }));

  // ★ 백틱만 보면 안 됩니다. + 로 이어 붙이는 게 더 흔한 인젝션입니다.
  //
  //     "SELECT * FROM 설비 WHERE id = " + req.query.id
  //
  //   예전에는 이걸 통째로 놓쳤습니다. 가장 고전적인 모양인데도요.
  const 더하기찾기 = /["'][^"'\n]*(SELECT|INSERT|UPDATE|DELETE)[^"'\n]*["']\s*\+/gi;
  const 더하기결과 = (주석없이.match(더하기찾기) ?? []).map((조각) => ({
    템플릿: 조각,
    자리: 줄번호(주석없이, 조각, 원본),
  }));

  return [...템플릿결과, ...더하기결과];
}


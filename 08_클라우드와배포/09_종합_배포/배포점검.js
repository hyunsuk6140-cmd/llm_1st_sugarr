function 점검하기(뿌리) {
  const 결과 = { 막음: [], 경고: [], 참고: [] };

  for (const 항목 of 항목들) {
    let 찾은것;
    try {
      찾은것 = 항목.보기(뿌리);
    } catch (에러) {
      // ★★ 검사기 자신이 터진 것은 **막음** 입니다. 그 항목의 심각도로 낮추면 안 됩니다.
      //
      //   경고·참고 항목이 터지면 종료 코드가 0 이 되어,
      //   set -e 를 건 배포 스크립트가 그대로 배포를 계속합니다.
      //   "검사를 못 했다" 는 "문제가 없다" 가 아닙니다.
      결과.막음.push({
        항목: 항목.이름,
        단원: 항목.단원,
        설명: `점검 중 오류 — 검사를 못 했습니다: ${에러.message}`,
      });
      continue;
    }

    for (const 설명 of 찾은것) {
      결과[항목.심각도].push({ 항목: 항목.이름, 단원: 항목.단원, 설명 });
    }
  }

  return 결과;
}

function 보고서(결과, 뿌리) {
  const 줄들 = [`===== 배포 전 점검: ${뿌리} =====`];

  for (const 심각도 of ["막음", "경고", "참고"]) {
    const 것들 = 결과[심각도];
    if (것들.length === 0) continue;

    줄들.push("");
    줄들.push(`[${심각도}] ${것들.length}건`);
    for (const 것 of 것들) {
      줄들.push(`  · (${것.단원}단원) ${것.항목}`);
      줄들.push(`      ${것.설명}`);
    }
  }

  const 총 = 결과.막음.length + 결과.경고.length + 결과.참고.length;
  줄들.push("");
  줄들.push(
    총 === 0
      ? "===== 걸린 것 없음 ====="
      : `===== 막음 ${결과.막음.length} · 경고 ${결과.경고.length} · 참고 ${결과.참고.length} =====`
  );

  return 줄들.join("\n");
}


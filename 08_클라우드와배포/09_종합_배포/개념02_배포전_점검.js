//
// ★★★ 여기서 배울 것
//
//   도구가 오탐을 내면 **도구를 고칩니다.**
//   결과를 손으로 무시하고 넘어가면 다음에 또 만납니다.
//   그리고 무시하는 습관이 생기면 진짜 문제도 무시하게 됩니다.
//
//   오탐이 많은 도구는 안 쓰게 됩니다. 그게 제일 나쁩니다.


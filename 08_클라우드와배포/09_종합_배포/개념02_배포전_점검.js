// 이 도구를 만들면서 오탐이 두 번 났습니다. 그때마다 도구를 고쳤습니다.
//
// ── 오탐 ① 줄 단위로 봤더니 ──
//
//   db.prepare("INSERT INTO 이력 ... VALUES (?, ?)").run(id, `점검 ${결과}`);
//
//   SQL 은 자리표시자를 제대로 썼습니다. ${결과} 는 **다른** 템플릿입니다.
//   같은 줄에 있다는 이유만으로 "SQL 을 이어 붙였다" 고 잡았습니다.
//
//   → 줄이 아니라 **템플릿 문자열 단위**로 보게 고쳤습니다.
//
// ── 오탐 ② 칸 이름을 이어 붙인 것을 잡았더니 ──
//
//   db.prepare(`UPDATE 설비 SET ${설정} WHERE id = ?`)
//
//   ${설정} 은 허용 목록에서 만든 칸 이름입니다. 값은 ? 로 갑니다.
//   04단원 개념04 에서 "이렇게 하세요" 라고 가르친 그 방식입니다.
//
//   → 값 자리(따옴표 안, = 뒤, VALUES 안) 만 '막음' 으로 잡고,

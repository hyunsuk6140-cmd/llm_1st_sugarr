// ============================================================
// 개념 01 — 표를 나누는 이유
// ============================================================
//
// 02단원에서는 표가 하나였습니다.
// 실제로는 표가 여러 개고, 서로 연결됩니다.
//
// 왜 나눠야 하는지를 먼저 봅니다.
// 안 나누면 뭐가 아픈지 직접 겪어 보는 게 빠릅니다.
//
// 실행: node 개념01_표를_나누기.js
// ============================================================

const { DatabaseSync } = require("node:sqlite");

// ============================================================
// 1. 한 표에 다 넣어 보기
// ============================================================
//
// 설비 목록에 "그 설비가 어느 라인이고, 라인 관리자가 누구인지" 를
// 같이 넣고 싶습니다. 칸을 늘리면 됩니다.

const 한표 = new DatabaseSync(":memory:");
한표.exec(`
  CREATE TABLE 설비 (
    id         INTEGER PRIMARY KEY,
    이름       TEXT NOT NULL,
    라인이름   TEXT NOT NULL,
    라인관리자 TEXT NOT NULL
  ) STRICT
`);

한표.exec(`
  INSERT INTO 설비 (이름, 라인이름, 라인관리자) VALUES
    ('용접로봇 1호', '조립 1라인', '김민준'),
    ('프레스 1호',   '조립 1라인', '김민준'),
    ('프레스 2호',   '조립 2라인', '이서연'),
    ('컨베이어 1호', '조립 2라인', '이서연'),
    ('검사기 1호',   '검사라인',   '박도윤')
`);

console.log(JSON.stringify(
  한표.prepare("SELECT 이름, 라인이름, 라인관리자 FROM 설비").all()
    .map((설비) => `${설비.이름}|${설비.라인이름}|${설비.라인관리자}`)
));
// 출력: ["용접로봇 1호|조립 1라인|김민준","프레스 1호|조립 1라인|김민준","프레스 2호|조립 2라인|이서연","컨베이어 1호|조립 2라인|이서연","검사기 1호|검사라인|박도윤"]

// 잘 돌아갑니다. 조회도 한 번에 됩니다.
// 그런데 문제가 네 가지 있습니다.

// ============================================================
// 2. 문제 ① 같은 값이 반복됩니다
// ============================================================

console.log("'조립 1라인' 이 적힌 줄:", 한표.prepare(`
  SELECT COUNT(*) AS n FROM 설비 WHERE 라인이름 = '조립 1라인'
`).get().n);
// 출력: '조립 1라인' 이 적힌 줄: 2

console.log("'김민준' 이 적힌 줄:", 한표.prepare(`
  SELECT COUNT(*) AS n FROM 설비 WHERE 라인관리자 = '김민준'
`).get().n);
// 출력: '김민준' 이 적힌 줄: 2

// 설비가 500대면 '조립 1라인' 이 200번 적혀 있을 수도 있습니다.
// 저장 공간이 아까운 건 사실 큰 문제가 아닙니다. 다음 게 진짜 문제입니다.

// ============================================================
// 3. 문제 ② 고칠 때 다 고쳐야 합니다
// ============================================================
//
// 조립 1라인의 관리자가 김민준 → 최지우 로 바뀌었습니다.

const 고친것 = 한표.prepare(`
  UPDATE 설비 SET 라인관리자 = ? WHERE 라인이름 = ?
`).run("최지우", "조립 1라인");

console.log("고친 줄 수:", 고친것.changes);
// 출력: 고친 줄 수: 2

// 2줄을 고쳤습니다. 설비가 200대면 200줄을 고쳐야 합니다.
//
// ★★ 여기서 하나라도 빠지면 어떻게 되는지 봅시다.
//   WHERE 조건을 잘못 적어서 한 줄만 고쳤다고 해 봅시다.

한표.prepare("UPDATE 설비 SET 라인관리자 = ? WHERE 이름 = ?").run("한서준", "프레스 1호");

console.log(JSON.stringify(한표.prepare(`
  SELECT DISTINCT 라인이름, 라인관리자 FROM 설비 WHERE 라인이름 = '조립 1라인'
`).all().map((행) => `${행.라인이름}:${행.라인관리자}`)));
// 출력: ["조립 1라인:최지우","조립 1라인:한서준"]

// 같은 라인의 관리자가 두 명이 됐습니다.
// 어느 쪽이 맞는지 DB 만 봐서는 알 수 없습니다.
//
// ★ 이런 상태를 "자료가 어긋났다" 고 합니다.
//   한 번 어긋나면 되돌리기가 아주 어렵습니다.
//   어느 게 맞는 값인지 알아야 하는데, 그걸 아는 사람이 없거든요.

// ============================================================
// 4. 문제 ③ 오타를 막을 방법이 없습니다
// ============================================================

한표.prepare(`
  INSERT INTO 설비 (이름, 라인이름, 라인관리자) VALUES (?, ?, ?)
`).run("포장기 1호", "조립1라인", "이서연"); // ← 공백을 빼먹었습니다

console.log(JSON.stringify(한표.prepare(`
  SELECT DISTINCT 라인이름 FROM 설비 ORDER BY 라인이름
`).all().map((행) => 행.라인이름)));
// 출력: ["검사라인","조립 1라인","조립 2라인","조립1라인"]

// 라인이 4개가 됐습니다. 실제로는 3개인데요.
//
// ★ CHECK 로 막을 수 있지 않나요?
//     CHECK (라인이름 IN ('조립 1라인', '조립 2라인', '검사라인'))
//
//   막을 수는 있습니다. 그런데 라인이 새로 생길 때마다
//   ALTER TABLE 로 CHECK 를 고쳐야 합니다.
//   그런데 SQLite 는 CHECK 를 나중에 고칠 수 없습니다. (02단원 9번)
//   표를 새로 만들어서 자료를 옮겨야 합니다.
//
//   라인 목록은 "자료" 입니다. "규칙" 이 아닙니다.
//   자료는 표에 넣어야 합니다.

// ============================================================
// 5. 문제 ④ 설비가 없는 라인은 표현할 수 없습니다
// ============================================================
//
// 'D 라인' 을 새로 만들었습니다. 아직 설비를 안 넣었습니다.
// 이 표에 어떻게 적을까요?
//
//   INSERT INTO 설비 (이름, 라인이름, ...) VALUES (???, 'D라인', ...)
//
// 설비 이름 자리에 뭘 넣어야 할지 알 수 없습니다.
// 빈 줄을 넣으면 "이름 없는 설비" 가 목록에 나타납니다.
//
// ★ 라인은 설비와 별개로 존재합니다.
//   별개로 존재하는 것은 별개의 표여야 합니다.
//
// ★★ 이게 표를 나누는 기준입니다.
//
//   "이건 그 자체로 존재하는 것인가?"
//
//   라인은 설비가 없어도 존재합니다      → 표
//   회원은 주문이 없어도 존재합니다      → 표
//   주문상세는 주문이 없으면 의미 없습니다 → 주문의 일부지만, 여러 개니까 표
//   설비의 온도는 설비 없이 존재 못 합니다 → 칸

한표.close();

// ============================================================
// 6. 나눠 봅시다
// ============================================================

const db = new DatabaseSync(":memory:");
db.exec("PRAGMA foreign_keys = ON");   // ★ 버전·도구에 따라 기본값이 다릅니다. 직접 켭니다.


db.exec(`
  CREATE TABLE 라인 (
    코드   TEXT PRIMARY KEY,
    이름   TEXT NOT NULL UNIQUE,
    관리자 TEXT
  ) STRICT
`);

db.exec(`
  CREATE TABLE 설비 (
    id       INTEGER PRIMARY KEY,
    이름     TEXT NOT NULL UNIQUE,
    라인코드 TEXT REFERENCES 라인(코드),
    온도     REAL
  ) STRICT
`);

db.exec(`
  INSERT INTO 라인 (코드, 이름, 관리자) VALUES
    ('A', '조립 1라인', '김민준'),
    ('B', '조립 2라인', '이서연'),
    ('C', '검사라인',   NULL),
    ('D', '빈라인',     '박도윤')
`);

db.exec(`
  INSERT INTO 설비 (이름, 라인코드, 온도) VALUES
    ('용접로봇 1호', 'A',  36.5),
    ('프레스 1호',   'A',  41.2),
    ('프레스 2호',   'B',  39.8),
    ('컨베이어 1호', 'B',  25.0),
    ('검사기 1호',   'C',  22.4),
    ('미배치 설비',  NULL, 30.0)
`);

console.log("라인:", db.prepare("SELECT COUNT(*) AS n FROM 라인").get().n);
// 출력: 라인: 4
console.log("설비:", db.prepare("SELECT COUNT(*) AS n FROM 설비").get().n);
// 출력: 설비: 6

// 이제 네 문제가 어떻게 되는지 봅시다.

// ============================================================
// 6-2. 문제 ① ② 해결 — 한 곳만 고치면 됩니다
// ============================================================

const 관리자고침 = db.prepare("UPDATE 라인 SET 관리자 = ? WHERE 코드 = ?").run("최지우", "A");
console.log("고친 줄 수:", 관리자고침.changes);
// 출력: 고친 줄 수: 1

// 설비가 200대든 2만대든 1줄입니다.
// 어긋날 방법이 없습니다. 값이 한 곳에만 있으니까요.

// ============================================================
// 6-3. 문제 ③ 해결 — 없는 라인은 못 넣습니다
// ============================================================

// ★ 먼저 짚을 것 — 나눈 뒤에는 설비가 라인을 **이름이 아니라 코드**로 가리킵니다.
//   라인.코드 는 'A' 'B' 'C' 'D' 이고, 설비.라인코드 에는 그중 하나가 들어갑니다.
//   그래서 '조립 1라인' 이라고 이름을 적으면 공백을 제대로 넣어도 안 들어갑니다.
//
//   막아야 할 오타는 이제 '코드 오타' 입니다. A 를 AA 로 잘못 친 경우입니다.

try {
  db.prepare("INSERT INTO 설비 (이름, 라인코드) VALUES (?, ?)").run("포장기 1호", "AA");
} catch (에러) {
  console.log(에러.message);
  // 출력: FOREIGN KEY constraint failed
}

// 오타가 막혔습니다. REFERENCES 덕분입니다.
//
// ★★ 나누기 전에는 '조립 1라인' 과 '조립1라인' 이 둘 다 그냥 들어갔습니다. (4번)
//   지금은 라인 표에 없는 값을 넣을 방법 자체가 없습니다.
//   "적어 두는 값" 을 "가리키는 값" 으로 바꾼 것이 핵심입니다.
//
// 새 라인이 생기면 라인 표에 한 줄 넣으면 됩니다. 구조를 안 고칩니다.

// ============================================================
// 6-4. 문제 ④ 해결 — 빈 라인이 그냥 있습니다
// ============================================================

console.log(JSON.stringify(db.prepare("SELECT 코드, 이름 FROM 라인 ORDER BY 코드").all()
  .map((라인) => `${라인.코드}:${라인.이름}`)));
// 출력: ["A:조립 1라인","B:조립 2라인","C:검사라인","D:빈라인"]

// D 라인은 설비가 없지만 표에 있습니다. 아무 문제 없습니다.

// ============================================================
// 7. 대신 생기는 불편 — 조회가 두 번이 됩니다
// ============================================================
//
// 나누기 전에는 한 번에 다 나왔습니다.
// 이제는 설비를 읽고, 그 라인을 또 읽어야 합니다.

const 설비 = db.prepare("SELECT 이름, 라인코드 FROM 설비 WHERE id = ?").get(1);
const 라인 = db.prepare("SELECT 이름, 관리자 FROM 라인 WHERE 코드 = ?").get(설비.라인코드);

console.log(`${설비.이름} / ${라인.이름} / ${라인.관리자}`);
// 출력: 용접로봇 1호 / 조립 1라인 / 최지우

// 이 불편을 없애 주는 게 JOIN 입니다. 개념02 에서 합니다.
//
// ★★ 그리고 이 "두 번 조회" 를 목록에서 하면 큰일 납니다.
//   설비 500대를 목록으로 보여 주려고 라인을 500번 조회하는 것 —
//   N+1 문제라고 합니다. 개념05 에서 다룹니다.

// ============================================================
// 8. 외래키 정리
// ============================================================
//
//   부모 표 (라인)        열쇠를 가진 쪽. PRIMARY KEY 가 있는 쪽.
//   자식 표 (설비)        가리키는 쪽. REFERENCES 를 쓴 쪽.
//
//   설비.라인코드  →  라인.코드
//
// ★ 자식 쪽 칸을 NOT NULL 로 할지 정해야 합니다.
//
//     라인코드 TEXT NOT NULL REFERENCES 라인(코드)
//       → 모든 설비는 반드시 라인에 속해야 한다
//
//     라인코드 TEXT REFERENCES 라인(코드)
//       → 라인이 안 정해진 설비가 있을 수 있다 (지금 우리 표)
//
//   '미배치 설비' 를 표현하려면 NULL 을 허용해야 합니다.
//   실제 업무를 보고 정하세요. 대충 정하면 나중에 고치기 아픕니다.

console.log("라인 없는 설비:", db.prepare(`
  SELECT COUNT(*) AS n FROM 설비 WHERE 라인코드 IS NULL
`).get().n);
// 출력: 라인 없는 설비: 1

// ============================================================
// 9. 한 대 여러 개 (1:N) 와 여러 개 여러 개 (N:M)
// ============================================================
//
// 지금까지가 1:N 입니다.
//
//   라인 1개  ↔  설비 여러 개
//   회원 1명  ↔  주문 여러 개
//
// 자식 표에 부모의 열쇠를 넣으면 됩니다. 그게 전부입니다.
//
// ★ N:M 은 다릅니다. 예를 들어 설비와 자격증.
//
//   설비 1대를 다룰 수 있는 자격증이 여러 개
//   자격증 1개로 다룰 수 있는 설비가 여러 대
//
// 이건 어느 쪽에도 넣을 수 없습니다. 표를 하나 더 만듭니다.

db.exec(`
  CREATE TABLE 자격증 (
    코드 TEXT PRIMARY KEY,
    이름 TEXT NOT NULL
  ) STRICT
`);

db.exec(`
  CREATE TABLE 설비_자격증 (
    설비id   INTEGER NOT NULL REFERENCES 설비(id),
    자격증코드 TEXT  NOT NULL REFERENCES 자격증(코드),
    PRIMARY KEY (설비id, 자격증코드)
  ) STRICT
`);

db.exec("INSERT INTO 자격증 VALUES ('WELD', '용접기능사'), ('PRESS', '프레스운전')");
db.exec(`
  INSERT INTO 설비_자격증 VALUES
    (1, 'WELD'), (1, 'PRESS'), (2, 'PRESS')
`);

console.log("이어 준 줄 수:", db.prepare("SELECT COUNT(*) AS n FROM 설비_자격증").get().n);
// 출력: 이어 준 줄 수: 3

// ★ PRIMARY KEY (설비id, 자격증코드) — 두 칸을 묶어서 열쇠로 썼습니다.
//   같은 조합이 두 번 들어가는 걸 막아 줍니다.

try {
  db.prepare("INSERT INTO 설비_자격증 VALUES (?, ?)").run(1, "WELD");
} catch (에러) {
  console.log(에러.message);
  // 출력: UNIQUE constraint failed: 설비_자격증.설비id, 설비_자격증.자격증코드
}

// 이렇게 둘을 이어 주기만 하는 표를 "연결 표" 라고 합니다.
// 학생↔수업, 글↔태그, 회원↔권한 — 전부 이 모양입니다.

// ============================================================
// 10. 어디까지 나눠야 하나
// ============================================================
//
// 나누는 걸 정규화라고 합니다. 이론적으로는 더 깊이 나눌 수 있습니다.
// 하지만 실무 기준은 단순합니다.
//
//   ○ 같은 값이 여러 줄에 반복되고, 그게 바뀔 수 있으면 → 나눕니다
//   ○ 그 자체로 존재하는 것이면 → 나눕니다
//   ✗ 안 바뀌는 값이면 → 안 나눠도 됩니다
//
// ★ 안 나누는 게 맞는 경우도 있습니다.
//
//   주문서에 적힌 "그때의 가격" 은 부품 표를 가리키면 안 됩니다.
//   나중에 부품 가격이 오르면 옛 주문 금액이 같이 바뀌어 버립니다.
//   주문상세 표에 단가를 **복사해서** 넣어야 합니다.
//
//   "그때 그 값" 이 중요한 건 복사합니다. 이건 중복이 아니라 기록입니다.

db.close();

// ============================================================
// 정리
// ============================================================
//
//   한 표에 다 넣으면
//     같은 값이 반복됨 → 고칠 때 다 고쳐야 함 → 하나 빠지면 어긋남
//     오타를 막을 방법이 없음
//     자식이 없는 부모를 표현 못 함

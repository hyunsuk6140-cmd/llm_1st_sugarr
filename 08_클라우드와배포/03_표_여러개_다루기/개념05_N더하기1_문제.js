const { DatabaseSync } = require("node:sqlite");
const fs = require("node:fs");
const path = require("node:path");

const 폴더 = path.join(__dirname, "실험용");
fs.mkdirSync(폴더, { recursive: true });

const db = new DatabaseSync(path.join(폴더, "n1.db"));
db.exec("PRAGMA journal_mode = WAL");
db.exec("DROP TABLE IF EXISTS 점검");
db.exec("DROP TABLE IF EXISTS 설비");

db.exec(`
  CREATE TABLE 설비 (
    id   INTEGER PRIMARY KEY,
    이름 TEXT NOT NULL
  ) STRICT;

  CREATE TABLE 점검 (
    id     INTEGER PRIMARY KEY,
    설비id INTEGER NOT NULL REFERENCES 설비(id),
    결과   TEXT    NOT NULL
  ) STRICT;
`);

// 설비 200대, 각 20건씩 점검 기록
db.exec("BEGIN");
const 설비넣기 = db.prepare("INSERT INTO 설비 (이름) VALUES (?)");
const 점검넣기 = db.prepare("INSERT INTO 점검 (설비id, 결과) VALUES (?, ?)");

for (let i = 1; i <= 200; i++) {
  설비넣기.run(`설비 ${i}호`);
  for (let j = 0; j < 20; j++) {
    점검넣기.run(i, j % 5 === 0 ? "이상" : "정상");
  }
}
db.exec("COMMIT");

db.exec("CREATE INDEX 점검_설비id ON 점검(설비id)"); // ← 색인은 제대로 걸어 뒀습니다


const 설비목록 = db.prepare("SELECT id, 이름 FROM 설비");
const 점검세기 = db.prepare("SELECT COUNT(*) AS n FROM 점검 WHERE 설비id = ?");

function N더하기1() {
  const 설비들 = 설비목록.all(); // ← 조회 1번

  return 설비들.map((설비) => ({
    ...설비,
    점검수: 점검세기.get(설비.id).n, // ← 설비 개수만큼 (200번)
  }));
}


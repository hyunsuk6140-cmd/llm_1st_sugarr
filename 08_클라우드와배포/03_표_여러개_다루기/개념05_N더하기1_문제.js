//   점검 100건이 설비 5대에 걸쳐 있으면 실제로 필요한 이름은 5개입니다.
//   Map 에 담아 두면 조회가 6번으로 줄어듭니다.
//   그래도 JOIN 이 1번이니 JOIN 이 낫습니다.

// ============================================================
// 7. 조회 횟수를 세는 방법
// ============================================================
//
// 눈으로 코드를 봐서는 놓칩니다. 특히 함수가 여러 겹이면요.
// 세어 주는 껍데기를 만들면 됩니다.

let 조회횟수 = 0;

function 세면서(문장) {
  return {
    all: (...값) => { 조회횟수 += 1; return 문장.all(...값); },
    get: (...값) => { 조회횟수 += 1; return 문장.get(...값); },
  };
}

const 센_설비목록 = 세면서(설비목록);
const 센_점검세기 = 세면서(점검세기);

조회횟수 = 0;
센_설비목록.all().map((설비) => 센_점검세기.get(설비.id));
console.log("N+1 방식 조회 횟수:", 조회횟수);
// 출력: N+1 방식 조회 횟수: 201

조회횟수 = 0;
세면서(조인으로).all();
console.log("JOIN 방식 조회 횟수:", 조회횟수);
// 출력: JOIN 방식 조회 횟수: 1

// ★ 04단원에서 저장소(repository) 계층을 만들 때
//   이런 세는 기능을 넣어 두면 개발 중에 바로 알 수 있습니다.
//
//   요청 하나가 끝날 때 "조회 201번" 이라고 로그에 찍히면
//   배포하기 전에 잡힙니다.
//
// ★ 실무 도구들(ORM 의 쿼리 로그, APM) 이 하는 일이 이겁니다.

// ============================================================
// 8. 정리해서 판단하는 순서
// ============================================================
//
//   1) 반복문 안에서 DB 를 부르고 있나?  → 거의 항상 N+1 입니다
//   2) 개수·합계만 필요한가?             → JOIN + 집계 (조회 1번)
//   3) 자식 목록이 필요한가?             → 조회 2번 + Map 으로 합치기
//   4) 목록에 LIMIT 이 있나?             → 그 id 들만 IN 으로
//
// ★★ 조심할 것: 반복문 안의 DB 호출이 항상 나쁜 건 아닙니다.
//
//   3개짜리 목록이면 4번 조회해도 됩니다. 읽기 쉬운 코드가 낫습니다.
//   문제는 **줄 수에 비례해서 늘어나는** 경우입니다.
//   자료가 늘면 같이 느려지니까요.
//
//   "지금 몇 줄인가" 가 아니라 "1년 뒤 몇 줄일까" 로 판단하세요.

db.close();

// ============================================================
// 정리
// ============================================================
//
//   N+1  목록 조회 1번 + 줄마다 조회 1번 = N+1번
//        반복문 안에서 DB 를 부르면 이렇게 됩니다
//
//   로컬 SQLite 에서는 3배쯤이라 잘 안 보입니다.
//   네트워크 건너 DB 에서는 200배가 됩니다. (왕복 3ms × 201번)
//   개발할 때 안 보이고 배포하고 나서 보이는 게 이래서입니다.
//
//   고치는 법
//     개수·합계   → LEFT JOIN + COUNT(자식.id) + GROUP BY
//     자식 목록   → 조회 2번 + Map 으로 묶기 (filter 쓰지 말고)
//     LIMIT 있음  → 그 id 들만 IN (...)
//
//   시간이 아니라 **횟수**를 세세요.
//
// 03단원 끝입니다. 연습문제를 풀어 보세요.
// 04단원에서는 백엔드 07단원의 저장소를 SQL 로 바꿔 끼웁니다.

function 재기(하기, 횟수 = 30) {
  하기(); // 첫 실행은 버립니다 (캐시를 채우려고)

  const 시작 = process.hrtime.bigint();
  for (let i = 0; i < 횟수; i++) 하기();
  return Number(process.hrtime.bigint() - 시작) / 1e6 / 횟수;
}

const n1시간 = 재기(N더하기1);

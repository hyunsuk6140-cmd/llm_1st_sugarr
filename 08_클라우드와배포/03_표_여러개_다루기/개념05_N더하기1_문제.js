// 4. ★★★ 그런데 3배밖에 안 빠릅니다
// ============================================================
//
// 제 컴퓨터에서 0.95ms → 0.30ms 였습니다. 3배입니다.
// 색인이 1810배였던 걸 생각하면 실망스럽습니다.
//
// "그럼 N+1 은 별문제 아니네" 라고 생각하면 안 됩니다.
//
// ★★ SQLite 는 **같은 프로세스 안**에 있습니다.
//   조회 한 번이 그냥 함수 호출입니다. 그래서 201번 해도 1ms 입니다.
//
//   실무의 DB 는 다른 컴퓨터에 있습니다.
//   Supabase(05단원), RDS, 회사 DB 서버 — 전부 네트워크 건너입니다.

console.log(`  N+1 : ${설비수 + 1}번 × ${왕복ms}ms = ${((설비수 + 1) * 왕복ms / 1000).toFixed(2)}초`);
// 출력:   N+1 : 201번 × 3ms = 0.60초
console.log(`  JOIN:   1번 × ${왕복ms}ms = ${(왕복ms / 1000).toFixed(3)}초`);
// 출력:   JOIN:   1번 × 3ms = 0.003초

// ★★★ 0.6초 대 0.003초. **200배**입니다.
//
//   그리고 이건 설비가 200대일 때입니다.
//   2000대가 되면 6초입니다. 사용자는 그냥 나갑니다.
//
// ★★ 여기서 진짜 배울 것:
//
//   **로컬 SQLite 로 테스트하면 N+1 이 안 보입니다.**
//
//   개발할 때는 빠릿합니다. 배포하고 나서 느립니다.
//   자료가 늘어나면 더 느려집니다. 그런데 조회 하나하나는 다 빠릅니다.
//   그래서 원인을 찾기가 어렵습니다.
//
//   조회 **횟수**를 세는 습관을 들이세요. 시간만 보면 안 보입니다.

// ============================================================
// 5. JOIN 을 못 쓸 때 — 두 번 조회하고 합치기
// ============================================================
//
// JOIN 으로 한 번에 안 되는 경우가 있습니다.
//
//   · 자식을 개수가 아니라 **목록으로** 붙여야 할 때
//     (설비마다 점검 기록 20건을 배열로)
//   · 세는 대상이 두 가지 이상일 때 (개념03 의 "부풀어 오름")
//
// 그럴 때는 조회를 2번으로 줄이고 자바스크립트에서 합칩니다.

const 점검전부 = db.prepare("SELECT 설비id, 결과 FROM 점검 ORDER BY id");

function 두번조회() {
  const 설비들 = 설비목록.all(); // 조회 1번
  const 점검들 = 점검전부.all(); // 조회 2번

  // 설비id 별로 묶어 둡니다
  const 묶음 = new Map();
  for (const 점검 of 점검들) {
    if (!묶음.has(점검.설비id)) 묶음.set(점검.설비id, []);
    묶음.get(점검.설비id).push(점검.결과);
  }

  return 설비들.map((설비) => ({
    ...설비,
    점검들: 묶음.get(설비.id) ?? [],
  }));
}

const 결과3 = 두번조회();
console.log(결과3[0].이름, 결과3[0].점검들.length, "건");
// 출력: 설비 1호 20 건
console.log("점검 없는 설비도 빈 배열:", Array.isArray(결과3[0].점검들));
// 출력: 점검 없는 설비도 빈 배열: true

// ★★ 핵심은 Map 입니다.
//
//   ✗  점검들.filter((점검) => 점검.설비id === 설비.id)
//      → 설비마다 4000건을 훑습니다. 200 × 4000 = 80만 번 비교입니다.
//         조회는 2번인데 자바스크립트가 느려집니다. 흔한 함정입니다.
//
//   ○  Map 에 한 번 담아 두고 꺼내 쓴다
//      → 4000번 담고, 200번 꺼냅니다.
//
// ★ ?? [] 를 빼먹지 마세요. 점검이 없는 설비는 Map 에 아예 없습니다.
//   undefined 가 화면으로 나가서 .length 를 부르면 터집니다.

// ============================================================
// 5-2. 필요한 것만 가져오기
// ============================================================
//
// 위 코드는 점검 4000건을 다 가져옵니다. 설비 목록 화면에 그게 필요할까요?
//
// 보통은 "최근 3건" 이나 "개수" 만 보여 줍니다.
// 그러면 IN 으로 범위를 좁힙니다.

// ★★ 아래 ${물음표} 는 이어 붙이는 것 아니냐고요?
//
//   끼워 넣는 것은 "?, ?, ?" 라는 **물음표뿐**입니다. 값은 한 글자도 안 들어갑니다.
//   값은 전부 .all(...설비ids) 로 따로 넘어갑니다.
//   그래서 설비ids 에 "1); DROP TABLE 점검;--" 같은 게 있어도
//   SQL 문장 모양은 그대로고, 그 글자는 그냥 값 하나로 취급됩니다.
//
//   ★ 규칙: 이어 붙여도 되는 것은 **내가 만든 ?** 와 **내가 코드에 적은 이름**뿐입니다.
//     사용자가 보낸 값은 절대 안 됩니다. (02단원 개념03 8번·9-2)

function 필요한것만(설비ids) {
  const 물음표 = 설비ids.map(() => "?").join(", ");

  // 검증무시: 끼워 넣는 것은 ? 뿐입니다
  return db.prepare(`
    SELECT 설비id, COUNT(*) AS 점검수,
           SUM(CASE WHEN 결과 = '이상' THEN 1 ELSE 0 END) AS 이상수
    FROM 점검
    WHERE 설비id IN (${물음표})
    GROUP BY 설비id
  `).all(...설비ids);
}

const 일부 = 필요한것만([1, 2, 3]);
console.log(JSON.stringify(일부.map((행) => `${행.설비id}:${행.점검수}/${행.이상수}`)));
// 출력: ["1:20/4","2:20/4","3:20/4"]

// ★ 화면에 20줄만 보여 준다면 IN 에도 20개만 넣으면 됩니다.
//   목록에 LIMIT 20 을 걸고, 그 20개의 id 로 자식을 가져오는 게 정석입니다.
//
// ★ IN 에 넣을 개수가 수천 개가 되면 그때는 JOIN 이 낫습니다.
//   SQLite 는 자리표시자 개수 한계가 32766 개입니다.

// ============================================================
// 6. 반대 방향 N+1 — 목록이 아닌데도 생깁니다
// ============================================================
//
// 점검 목록에 "그 설비 이름" 을 붙이는 경우입니다.
// 방향이 반대인데 똑같이 N+1 이 됩니다.

const 점검목록 = db.prepare("SELECT id, 설비id, 결과 FROM 점검 LIMIT 100");
const 설비이름 = db.prepare("SELECT 이름 FROM 설비 WHERE id = ?");

function 나쁜방향() {
  return 점검목록.all().map((점검) => ({
    ...점검,
    설비명: 설비이름.get(점검.설비id).이름, // ← 100번
  }));
}

const 나쁜것 = 나쁜방향();
console.log(나쁜것[0].설비명, "/ 조회 횟수:", 나쁜것.length + 1);
// 출력: 설비 1호 / 조회 횟수: 101

// JOIN 으로 바꾸면 1번입니다.

const 좋은방향 = db.prepare(`
  SELECT 점검.id, 점검.설비id, 점검.결과, 설비.이름 AS 설비명
  FROM 점검
  JOIN 설비 ON 점검.설비id = 설비.id
  LIMIT 100
`);

console.log(좋은방향.all()[0].설비명, "/ 조회 횟수: 1");
// 출력: 설비 1호 / 조회 횟수: 1


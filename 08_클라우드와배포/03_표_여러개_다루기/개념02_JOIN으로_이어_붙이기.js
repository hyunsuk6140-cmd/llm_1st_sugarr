const 서브쿼리 = 보기(`
  SELECT 설비.이름 AS 설비명,
         (SELECT COUNT(*) FROM 점검 WHERE 점검.설비id = 설비.id) AS 점검수
  FROM 설비
  ORDER BY 설비.id
`);

console.log(JSON.stringify(서브쿼리.map((행) => `${행.설비명}:${행.점검수}`)));
// 출력: ["용접로봇 1호:2","프레스 1호:2","프레스 2호:1","컨베이어 1호:0","검사기 1호:1","미배치 설비:0"]


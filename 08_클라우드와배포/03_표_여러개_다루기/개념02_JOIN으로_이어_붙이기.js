// 출력: ["프레스 1호","검사기 1호"]

// ★ EXISTS 는 "한 건이라도 있으면" 입니다. 찾자마자 멈춥니다.
//   COUNT(*) > 0 으로 세는 것보다 빠릅니다.
//
// ★ SELECT 1 은 관례입니다. 무슨 칸을 고르든 상관없어서 1 을 씁니다.

// ============================================================
// 9-3. ★★ NOT IN 에 NULL 이 섞이면 아무것도 안 나옵니다
// ============================================================

const 니은db = new DatabaseSync(":memory:");
니은db.exec("CREATE TABLE 가 (값 TEXT) STRICT; CREATE TABLE 나 (값 TEXT) STRICT;");
니은db.exec("INSERT INTO 가 VALUES ('x'), ('y'), ('z')");
니은db.exec("INSERT INTO 나 VALUES ('x'), (NULL)");

console.log("NOT IN:", 니은db.prepare(`
  SELECT COUNT(*) AS n FROM 가 WHERE 값 NOT IN (SELECT 값 FROM 나)
`).get().n);
// 출력: NOT IN: 0

console.log("NOT EXISTS:", 니은db.prepare(`
  SELECT COUNT(*) AS n FROM 가 WHERE NOT EXISTS (SELECT 1 FROM 나 WHERE 나.값 = 가.값)
`).get().n);
// 출력: NOT EXISTS: 2

// ★★★ 답은 2 입니다 ('y', 'z'). NOT IN 은 0 을 줬습니다.
//
//   'y' NOT IN ('x', NULL) 을 풀어 보면
//     'y' <> 'x'   → 참
//     'y' <> NULL  → 모름
//   전부 참이어야 하는데 하나가 "모름" 이라 결과가 "모름" 이 됩니다.
//   모름은 통과 못 합니다.
//
// ★ 이게 아주 찾기 힘든 버그입니다. 오류도 없고, 결과가 0건일 뿐입니다.
//
//   서브쿼리를 쓰는 NOT IN 은 **NOT EXISTS 로 쓰세요.**
//   또는 서브쿼리에 WHERE 값 IS NOT NULL 을 붙이세요.
//
// ★ IN 은 괜찮습니다. NULL 이 있어도 있는 것만 찾아 줍니다.

console.log("IN:", 니은db.prepare(`
  SELECT COUNT(*) AS n FROM 가 WHERE 값 IN (SELECT 값 FROM 나)
`).get().n);
// 출력: IN: 1


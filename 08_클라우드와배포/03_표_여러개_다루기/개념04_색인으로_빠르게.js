// ============================================================
//
// 책 뒤에 있는 '찾아보기' 를 생각하면 됩니다.
//
//   찾아보기 없는 책에서 '트랜잭션' 을 찾으려면 → 1쪽부터 다 넘겨 봅니다
//   찾아보기가 있으면 → ㅌ 을 펴서 "트랜잭션 ... 152쪽" 을 보고 바로 갑니다
//
// 색인은 그 찾아보기입니다.
// 설비id 를 순서대로 정렬해 둔 별도의 표를 만들고,
// 각 값이 원래 표의 몇 번 줄인지 적어 둡니다.
//
// 정렬돼 있으니 이분 탐색이 가능합니다. 20만 줄이라도 18번만 보면 찾습니다.
//
// ★ INTEGER PRIMARY KEY 는 색인이 따로 필요 없습니다.
//   줄 자체가 그 번호 순서로 저장돼 있어서, 번호가 곧 자리입니다.
//   그래서 WHERE id = ? 는 처음부터 빨랐습니다.

console.log(계획("SELECT * FROM 점검 WHERE id = 500"));
// 출력: SEARCH 점검 USING INTEGER PRIMARY KEY (rowid=?)

// ★ 계획에 INDEX 가 아니라 INTEGER PRIMARY KEY 라고 나온 게 그 뜻입니다.
//   따로 만들어 둔 색인을 거치는 게 아니라 표 자체를 바로 찾아갑니다.
//
// ★★ INTEGER 가 아닌 PRIMARY KEY 는 다릅니다.
//   코드 TEXT PRIMARY KEY 처럼 만들면 sqlite_autoindex_... 라는 색인이 진짜로 생깁니다.
//   UNIQUE 를 붙인 칸도 마찬가지로 색인이 자동으로 생깁니다. (02단원의 설비.이름)

// ============================================================
// 6. ★★ 색인이 안 먹는 경우
// ============================================================
//
// 색인을 만들었는데도 SCAN 이 나오는 경우가 있습니다.
// 이걸 모르면 "색인을 만들었는데 왜 안 빨라지지" 로 헤맵니다.

const 경우들 = [
  ["그냥 비교        ", "SELECT * FROM 점검 WHERE 설비id = 1"],
  ["칸에 계산을 붙임  ", "SELECT * FROM 점검 WHERE 설비id + 0 = 1"],
  ["칸에 함수를 씌움  ", "SELECT * FROM 점검 WHERE CAST(설비id AS TEXT) = '1'"],
  ["OR 로 이음       ", "SELECT * FROM 점검 WHERE 설비id = 1 OR 결과 = '이상'"],
  ["색인 없는 칸      ", "SELECT * FROM 점검 WHERE 결과 = '이상'"],
];

for (const [설명, sql] of 경우들) {
  console.log(`${설명} ${계획(sql).startsWith("SEARCH") ? "SEARCH (색인 씀)" : "SCAN (다 훑음)"}`);
}
// 출력: 그냥 비교         SEARCH (색인 씀)
// 출력: 칸에 계산을 붙임   SCAN (다 훑음)
// 출력: 칸에 함수를 씌움   SCAN (다 훑음)
// 출력: OR 로 이음        SCAN (다 훑음)
// 출력: 색인 없는 칸       SCAN (다 훑음)

// ★★ 규칙: **색인 걸린 칸을 그대로 두고 비교**해야 색인을 씁니다.
//
//   ✗  WHERE 설비id + 0 = 1
//   ✗  WHERE CAST(설비id AS TEXT) = '1'
//   ✗  WHERE date(시각) = '2026-01-01'      ← 아주 흔한 실수
//   ○  WHERE 설비id = 1
//   ○  WHERE 시각 >= '2026-01-01' AND 시각 < '2026-01-02'
//
//   칸을 건드리지 말고, 값 쪽을 맞추세요.
//
// ★ OR 은 **양쪽 칸에 색인이 다 있어야** 색인을 씁니다.
//
//   둘 다 있으면 SQLite 가 색인 두 개를 각각 훑고 결과를 합칩니다.
//   실행 계획에 MULTI-INDEX OR 이라고 나옵니다.
//
//     WHERE 설비id = 1 OR 담당자id = 2      ← 둘 다 색인 있음 → 색인 사용
//     WHERE 설비id = 1 OR 메모 = 'x'        ← 메모에 색인 없음 → 전부 훑기
//
//   ★ 한쪽이라도 색인이 없으면 **전체를 훑습니다.** OR 이라서가 아니라,
//     색인 없는 칸을 확인하려면 어차피 모든 줄을 봐야 하기 때문입니다.
//
//   그래서 OR 이 느리면 "OR 이라서" 가 아니라 **어느 칸에 색인이 없는지**를 보세요.


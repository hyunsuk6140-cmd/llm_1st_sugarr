// 출력: 몇 배쯤: 10배 이상

// ★★★ 제 컴퓨터에서는 1810ms → 1ms 였습니다. **1810배**입니다.
//
//   코드를 한 줄도 안 고쳤습니다. CREATE INDEX 한 줄을 실행한 것뿐입니다.

const 등급별 = 여러(`
  SELECT CASE
           WHEN 온도 IS NULL THEN '측정없음'
           WHEN 온도 >= 40   THEN '위험'
           WHEN 온도 >= 30   THEN '주의'
           ELSE                   '정상'
         END AS 등급,
         COUNT(*) AS 대수
  FROM 설비
  GROUP BY 등급
  ORDER BY 대수 DESC, 등급
`);

console.log(JSON.stringify(등급별.map((행) => `${행.등급}:${행.대수}`)));

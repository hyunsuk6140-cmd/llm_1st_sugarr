const { DatabaseSync } = require("node:sqlite");

const db = new DatabaseSync(":memory:");

db.exec(`
  CREATE TABLE 라인 (
    코드 TEXT PRIMARY KEY,
    이름 TEXT NOT NULL
  ) STRICT;

  CREATE TABLE 설비 (
    id       INTEGER PRIMARY KEY,
    이름     TEXT NOT NULL,
    라인코드 TEXT REFERENCES 라인(코드),
    온도     REAL
  ) STRICT;

  CREATE TABLE 점검 (
    id     INTEGER PRIMARY KEY,
    설비id INTEGER NOT NULL REFERENCES 설비(id),
    결과   TEXT NOT NULL CHECK (결과 IN ('정상', '이상')),
    시각   TEXT NOT NULL
  ) STRICT;
`);

db.exec(`
  INSERT INTO 라인 VALUES ('A','조립 1라인'),('B','조립 2라인'),('C','검사라인'),('D','빈라인')
`);
db.exec(`
  INSERT INTO 설비 (이름, 라인코드, 온도) VALUES
    ('용접로봇 1호', 'A',  36.5),
    ('프레스 1호',   'A',  41.2),
    ('프레스 2호',   'B',  39.8),
    ('컨베이어 1호', 'B',  25.0),
    ('검사기 1호',   'C',  22.4),
    ('미배치 설비',  NULL, NULL)
`);
db.exec(`
  INSERT INTO 점검 (설비id, 결과, 시각) VALUES
    (1, '정상', '2026-08-01'), (1, '정상', '2026-08-08'),
    (2, '이상', '2026-08-01'), (2, '정상', '2026-08-08'),
    (3, '정상', '2026-08-01'), (5, '이상', '2026-08-05')
`);

const 하나 = (sql, ...값) => db.prepare(sql).get(...값);
const 여러 = (sql, ...값) => db.prepare(sql).all(...값);

// ============================================================
// 1. 집계 함수 다섯 개
// ============================================================

const 전체 = 하나(`
  SELECT COUNT(*) AS 대수,
         SUM(온도) AS 합,
         AVG(온도) AS 평균,
         MIN(온도) AS 최저,
         MAX(온도) AS 최고
  FROM 설비
`);

console.log(`대수 ${전체.대수} / 합 ${전체.합} / 최저 ${전체.최저} / 최고 ${전체.최고}`);
// 출력: 대수 6 / 합 164.9 / 최저 22.4 / 최고 41.2

console.log("평균 그대로:", 전체.평균);
// 출력: 평균 그대로: 32.980000000000004

// ★★ 32.98 이 아니라 32.980000000000004 입니다.
//
//   REAL 은 실수를 2진수로 저장합니다. 0.1 이나 0.98 은 2진수로 딱 떨어지지 않습니다.
//   그래서 나누기를 하면 아주 작은 오차가 남습니다.
//   자바스크립트의 0.1 + 0.2 !== 0.3 과 **완전히 같은 이유**입니다.
//
//   이 값을 그대로 화면에 보내면 사용자가 32.980000000000004 도를 봅니다.
//
// ★ 그래서 AVG 는 ROUND 로 감싸는 게 기본입니다.

console.log("평균 반올림:", 하나("SELECT ROUND(AVG(온도), 1) AS 평균 FROM 설비").평균);
// 출력: 평균 반올림: 33

// ROUND(값, 1) 은 소수 첫째 자리까지입니다.
// 33.0 이 아니라 33 으로 보이는 건 자바스크립트가 그렇게 찍는 것입니다.
// 화면에 33.0 으로 보이려면 (33).toFixed(1) 을 쓰세요.
//
// ★ 돈을 다룰 때는 REAL 을 아예 쓰지 마세요. (02단원 개념02)
//   INTEGER 에 원 단위로 넣으면 오차가 생길 수 없습니다.
//   합계가 1원씩 안 맞는 사고를 미리 막는 방법입니다.

// ============================================================
// 2. ★★ COUNT(*) 와 COUNT(칸) 은 다릅니다
// ============================================================

const 세기차이 = 하나("SELECT COUNT(*) AS 별표, COUNT(온도) AS 온도칸, COUNT(라인코드) AS 라인칸 FROM 설비");
console.log(세기차이.별표, 세기차이.온도칸, 세기차이.라인칸);
// 출력: 6 5 5

// ★★ COUNT(*)  → 줄 수를 셉니다. 6
//    COUNT(온도) → 온도가 NULL 이 아닌 줄만 셉니다. 5
//
// '미배치 설비' 는 온도와 라인코드가 둘 다 NULL 이라 빠졌습니다.
//
// ★ 이걸 모르면 "왜 개수가 다르지?" 로 한참 헤맵니다.
//   "몇 줄인가" 를 알고 싶으면 COUNT(*) 를 쓰세요.
//   "값이 있는 게 몇 개인가" 를 알고 싶으면 COUNT(칸) 을 쓰세요.

// ============================================================
// 2-2. AVG 와 SUM 도 NULL 을 무시합니다
// ============================================================

console.log("합 / 대수 =", (164.9 / 6).toFixed(2));
// 출력: 합 / 대수 = 27.48
console.log("AVG 결과  =", 하나("SELECT ROUND(AVG(온도), 2) AS 평균 FROM 설비").평균);
// 출력: AVG 결과  = 32.98

// 27.48 이 아니라 32.98 입니다.
// AVG 는 164.9 / 6 이 아니라 **164.9 / 5** 를 계산했습니다.
// NULL 인 줄은 세지도 않습니다.
//
// ★ "NULL 을 0 으로 치고 평균을 내고 싶다" 면 직접 바꿔야 합니다.

console.log("NULL 을 0 으로:", 하나("SELECT ROUND(AVG(COALESCE(온도, 0)), 2) AS 평균 FROM 설비").평균);
// 출력: NULL 을 0 으로: 27.48

// ★★ 어느 쪽이 맞는지는 업무가 정합니다.
//   "온도 센서가 없는 설비" 라면 평균에서 빼는 게 맞습니다 (AVG 그대로).
//   "측정값이 0 이었다" 면 0 으로 치는 게 맞습니다 (COALESCE).
//   대충 넘기면 숫자가 틀립니다.

// ============================================================
// 2-3. 아무것도 안 걸리면
// ============================================================

const 빈것 = 하나("SELECT COUNT(*) AS 개수, SUM(온도) AS 합, AVG(온도) AS 평균 FROM 설비 WHERE 온도 > 1000");
console.log(빈것.개수, 빈것.합, 빈것.평균);
// 출력: 0 null null

// ★★ COUNT 는 0 이지만 SUM 과 AVG 는 **null** 입니다. 0 이 아닙니다.
//
//   const { 합 } = 하나(...);
//   화면에 합.toFixed(2) 를 쓰면 → "Cannot read properties of null"
//
//   합계는 항상 이렇게 받으세요.
//
//     SELECT COALESCE(SUM(온도), 0) AS 합 FROM ...
//
// ★ 매출 합계 API 에서 아주 흔한 500 오류의 원인입니다.
//   그날 주문이 하나도 없으면 null 이 옵니다.

console.log("COALESCE 씌우면:", 하나("SELECT COALESCE(SUM(온도), 0) AS 합 FROM 설비 WHERE 온도 > 1000").합);
// 출력: COALESCE 씌우면: 0

// ============================================================
// 3. GROUP BY — 묶어서 계산하기
// ============================================================

const 라인별 = 여러(`
  SELECT 라인코드, COUNT(*) AS 대수, ROUND(AVG(온도), 1) AS 평균온도
  FROM 설비
  GROUP BY 라인코드
  ORDER BY 라인코드
`);

console.log(JSON.stringify(라인별.map((행) => `${행.라인코드}:${행.대수}대,${행.평균온도}도`)));
// 출력: ["null:1대,null도","A:2대,38.9도","B:2대,32.4도","C:1대,22.4도"]

// GROUP BY 라인코드 → 라인코드가 같은 줄들을 한 덩어리로 묶습니다.
// 덩어리마다 COUNT 와 AVG 를 따로 계산합니다.
//
// ★ NULL 도 하나의 덩어리가 됩니다. 맨 앞에 나옵니다.
//   (개념02 의 "= NULL 은 안 된다" 와 다릅니다. GROUP BY 는 NULL 끼리 묶습니다)

// ============================================================
// 3-2. SELECT 에 뭘 적을 수 있나
// ============================================================
//
// GROUP BY 를 쓰면 SELECT 에 적을 수 있는 게 제한됩니다.
//
//   ○ GROUP BY 에 적은 칸
//   ○ 집계 함수 (COUNT, SUM, ...)
//   ✗ 그 밖의 칸
//
// 그런데 SQLite 는 막지 않습니다. 이게 함정입니다.

const 위험한것 = 여러(`
  SELECT 라인코드, 이름, COUNT(*) AS 대수
  FROM 설비
  GROUP BY 라인코드
  ORDER BY 라인코드
`);

console.log(JSON.stringify(위험한것.map((행) => `${행.라인코드}:${행.이름}(${행.대수})`)));
// 출력: ["null:미배치 설비(1)","A:용접로봇 1호(2)","B:프레스 2호(2)","C:검사기 1호(1)"]

// ★★★ A 라인에는 설비가 2대인데 이름은 '용접로봇 1호' 하나만 나왔습니다.
//
//   "2대 중 아무거나 한 대" 를 골라 준 것입니다.
//   어느 걸 골라 줄지는 보장되지 않습니다. SQLite 버전이 바뀌면 달라질 수 있습니다.
//
// ★★ Postgres·MySQL(기본 설정) 은 이걸 **오류로 막습니다.**
//
//     ERROR: column "설비.이름" must appear in the GROUP BY clause
//
//   SQLite 에서 잘 돌던 코드가 Supabase 로 옮기면 터집니다. (05단원)
//   처음부터 안 쓰는 습관을 들이세요.
//
// ★ 이름들을 다 보고 싶으면 group_concat 을 쓰세요.

const 이름모으기 = 여러(`
  SELECT 라인코드, COUNT(*) AS 대수, group_concat(이름, ' / ') AS 설비들
  FROM 설비
  WHERE 라인코드 IS NOT NULL
  GROUP BY 라인코드
  ORDER BY 라인코드
`);

console.log(JSON.stringify(이름모으기.map((행) => `${행.라인코드}: ${행.설비들}`)));
// 출력: ["A: 용접로봇 1호 / 프레스 1호","B: 프레스 2호 / 컨베이어 1호","C: 검사기 1호"]

// ★ group_concat(칸, 구분자) — 구분자를 안 주면 쉼표입니다.
//   Postgres 에서는 string_agg 라고 부릅니다. 이름이 다릅니다.

// ============================================================
// 4. HAVING — 묶은 뒤에 걸러내기
// ============================================================

const 두대이상 = 여러(`
  SELECT 라인코드, COUNT(*) AS 대수
  FROM 설비
  GROUP BY 라인코드
  HAVING COUNT(*) >= 2
  ORDER BY 라인코드
`);

console.log(JSON.stringify(두대이상.map((행) => `${행.라인코드}:${행.대수}`)));
// 출력: ["A:2","B:2"]

// ★★ WHERE 와 HAVING 의 차이
//
//   WHERE   묶기 **전에** 줄을 고릅니다.  → 집계 함수를 쓸 수 없습니다
//   HAVING  묶은 **뒤에** 덩어리를 고릅니다. → 집계 함수를 쓸 수 있습니다
//
// 순서를 기억하면 헷갈리지 않습니다.
//
//   FROM → WHERE → GROUP BY → HAVING → SELECT → ORDER BY → LIMIT
//
// WHERE 에 COUNT(*) 를 쓰면 오류가 납니다.

try {
  여러("SELECT 라인코드 FROM 설비 WHERE COUNT(*) >= 2 GROUP BY 라인코드");
} catch (에러) {
  console.log(에러.message);
  // 출력: misuse of aggregate: COUNT()
}

// ★ 둘을 같이 쓰는 게 흔합니다.

const 섞어서 = 여러(`
  SELECT 라인코드, COUNT(*) AS 대수
  FROM 설비
  WHERE 온도 IS NOT NULL          -- 묶기 전: 온도 없는 설비 제외
  GROUP BY 라인코드
  HAVING AVG(온도) > 30           -- 묶은 뒤: 평균 30도 넘는 라인만
  ORDER BY 라인코드
`);

console.log(JSON.stringify(섞어서.map((행) => `${행.라인코드}:${행.대수}`)));
// 출력: ["A:2","B:2"]

// ★ -- 는 SQL 의 한 줄 주석입니다. // 가 아닙니다.

// ============================================================
// 5. JOIN 과 집계를 같이 — 여기가 제일 많이 틀립니다
// ============================================================

const 잘못센것 = 여러(`
  SELECT 라인.코드, COUNT(*) AS 대수
  FROM 라인
  LEFT JOIN 설비 ON 라인.코드 = 설비.라인코드
  GROUP BY 라인.코드
  ORDER BY 라인.코드
`);

console.log("COUNT(*):", JSON.stringify(잘못센것.map((행) => `${행.코드}:${행.대수}`)));
// 출력: COUNT(*): ["A:2","B:2","C:1","D:1"]

const 제대로센것 = 여러(`
  SELECT 라인.코드, COUNT(설비.id) AS 대수
  FROM 라인
  LEFT JOIN 설비 ON 라인.코드 = 설비.라인코드
  GROUP BY 라인.코드
  ORDER BY 라인.코드
`);

console.log("COUNT(설비.id):", JSON.stringify(제대로센것.map((행) => `${행.코드}:${행.대수}`)));
// 출력: COUNT(설비.id): ["A:2","B:2","C:1","D:0"]

// ★★★ D 라인이 1 과 0 으로 다르게 나왔습니다. 정답은 0 입니다.
//
//   LEFT JOIN 은 짝이 없어도 줄을 하나 만듭니다. 설비 칸이 다 NULL 인 줄입니다.
//   COUNT(*) 는 그 줄도 "한 줄" 로 세서 1 이 됩니다.
//   COUNT(설비.id) 는 NULL 을 안 세니까 0 이 됩니다.
//
// ★★ 규칙: LEFT JOIN 뒤에 세려면 **오른쪽 표의 칸**을 세세요.
//
//     ✗  COUNT(*)
//     ○  COUNT(설비.id)
//
//   "주문이 0건인 회원" 이 1건으로 보이는 버그가 정확히 이겁니다.

// ============================================================
// 5-2. 두 가지를 한꺼번에 세면 부풀어 오릅니다
// ============================================================
//
// 설비별로 "점검 횟수" 와 "이상 횟수" 를 같이 보고 싶습니다.

const 부푼것 = 여러(`
  SELECT 설비.이름, COUNT(점검.id) AS 점검수
  FROM 설비
  LEFT JOIN 점검 ON 설비.id = 점검.설비id
  GROUP BY 설비.id
  ORDER BY 설비.id
`);

console.log(JSON.stringify(부푼것.map((행) => `${행.이름}:${행.점검수}`)));
// 출력: ["용접로봇 1호:2","프레스 1호:2","프레스 2호:1","컨베이어 1호:0","검사기 1호:1","미배치 설비:0"]

// 여기까지는 맞습니다. 그런데 표를 하나 더 붙이면 문제가 생깁니다.
// (자격증 표를 붙여서 "점검수 와 자격증수" 를 같이 세면
//  점검 2건 × 자격증 3개 = 6줄이 되어 둘 다 6 으로 나옵니다)
//
// ★ 해결은 DISTINCT 를 쓰거나, 서브쿼리로 각각 세는 것입니다.

const 각각세기 = 여러(`
  SELECT 설비.이름,
         (SELECT COUNT(*) FROM 점검 WHERE 점검.설비id = 설비.id) AS 점검수,
         (SELECT COUNT(*) FROM 점검 WHERE 점검.설비id = 설비.id AND 결과 = '이상') AS 이상수
  FROM 설비
  ORDER BY 설비.id
`);

console.log(JSON.stringify(각각세기.map((행) => `${행.이름}:${행.점검수}/${행.이상수}`)));
// 출력: ["용접로봇 1호:2/0","프레스 1호:2/1","프레스 2호:1/0","컨베이어 1호:0/0","검사기 1호:1/1","미배치 설비:0/0"]

// 각 서브쿼리가 자기 것만 세니까 부풀지 않습니다.

// ============================================================
// 6. 조건부로 세기 — CASE
// ============================================================
//
// 서브쿼리를 여러 개 쓰는 대신 한 번의 스캔으로 끝낼 수도 있습니다.

const 조건부 = 하나(`
  SELECT COUNT(*) AS 전체,
         SUM(CASE WHEN 결과 = '이상' THEN 1 ELSE 0 END) AS 이상건수,
         SUM(CASE WHEN 결과 = '정상' THEN 1 ELSE 0 END) AS 정상건수
  FROM 점검
`);

console.log(`전체 ${조건부.전체} / 이상 ${조건부.이상건수} / 정상 ${조건부.정상건수}`);
// 출력: 전체 6 / 이상 2 / 정상 4

// ★ CASE WHEN 조건 THEN 값 ELSE 값 END — 자바스크립트의 삼항 연산자와 같습니다.
//   조건에 맞으면 1, 아니면 0 을 만들고 다 더하면 개수가 됩니다.

//   SUM · AVG     NULL 을 무시합니다. 아무것도 없으면 결과가 null
//                 → COALESCE(SUM(...), 0) 으로 감싸세요
//   ROUND(값, 1)  소수점 자르기
//
//   GROUP BY      묶어서 계산

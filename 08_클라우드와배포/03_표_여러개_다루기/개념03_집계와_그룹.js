// 8. 순위 매기기 — 창 함수
// ============================================================
//
// "라인별로 가장 뜨거운 설비" 를 찾고 싶습니다.
//
// ★ SQLite 에서는 MAX(온도) 옆에 이름을 같이 적으면 **그 줄의 이름이 나옵니다.**
//
//     SELECT 라인코드, 이름, MAX(온도) FROM 설비 GROUP BY 라인코드
//     → A | 프레스 1호 | 41.2      ← 온도가 41.2 인 그 줄의 이름
//
//   min()/max() 를 쓸 때만 SQLite 가 특별히 봐 주는 규칙입니다.
//
// ★★ 그런데 이걸 쓰지 마세요. **SQLite 에서만 됩니다.**
//   Postgres·MySQL 에서는 오류가 나거나 엉뚱한 줄의 이름이 나옵니다.
//   05단원에서 Supabase(Postgres) 로 옮기면 바로 깨집니다.
//
//   그래서 어디서나 되는 방법을 씁니다. 창 함수입니다.

const 순위 = 여러(`
  SELECT 라인코드, 이름, 온도, 순번
  FROM (
    SELECT 라인코드, 이름, 온도,
           ROW_NUMBER() OVER (PARTITION BY 라인코드 ORDER BY 온도 DESC) AS 순번
    FROM 설비
    WHERE 라인코드 IS NOT NULL
  )
  WHERE 순번 = 1
  ORDER BY 라인코드
`);

console.log(JSON.stringify(순위.map((행) => `${행.라인코드}:${행.이름}(${행.온도})`)));
// 출력: ["A:프레스 1호(41.2)","B:프레스 2호(39.8)","C:검사기 1호(22.4)"]

// ★ ROW_NUMBER() OVER (PARTITION BY 묶을칸 ORDER BY 정렬칸)
//     묶음 안에서 순서대로 1, 2, 3... 번호를 붙입니다.
//   그걸 감싸서 순번 = 1 만 고르면 "묶음별 1등" 이 됩니다.
//
// ★ 창 함수는 집계와 달리 줄을 줄이지 않습니다. 칸을 하나 더 붙일 뿐입니다.
//
// ★ 처음에는 어렵게 느껴집니다. 필요할 때 찾아 쓰면 됩니다.
//   "묶음별 1등", "누적 합계", "이전 줄과의 차이" 가 필요하면 창 함수입니다.
//   SQLite 3.25(2018) 부터, Postgres·MySQL 8 에도 다 있습니다.

// ============================================================
// 9. 서버에서 쓰는 모양
// ============================================================
//
// 통계 API 는 이런 식으로 만듭니다.

function 라인별통계() {
  return db.prepare(`
    SELECT 라인.코드,
           라인.이름,
           COUNT(설비.id)                            AS 설비수,
           COALESCE(ROUND(AVG(설비.온도), 1), 0)      AS 평균온도,
           COALESCE(MAX(설비.온도), 0)                AS 최고온도
    FROM 라인
    LEFT JOIN 설비 ON 라인.코드 = 설비.라인코드
    GROUP BY 라인.코드
    ORDER BY 라인.코드
  `).all();
}

const 통계 = 라인별통계();
console.log(JSON.stringify(통계.map((행) => `${행.이름}:${행.설비수}대,평균${행.평균온도}`)));
// 출력: ["조립 1라인:2대,평균38.9","조립 2라인:2대,평균32.4","검사라인:1대,평균22.4","빈라인:0대,평균0"]

// 빈라인이 0대 / 평균 0 으로 제대로 나왔습니다. 세 가지를 다 챙겼습니다.
//
//   LEFT JOIN         설비 없는 라인도 남기기
//   COUNT(설비.id)    NULL 줄을 세지 않기
//   COALESCE(..., 0)  AVG 가 null 일 때 0 으로
//
// ★ 이 세 개를 빼먹으면 각각
//   "빈라인이 안 보임", "빈라인이 1대로 보임", "평균이 null 로 나가서 화면이 깨짐"
//   이 됩니다. 다 실제로 겪는 일입니다.

db.close();


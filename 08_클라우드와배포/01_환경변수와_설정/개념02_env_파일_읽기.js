// ============================================================
// 01단원 · 개념 02 — .env 파일 읽기
// ------------------------------------------------------------
// 실행: node 개념02_env_파일_읽기.js
// ============================================================
//
// 개념01 에서 환경변수를 명령 앞에 붙여 봤습니다.
//
//   PORT=4000 node server.js
//
// 그런데 값이 열 개면 어떻게 할까요?
//
//   PORT=4000 NODE_ENV=development DB_FILE=./data.db CORS_ORIGINS=... node server.js
//
// 매번 이걸 칠 수는 없습니다. 그래서 파일에 적어 둡니다. `.env` 입니다.

const path = require("path");

const 이폴더 = __dirname;


// ── 섹션 1: .env 파일 모양 ──

// 옆의 .env 파일을 열어 보세요. 이렇게 생겼습니다.
//
//   # 주석은 # 로
//   PORT=3000
//   NODE_ENV=development
//   DB_FILE=./data/설비.db
//   CORS_ORIGINS=http://localhost:5173,http://localhost:5500
//
// 규칙
//   · 한 줄에 하나
//   · 이름=값   (등호 앞뒤 공백은 있어도 됩니다)
//   · 이름은 대문자와 밑줄
//   · 따옴표는 없어도 됩니다


// ── 섹션 2: Node 가 직접 읽어 줍니다 ──

// Node 가 .env 를 직접 읽어 주는 기능이 있습니다. 패키지가 필요 없습니다.
//
//   방법 ①  node --env-file=.env server.js     ← Node 20.6 이상
//   방법 ②  process.loadEnvFile(".env")        ← 코드 안에서. Node 20.12 / 21.7 이상
//
// ★ 두 방법이 들어온 버전이 다릅니다. ②가 조금 늦게 들어왔습니다.
//   ②에서 "process.loadEnvFile is not a function" 이 나오면 Node 를 올리세요.
//
// ①은 서버를 켤 때 붙입니다. package.json 의 scripts 에 적어 두면 편합니다.
//
//   "scripts": { "dev": "node --env-file=.env server.js" }

// 여기서는 ②로 읽어 봅니다.
process.loadEnvFile(path.join(이폴더, ".env"));

console.log(process.env.PORT);
// 출력: 3000
console.log(process.env.NODE_ENV);
// 출력: development
console.log(process.env.DB_FILE);
// 출력: ./data/설비.db
console.log(process.env.CORS_ORIGINS);
// 출력: http://localhost:5173,http://localhost:5500

// ★ 값은 여전히 전부 글자입니다. 파일에서 읽어도 마찬가지입니다.
console.log(typeof process.env.PORT);
// 출력: string


// ── 섹션 3: ★★ 이미 있는 값은 안 덮어씁니다 ──

// 직접 재 본 결과입니다.
//
//   PORT=9999 node 파일.js
//   그 안에서 process.loadEnvFile(".env")   (.env 에는 PORT=3000)
//
//   결과:  9999
//
// .env 가 이기지 않습니다. 명령줄이 이깁니다.

const 우선순위 = [
  "① 명령 앞에 붙인 값        PORT=9999 node ...",
  "② 서버·PM2·Docker 설정      (실제 배포에서 씁니다)",
  "③ .env 파일",
  "④ 코드의 기본값             process.env.PORT || 3000",
];

우선순위.forEach((줄) => console.log(줄));
// 출력: ① 명령 앞에 붙인 값        PORT=9999 node ...
// 출력: ② 서버·PM2·Docker 설정      (실제 배포에서 씁니다)
// 출력: ③ .env 파일
// 출력: ④ 코드의 기본값             process.env.PORT || 3000

// ★★ 이 순서가 아주 중요합니다.
//
//   배포 서버에 .env 파일을 안 두고 ②로 설정해 두면,
//   실수로 .env 가 올라가도 서버 설정이 이깁니다.
//
//   그리고 잠깐 다른 포트로 띄워 보고 싶을 때
//   .env 를 안 고치고 ①로 덮어쓸 수 있습니다.
//
// ★ 이 성질 때문에 헷갈리는 경우
//   "\.env 를 고쳤는데 왜 안 바뀌지?"
//   → 터미널에 그 값이 이미 설정돼 있는 것입니다.
//     PowerShell 에서 $env:PORT 를 한 번 정하면 그 창이 닫힐 때까지 남습니다.


// ── 섹션 4: 값 쓰는 법 (실제로 재 봤습니다) ──

// .env.시험 이라는 파일에 이렇게 적고 읽어 봤습니다.
//
//   QUOTE_TEST="큰따옴표 안"     →  큰따옴표 안        (따옴표는 벗겨집니다)
//   SPACE_TEST = 앞뒤공백        →  앞뒤공백           (등호 앞뒤 공백은 지워집니다)
//   HASH_TEST=값 # 이건 주석인가  →  값                 (# 뒤는 잘립니다)
//   EQ_TEST=a=b=c               →  a=b=c              (첫 = 만 구분자)
//   EMPTY_TEST=                 →  ""                 (빈 글자)

const 형식규칙 = {
  '값에 공백이 있으면': '따옴표로 감싸세요.  이름="앞 뒤 공백"',
  "값에 # 이 들어가면": "따옴표로 감싸세요. 안 그러면 그 뒤가 잘립니다",
  "값에 = 이 들어가면": "그대로 써도 됩니다. 첫 = 만 구분자입니다",
  "값을 비우면": "빈 글자가 됩니다. undefined 가 아닙니다",
  "줄바꿈이 필요하면": '따옴표 안에 \\n 을 쓰거나, 값을 한 줄로 만드세요',
};

for (const 경우 of Object.keys(형식규칙)) {
  console.log(`${경우} → ${형식규칙[경우]}`);
}
// 출력: 값에 공백이 있으면 → 따옴표로 감싸세요.  이름="앞 뒤 공백"
// 출력: 값에 # 이 들어가면 → 따옴표로 감싸세요. 안 그러면 그 뒤가 잘립니다
// 출력: 값에 = 이 들어가면 → 그대로 써도 됩니다. 첫 = 만 구분자입니다
// 출력: 값을 비우면 → 빈 글자가 됩니다. undefined 가 아닙니다
// 출력: 줄바꿈이 필요하면 → 따옴표 안에 \n 을 쓰거나, 값을 한 줄로 만드세요

// ★★ '# 뒤가 잘린다' 를 조심하세요.
//   비밀번호에 # 이 들어가는 경우가 흔합니다.
//
//     ADMIN_KEY=a1b2#c3d4      →  "a1b2" 만 들어갑니다
//     ADMIN_KEY="a1b2#c3d4"    →  제대로 들어갑니다
//
//   그리고 에러가 안 납니다. 그냥 로그인이 안 될 뿐입니다.
//   비밀번호는 따옴표로 감싸는 습관을 들이세요.


// ── 섹션 5: dotenv 패키지 ──

// Node 에 기능이 들어오기 전에는 dotenv 라는 패키지를 썼습니다.
// 지금도 대부분의 프로젝트가 이걸 씁니다.

require("dotenv").config({ path: path.join(이폴더, ".env"), quiet: true });

console.log(process.env.PORT);
// 출력: 3000

// ★ 결과는 같습니다. 무엇을 쓸까요?
const 비교 = {
  "Node 내장 (--env-file / loadEnvFile)": "설치가 필요 없습니다. --env-file 은 20.6, loadEnvFile 은 20.12 이상",
  "dotenv 패키지": "옛날 Node 에서도 됩니다. 자료·블로그가 전부 이걸 씁니다",
  결론: "새로 시작하면 내장을 쓰세요. 남의 코드에서 dotenv 를 보면 같은 것이라고 알면 됩니다",
};

for (const 것 of Object.keys(비교)) {
  console.log(`${것}: ${비교[것]}`);
}
// 출력: Node 내장 (--env-file / loadEnvFile): 설치가 필요 없습니다. --env-file 은 20.6, loadEnvFile 은 20.12 이상
// 출력: dotenv 패키지: 옛날 Node 에서도 됩니다. 자료·블로그가 전부 이걸 씁니다
// 출력: 결론: 새로 시작하면 내장을 쓰세요. 남의 코드에서 dotenv 를 보면 같은 것이라고 알면 됩니다

// ★ dotenv 도 '이미 있는 값은 안 덮어쓴다' 가 기본입니다.
//   덮어쓰려면 config({ override: true }) 를 줘야 합니다.


// ── 섹션 6: .env · .env.예시 · .gitignore ──

// 이 폴더에 세 파일이 있습니다. 각각 역할이 다릅니다.

const 세파일 = {
  ".env": "진짜 값. ★ Git 에 올리지 않습니다",
  ".env.예시": "무엇이 필요한지만. 진짜 값은 없습니다. Git 에 올립니다",
  ".gitignore": ".env* 를 올리지 말라고 Git 에 알려 줍니다",
};

for (const 파일 of Object.keys(세파일)) {
  console.log(`${파일} — ${세파일[파일]}`);
}
// 출력: .env — 진짜 값. ★ Git 에 올리지 않습니다
// 출력: .env.예시 — 무엇이 필요한지만. 진짜 값은 없습니다. Git 에 올립니다
// 출력: .gitignore — .env* 를 올리지 말라고 Git 에 알려 줍니다

// ★★ .env.예시 가 왜 필요한가
//
//   .env 를 안 올리니까, 새로 온 사람은 무엇이 필요한지 모릅니다.
//   서버를 켜면 undefined 때문에 이상한 데서 터집니다.
//
//   .env.예시 를 올려 두면 이렇게 시작할 수 있습니다.
//     cp .env.예시 .env
//   그리고 진짜 값만 채우면 됩니다.
//
//   이름은 .env.example 을 많이 씁니다. 이 자료는 읽기 쉽게 한글로 했습니다.
//
// ★★★ .gitignore 는 '처음에' 만드세요.
//   나중에 넣으면 이미 올라간 뒤입니다.
//   Git 은 한 번 추적하기 시작한 파일은 .gitignore 를 무시합니다.
//
//   이미 올렸다면 이렇게 뺍니다.
//     git rm --cached .env
//     git commit -m "환경 파일 제외"
//
//   ★ 그래도 '기록' 에는 남아 있습니다.
//     그 비밀번호는 이미 새어 나간 것으로 보고 바꿔야 합니다.



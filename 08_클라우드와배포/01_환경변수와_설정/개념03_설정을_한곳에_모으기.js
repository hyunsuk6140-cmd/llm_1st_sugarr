function 켜보기(환경) {
  return cp.spawnSync("node", ["-e", `const 설정 = require(process.argv[1]); console.log("켜짐:" + 설정.포트)`, 설정파일], {
    encoding: "utf8",
    env: { PATH: process.env.PATH, ENV_FILE: "없는파일.env", ...환경 },
  });
}


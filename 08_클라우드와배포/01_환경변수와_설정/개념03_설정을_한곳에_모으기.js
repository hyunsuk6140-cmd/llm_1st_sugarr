// ── 섹션 5: 비밀은 가려서 찍습니다 ──

function 가리기(값) {
  if (!값) return "(없음)";
  if (값.length <= 4) return "****";

  // 앞 두 글자와 뒤 두 글자만 보여 줍니다.
  return 값.slice(0, 2) + "*".repeat(값.length - 4) + 값.slice(-2);
}

function 설정찍기(설정) {
  return {
    환경: 설정.환경,
    포트: 설정.포트,
    DB파일: 설정.DB파일,
    허용출처들: 설정.허용출처들.join(", "),
    최대업로드: `${Math.round(설정.최대업로드 / 1024 / 1024)}MB`,
    관리자키: 가리기(설정.관리자키), // ★ 가려서
  };
}


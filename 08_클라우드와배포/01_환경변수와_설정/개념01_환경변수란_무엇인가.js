// ── 섹션 1: process.env 는 무엇인가 ──

// 운영체제가 프로그램에게 건네주는 '설정 쪽지' 입니다.
// 프로그램을 켤 때 붙여 주면, 프로그램 안에서 읽을 수 있습니다.

console.log(typeof process.env);
// 출력: object

console.log(typeof process.env.PATH);
// 출력: string

// ★ PATH 는 우리가 안 넣었는데 있습니다.
//   운영체제가 원래부터 갖고 있는 것들입니다.
//   `node` 라고만 쳐도 실행되는 이유가 PATH 에 node 위치가 적혀 있어서입니다.


// ── 섹션 2: ★ 값은 언제나 글자입니다 ──

process.env.TEST_NUMBER = 3000;
process.env.TEST_TRUE = true;

// ★ 시험용 변수도 이름을 영문 대문자와 밑줄로 지었습니다.
//   환경변수 이름에 한글을 쓰면 운영체제에 따라 안 됩니다. (아래 [실수 6])
//   가르치는 것과 코드가 다르면 안 되니 여기서도 지킵니다.

console.log(typeof process.env.TEST_NUMBER, process.env.TEST_NUMBER);
// 출력: string 3000
console.log(typeof process.env.TEST_TRUE, process.env.TEST_TRUE);
// 출력: string true

// ★★ 숫자를 넣었는데 글자로 바뀌었습니다.
//
//   환경변수는 운영체제가 주는 '글자' 입니다. 타입이라는 게 없습니다.
//   그래서 이런 사고가 납니다.
//
//     const PORT = process.env.PORT || 3000;
//     const 다음포트 = PORT + 1;      →  "3000" + 1  →  "30001"
//
//   백엔드자료 08단원에서 실제로 이 실수를 했고 서버가 안 켜졌습니다.
//   포트 번호가 "34504100" 이 됐습니다.
//
// ★ 반드시 바꿔서 쓰세요.
console.log(Number(process.env.TEST_NUMBER) + 1);
// 출력: 3001

// true/false 는 더 조심해야 합니다.
console.log(Boolean(process.env.TEST_FALSE ?? "false"));
// 출력: true

// ★★★ "false" 라는 글자는 Boolean 으로 바꾸면 true 입니다.
//   빈 글자가 아니면 전부 true 이기 때문입니다.
//
//     DEBUG=false 라고 적어 뒀는데 디버그가 켜집니다.
//     원인을 찾기 아주 어렵습니다.
//
//   이렇게 비교하세요.
console.log(process.env.TEST_FALSE === "true");
// 출력: false

process.env.TEST_ON = "true";
console.log(process.env.TEST_ON === "true");
// 출력: true


// ── 섹션 3: 없는 값을 읽으면 ──

console.log(process.env.NO_SUCH_VAR);
// 출력: undefined

// ★ null 이 아니라 undefined 입니다.
//   그래서 || 나 ?? 로 기본값을 줄 수 있습니다.

console.log(process.env.NO_SUCH_VAR || "기본값");
// 출력: 기본값
console.log(process.env.NO_SUCH_VAR ?? "기본값");
// 출력: 기본값

// ★★ || 와 ?? 의 차이가 여기서 중요합니다.
process.env.EMPTY_VALUE = "";

console.log(process.env.EMPTY_VALUE || "기본값");
// 출력: 기본값
console.log(process.env.EMPTY_VALUE ?? "기본값");
// 출력:

// ★ 빈 글자일 때 다릅니다.
//   ||  빈 글자를 '없는 것' 으로 보고 기본값을 씁니다
//   ??  빈 글자도 '값' 으로 보고 그대로 씁니다
//
//   .env 에 `ADMIN_KEY=` 라고 값 없이 적어 두면 빈 글자가 됩니다.
//   그때 || 를 쓰면 기본값으로 넘어가고, ?? 를 쓰면 빈 증표로 서버가 돕니다.
//
//   환경변수에는 보통 || 가 낫습니다. "값이 비어 있으면 없는 것" 이 자연스럽습니다.



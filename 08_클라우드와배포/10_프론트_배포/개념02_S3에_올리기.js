// 3. ★★ 올라갔는데 화면이 안 나옵니다
// ============================================================

function 열어보기(s3, 제목) {
  console.log(`\n=== ${제목} ===\n`);

  const 볼것 = [
    ["index.html", "문서"],
    ["assets/index-a1b2c3d4.js", "스크립트"],
    ["assets/index-e5f6g7h8.css", "스타일"],
  ];

  const 결과들 = 볼것.map(([키, 무엇]) => {
    const 결과 = 브라우저가받음(s3.받아보기(키), 무엇);
    console.log(`${결과.됨 ? "○" : "✕"} ${키.padEnd(26, " ")} ${결과.이유}`);
    return { 무엇, ...결과 };
  });

  const 문서 = 결과들.find((하나) => 하나.무엇 === "문서");
  const 나머지 = 결과들.filter((하나) => 하나.무엇 !== "문서");

  const 진단 = !문서.됨
    ? "★ 화면이 아예 안 뜹니다 — 파일이 내려받아집니다"
    : 나머지.every((하나) => 하나.됨)
      ? "정상"
      : "★ 하얀 화면 — 틀은 왔는데 안이 안 채워집니다";

  console.log(`\n→ ${진단}`);
}

// ★★★ 파일은 네 개 다 올라갔습니다. 404 도 아닙니다.
//   그런데 브라우저가 아무것도 안 합니다.
//
// ★★ 증상이 두 가지입니다. 어느 파일이 틀렸느냐에 따라 다릅니다.
//
//   (가) index.html 이 틀림  →  주소를 열면 **내려받기 창**이 뜹니다
//        화면은 아예 안 나옵니다. 그나마 이건 뭔가 이상한 걸 압니다.
//
//   (나) index.html 은 맞고 assets 만 틀림  →  ★ **하얀 화면**
//        주소는 열립니다. 탭 제목도 나옵니다. 그런데 화면이 비어 있습니다.
//        ★★ 이게 제일 헷갈립니다. 다 된 것 같은데 아무것도 없습니다.
//
//   ★ (나) 가 왜 흔하냐면 — index.html 은 콘솔에서 손으로 올리고
//     assets 는 스크립트로 올리는 일이 많기 때문입니다.
//     콘솔은 종류를 알아서 정해 주고, 스크립트는 안 정해 줍니다.
//
//   진짜 브라우저 콘솔에는 이렇게 나옵니다:
//
//     Failed to load module script: Expected a JavaScript module script
//     but the server responded with a MIME type of "binary/octet-stream".
//     Strict MIME type checking is enforced for module scripts per HTML spec.
//
//   CSS 는 이렇게 나옵니다:
//
//     Refused to apply style from '...' because its MIME type
//     ('binary/octet-stream') is not a supported stylesheet MIME type.
//
// ★ 이 오류를 한 번 보고 나면 평생 안 잊습니다.
//   "파일 다 올렸는데 하얀 화면" 이면 F12 → Console 을 먼저 보세요.

// ============================================================
// 4. 확장자로 종류를 정합니다
// ============================================================

const 종류표 = {
  ".html": "text/html",
  ".js": "text/javascript",
  ".css": "text/css",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};

function 종류정하기(키) {
  return 종류표[path.extname(키).toLowerCase()] ?? "application/octet-stream";
}

// ★ 여기 기본값은 `application/octet-stream` 인데 위의 가짜 S3 는
//   `binary/octet-stream` 을 씁니다. **같은 뜻입니다.**
//   표준(IANA) 이름은 application/ 쪽이고, S3 가 실제로 돌려주는 값이
//   binary/ 쪽이라 그렇게 흉내 냈습니다. 둘 다 "모르겠다" 는 뜻입니다.

function 표보기() {
  console.log("\n=== 4. 확장자 → 종류 ===\n");

  for (const [확장자, 종류] of Object.entries(종류표)) {
    console.log(`${확장자.padEnd(8, " ")} ${종류}`);
  }

  console.log(`\n모르는 것: ${종류정하기("파일.zzz")}`);
}

// ★★ 이 표를 손으로 안 써도 됩니다. `mime-types` 패키지가 있습니다.
//
//     npm i mime-types
//     const mime = require("mime-types");
//     mime.lookup("index.js")   →  "text/javascript"
//
//   여기서는 무슨 일이 벌어지는지 보이려고 직접 썼습니다.
//
//   ★ 버전을 봐야 합니다. 같은 함수가 다른 값을 돌려줍니다.
//       mime-types@3      "text/javascript"
//       mime-types@2.1.35 "application/javascript"
//     둘 다 브라우저가 스크립트로 받아 줍니다만, 값이 다르니
//     테스트에 못 박아 두면 패키지를 올릴 때 깨집니다.
//
//   ★ `.ico` 는 위 표와 다릅니다.
//       위 표          image/x-icon
//       mime-types     image/vnd.microsoft.icon   ← IANA 에 등록된 이름
//     둘 다 브라우저가 알아듣습니다. 표 쪽이 예전부터 쓰던 이름입니다.
//
// ★★ 실제로 올릴 때는 텍스트에 charset 을 붙이는 게 좋습니다.
//
//     ".html": "text/html; charset=utf-8"
//     ".css":  "text/css; charset=utf-8"
//
//   S3 는 charset 을 안 붙여 줍니다. 안 붙이면 브라우저가 추측합니다.
//   HTML 은 안에 <meta charset="UTF-8"> 이 있어서 대개 괜찮지만,
//   CSS 안의 한글(`content: "설비"`) 은 깨질 수 있습니다.
//   ★ 위 표에 안 넣은 건 아래 브라우저 흉내가 값을 **글자 그대로** 비교하기
//     때문입니다. 진짜 코드에서는 붙이세요.
//
// ★ AWS CLI 로 올리면 (`aws s3 sync`) 확장자를 보고 알아서 정해 줍니다.
//   SDK 로 올릴 때만 직접 정해야 합니다.
//   ★★ 그래서 "CLI 로는 되는데 코드로는 안 돼요" 가 나옵니다.

// ============================================================
// 5. 고쳐서 다시 올리기
// ============================================================

async function 제대로올리기(s3) {
  console.log("\n=== 5. 제대로 올리기 ===\n");

  for (const 하나 of 파일전부(dist)) {
    const 종류 = 종류정하기(하나.키);

    await s3.send(
      new PutObjectCommand({
        Bucket: "내화면버킷",
        Key: 하나.키,
        Body: fs.readFileSync(하나.전체),
        ContentType: 종류, // ★ 이 한 줄이 전부입니다
      }),
    );

    console.log(`${하나.키.padEnd(28, " ")} ${종류}`);
  }
}


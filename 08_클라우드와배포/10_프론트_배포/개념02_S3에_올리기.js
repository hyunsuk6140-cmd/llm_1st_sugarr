// ============================================================
//
// 개념01 에서 dist 가 **그냥 파일 몇 개**인 걸 봤습니다.
// 이제 그 파일들을 S3 에 올립니다.
//
// ★★ 08단원에서도 S3 를 썼습니다. 그런데 쓰는 법이 다릅니다.
//
//   08단원 — 파일을 **보관**했습니다. 아무도 직접 못 봅니다. 비공개.
//   10단원 — 화면을 **서비스**합니다. 누구나 봐야 합니다. 공개.
//
// ★★★ 이 단원 최대의 함정이 여기 있습니다.
//   파일은 다 올라갔고 404 도 아닌데 화면이 안 나옵니다.
//   원인은 `ContentType` 한 줄입니다. 3번 절에서 봅니다.
//
// 실행: node 개념02_S3에_올리기.js
// ============================================================

const fs = require("node:fs");
const path = require("node:path");

const dist = path.join(__dirname, "예제dist");

// ============================================================
// 0. 가짜 S3 (08단원 것에 "웹사이트로 열어 보기" 를 붙였습니다)
// ============================================================

class PutObjectCommand {
  constructor(input) {
    this.input = input;
  }
}

function 가짜S3만들기() {
  const 안에든것 = new Map(); // 키 → { 내용, 종류 }

  return {
    async send(명령) {
      if (명령.constructor.name !== "PutObjectCommand") {
        throw new Error(`가짜 S3 가 모르는 명령: ${명령.constructor.name}`);
      }

      const 입력 = 명령.input;

      // ★★★ 여기가 핵심입니다.
      //   ContentType 을 안 주면 S3 는 `binary/octet-stream` 으로 정합니다.
      //   확장자를 보고 알아서 정해 주지 **않습니다.**
      안에든것.set(입력.Key, {
        내용: Buffer.from(입력.Body),
        종류: 입력.ContentType ?? "binary/octet-stream",
      });

      return { ETag: '"가짜"' };
    },

    // 브라우저가 이 주소를 열었다고 치고, S3 가 뭘 돌려주는지 봅니다
    받아보기(키) {
      const 것 = 안에든것.get(키);
      if (!것) return { 상태: 404, 종류: null };
      return { 상태: 200, 종류: 것.종류, 내용: 것.내용.toString("utf-8") };
    },

    지금든것: () => [...안에든것.keys()].sort(),
  };
}

// ============================================================
// 1. dist 통째로 올리기
// ============================================================
//
// 파일이 네 개뿐이라도 하나씩 손으로 올리면 안 됩니다.
// 진짜 빌드 결과는 수십 개입니다. 폴더를 훑어서 전부 올립니다.

function 파일전부(뿌리) {
  const 모음 = [];

  (function 훑기(현재, 앞) {
    for (const 이름 of fs.readdirSync(현재).sort()) {
      const 전체 = path.join(현재, 이름);

      if (fs.statSync(전체).isDirectory()) {
        훑기(전체, `${앞}${이름}/`);
      } else {
        모음.push({ 키: `${앞}${이름}`, 전체 });
      }
    }
  })(뿌리, "");

  return 모음;
}

// ★ 키에 `\` 가 아니라 `/` 를 씁니다.
//   윈도우에서 만든 경로를 그대로 쓰면 `assets\index.js` 가 됩니다.
//   S3 는 그걸 폴더로 안 보고 **이름에 역슬래시가 든 파일**로 봅니다.
//   위 코드는 처음부터 `/` 로 이어 붙여서 이 문제를 피했습니다.

async function 그냥올리기(s3) {
  console.log("=== 1. 그냥 올리기 ===\n");

  for (const 하나 of 파일전부(dist)) {
    await s3.send(
      new PutObjectCommand({
        Bucket: "내화면버킷",
        Key: 하나.키,
        Body: fs.readFileSync(하나.전체),
        // ContentType 을 안 줬습니다. 잠시 후 무슨 일이 생기는지 봅니다.
      }),
    );
    console.log(`올림  ${하나.키}`);
  }

  console.log(`\n${s3.지금든것().length}개 올렸습니다`);
}

// ★ (나) 를 재현하려고 만든 것입니다.
//   index.html 만 콘솔에서 손으로 올리고, 나머지는 스크립트로 올린 상황입니다.
async function 반만정해서올리기(s3) {
  for (const 하나 of 파일전부(dist)) {
    const 손으로올린것 = 하나.키 === "index.html";

    await s3.send(
      new PutObjectCommand({
        Bucket: "내화면버킷",
        Key: 하나.키,
        Body: fs.readFileSync(하나.전체),
        ...(손으로올린것 ? { ContentType: "text/html" } : {}),
      }),
    );
  }
}

// ============================================================
// 2. 브라우저가 뭘 하는지
// ============================================================
//
// 브라우저는 파일을 받으면 **확장자를 안 봅니다.**
// 서버가 같이 보내 준 `Content-Type` 헤더만 봅니다.
//
// ★★ 그리고 요즘 브라우저는 이걸 아주 깐깐하게 봅니다.
//   종류가 안 맞으면 받아 놓고도 **실행을 거부합니다.**
//
// ★★★ 다만 **전부 그런 건 아닙니다.** 종류마다 다릅니다. 이걸 알면
//   증상만 보고 원인을 되짚을 수 있습니다.
//
//   .js / .css   종류가 안 맞으면 **무조건 거부**합니다. 봐주는 게 없습니다.
//   .html        내려받기 창이 뜹니다. 화면이 안 그려집니다.
//   .png / .jpg  브라우저가 파일 앞부분을 읽어 알아냅니다(스니핑).
//                → `binary/octet-stream` 이어도 **그림은 그냥 뜹니다.**
//   .svg         스니핑 대상이 아닙니다. `image/svg+xml` 이 아니면 안 뜹니다.
//                (svg 안에 스크립트를 넣을 수 있어서 아무 종류나 못 믿습니다)
//
//   ★ 그래서 "사진은 나오는데 아이콘(svg)만 안 나온다" 면
//     ContentType 을 안 준 것입니다. **사진이 나온다고 맞는 게 아닙니다.**
//     아래 흉내 코드는 .js·.css·.html 세 가지만 다룹니다.

function 브라우저가받음(응답, 무엇) {
  if (응답.상태 === 404) return { 됨: false, 이유: "404 — 파일이 없습니다" };

  const 맞는종류 = {
    문서: ["text/html"],
    스크립트: ["text/javascript", "application/javascript"],
    스타일: ["text/css"],
  }[무엇];

  if (!맞는종류.includes(응답.종류)) {
    // ★ 증상이 다릅니다. 문서는 내려받기 창이 뜨고, 나머지는 조용히 거부됩니다.
    return 무엇 === "문서"
      ? { 됨: false, 이유: `내려받기 창 (${응답.종류})` }
      : { 됨: false, 이유: `거부 (${응답.종류})` };
  }

  return { 됨: true, 이유: "실행함" };
}


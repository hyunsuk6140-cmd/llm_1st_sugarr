function 주소두개() {
  console.log("\n=== 7. 주소 두 개 ===\n");

  const 둘 = [
    ["REST", "내버킷.s3.ap-northeast-2.amazonaws.com", "파일 하나씩. 08단원에서 쓴 것"],
    ["웹사이트", "내버킷.s3-website.ap-northeast-2.amazonaws.com", "★ 사이트처럼. 이걸 씁니다"],
  ];

  둘.forEach(([이름, 주소, 설명], 순번) => {
    if (순번 > 0) console.log("");
    console.log(`[${이름}]`);
    console.log(`  ${주소}`);
    console.log(`  ${설명}`);
  });
}

// ★★ 웹사이트 엔드포인트만 할 수 있는 것
//
//   · `/` 로 들어오면 index.html 을 줍니다 (인덱스 문서)
//   · 없는 주소일 때 정해 둔 파일을 줍니다 (오류 문서) → ★ 개념03 에서 씁니다
//
//   REST 엔드포인트로 `/` 를 열면 XML 목록이 나오거나 403 이 납니다.
//   ★ "왜 홈페이지가 안 뜨죠?" 의 절반은 주소를 잘못 쓴 것입니다.
//
// ★ 웹사이트 엔드포인트는 **HTTPS 가 안 됩니다.** http 뿐입니다.
//   https 로 하려면 앞에 CloudFront 를 둡니다. 이 과정 밖입니다.
//
//   ★★ 그때 오리진은 웹사이트 엔드포인트가 아니라
//     **REST 엔드포인트 + OAC**(Origin Access Control) 로 잡는 게 보통입니다.
//     버킷을 계속 비공개로 두고 CloudFront 에게만 열어 주는 방식입니다.
//
//   ★★★ 그러면 없는 주소에 404 가 아니라 **403** 이 옵니다. 이유가 있습니다.
//     OAC 정책은 `s3:GetObject` 만 주고 `s3:ListBucket` 은 안 줍니다.
//     목록 권한이 없으면 S3 는 "없는 키" 와 "볼 수 없는 키" 를
//     **구분해서 알려 주지 않습니다.** 전부 403 입니다.
//     구분해 주면 키 이름을 하나씩 넣어 보며 버킷 안에 뭐가 있는지
//     알아낼 수 있으니까요.
//     → 개념03 에서 "403·404 를 200 으로 바꿔 준다" 고 적은 이유입니다.


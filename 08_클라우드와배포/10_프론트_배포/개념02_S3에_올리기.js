// ★★ `Action` 이 `s3:GetObject` 하나뿐입니다. **읽기만** 입니다.
//   `s3:PutObject` 를 같이 열면 아무나 내 버킷에 파일을 올립니다.
//   요금은 제가 냅니다.
//
// ★★★ 순서가 있습니다. 콘솔에서 이 순서로 합니다.
//
//   (1) 버킷 → 권한 → **퍼블릭 액세스 차단**을 끕니다
//   (2) 그 다음에 위 버킷 정책을 붙입니다
//
//   ★ (1) 을 안 끄고 (2) 를 하면 정책은 저장되는데 **아무 일도 안 일어납니다.**
//     차단이 정책보다 셉니다. "정책 넣었는데 403 이에요" 가 거의 이 경우입니다.
//
// ★ 만들 때 켜져 있는 게 정상입니다. 실수로 공개되는 사고가 하도 많아서
//   AWS 가 기본값을 "차단" 으로 바꿨습니다.


// ============================================================
// 4. 세 번을 나란히 놓고 보면
// ============================================================
//
//   2번 — index.html 도 assets 도 캐시에 있습니다.
//         서버에 **아무것도 안 물어봅니다.** 옛 화면을 그대로 봅니다.
//         → 1년 동안 그럽니다. 옛 파일을 지웠든 말든 상관이 없습니다.
//
//         ★ 이 파일을 쓰면서 여기를 틀렸습니다.
//           "옛 파일을 지웠으니 깨질 것" 이라고 적어 놨는데, 돌려 보니
//           **안 깨졌습니다.** 물어보지를 않으니 없어진 걸 알 수가 없습니다.
//           깨지려면 조건이 하나 더 있어야 합니다. 그게 3번입니다.
//
//   3번 — index.html 은 캐시에 남았는데 **assets 캐시만 사라진** 경우입니다.
//         브라우저가 자리가 모자라면 캐시를 하나씩 버립니다. 흔한 일입니다.
//         옛 index.html 이 옛 assets 를 찾는데 그건 서버에서 지웠습니다.
//         → 404 → (개념03 의 오류 문서) index.html 이 옴 → ★ **깨집니다.**
//
//   4번 — index.html 을 매번 새로 받으니 새 assets 를 찾습니다.
//         → ★ 정상입니다.
//
// ★★ 3번이 알려 주는 것 — **옛 파일을 바로 지우면 안 됩니다.**
//   배포한 순간에도 옛 index.html 을 들고 있는 브라우저가 있습니다.
//   며칠 두었다가 지우세요. 어차피 파일 몇 개라 요금도 얼마 안 됩니다.
//
//   ★★★ 그 "바로 지우는 짓" 을 하는 게 `aws s3 sync --delete` 입니다.
//     검색해서 나오는 배포 가이드는 대부분 `--delete` 를 붙여 둡니다.
//     버킷을 dist 와 **똑같이** 맞춰 주니 깔끔해 보이거든요.
//     그런데 붙이는 순간 옛 assets 가 사라지고 위 3번이 그대로 일어납니다.
//
//     → 평소 배포에는 `--delete` 를 **빼세요.**
//       정리는 며칠 지난 뒤에 따로 한 번 돌리거나,
//       S3 수명 주기 규칙(예: 30일 지난 것 삭제)에 맡기세요.
//
//     ★ "그럼 파일이 계속 쌓이지 않나요?" — 쌓입니다. 그래도 괜찮습니다.
//       빌드 결과는 몇백 KB 라 한 달 치를 모아도 요금이 안 보입니다.
//       깨진 화면을 보는 사용자가 훨씬 비쌉니다.
//
// ★★★ 2번과 3번의 차이가 중요합니다.
//   같은 잘못(index.html 을 캐시함)인데 증상이 다릅니다.
//   그래서 "저는 그대로예요" 와 "저는 깨졌어요" 가 **같이** 나옵니다.
//   두 사람이 다른 말을 한다고 원인이 둘인 게 아닙니다.

// ============================================================
// 5. no-cache 와 no-store 는 다릅니다
// ============================================================
//
//   no-cache   캐시에 저장은 합니다. 대신 **쓸 때마다 서버에 물어봅니다.**
//              "안 바뀌었어?" → 안 바뀌었으면 304 를 받고 캐시 것을 씁니다.
//              ★ 이름이 헷갈립니다. "캐시 안 함" 이 아닙니다.
//
//   no-store   아예 저장을 안 합니다. 매번 통째로 받습니다.
//              은행 잔액 같은 것에 씁니다.
//
// ★★ index.html 에는 `no-cache` 를 씁니다.
//   파일이 안 바뀌었으면 304 만 오고 끝납니다. 400바이트도 안 씁니다.
//   `no-store` 로 하면 매번 전체를 받습니다. 그럴 이유가 없습니다.
//
// ★ 정확히 쓰면 이렇습니다.
//
//     index.html   Cache-Control: no-cache
//     assets/*     Cache-Control: public, max-age=31536000, immutable
//
//   31536000 = 60 × 60 × 24 × 365. 1년입니다.
//   ★ 규격이 1년까지라고 정해 둔 건 아닙니다. 관례로 1년을 씁니다.

// ============================================================
// 6. 올릴 때 넣습니다
// ============================================================
//
// 개념02 의 올리는 코드에 한 줄을 더합니다.
//
//     const 해시붙음 = 하나.키.startsWith("assets/");
//
//     await s3.send(new PutObjectCommand({
//       Bucket: "내화면버킷",
//       Key: 하나.키,
//       Body: fs.readFileSync(하나.전체),
//       ContentType: 종류정하기(하나.키),          // ← 개념02
//       CacheControl: 해시붙음                     // ← ★ 이번에 추가
//         ? "public, max-age=31536000, immutable"
//         : "no-cache",
//     }));
//
// ★ CLI 로 하면 **세 번** 나눠 올립니다.
//   해시가 붙은 것과 안 붙은 것을 갈라야 하기 때문입니다.
//
//     # ① 해시가 붙은 것만 1년 — Vite 는 전부 assets/ 에 넣습니다
//     aws s3 sync dist/assets/ s3://내버킷/assets/ \
//       --cache-control "public,max-age=31536000,immutable"
//
//     # ② dist 루트의 나머지 (vite.svg·favicon·robots.txt …) — 해시가 없습니다
//     aws s3 sync dist/ s3://내버킷 --exclude "assets/*" --exclude "index.html" \
//       --cache-control "no-cache"
//
//     # ③ index.html 을 맨 마지막에 (7번 절)
//     aws s3 cp dist/index.html s3://내버킷/index.html \
//       --cache-control "no-cache"
//
// ★★★ ② 를 빼고 `aws s3 sync dist/ … --exclude index.html` 한 줄로 하면
//   해시가 **없는** 파일에까지 1년 immutable 이 걸립니다.
//   Vite 는 `public/` 의 파일을 이름 그대로 dist 루트에 복사하거든요. (개념01)
//   그러면 `vite.svg` 를 고쳐 다시 올려도 **1년 동안 안 낫습니다.**
//   (연습문제_정답 문제 12 의 "이미 캐시된 사람은 안 낫습니다" 가 그 얘기입니다)
//
//   ★ 위의 SDK 코드는 `startsWith("assets/")` 로 판정합니다.
//     CLI 도 **같은 기준**이 되게 갈라야 합니다.
//     같은 절의 두 방법이 서로 다르게 동작하면 안 됩니다.

// ============================================================
// 7. ★★ 올리는 순서가 있습니다
// ============================================================

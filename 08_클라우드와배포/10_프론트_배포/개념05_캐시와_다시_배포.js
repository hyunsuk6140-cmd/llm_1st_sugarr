// ============================================================
// 8. ★★ CloudFront 를 앞에 뒀다면 — 무효화(invalidation)
// ============================================================
//
// 개념02 에서 HTTPS 때문에, 개념03 에서 404 를 200 으로 바꾸려고
// CloudFront 를 권했습니다. 그러면 캐시가 **한 겹 더** 생깁니다.
//
//     브라우저 캐시  ←  CloudFront 캐시  ←  S3
//
// S3 를 갈아 끼워도 CloudFront 가 옛것을 들고 있으면
// 사용자는 그대로 옛 화면을 봅니다. 지금까지의 규칙만으로는 안 낫습니다.
//
//     aws cloudfront create-invalidation \
//       --distribution-id E1234567890ABC \
//       --paths "/index.html" "/"
//
// ★ 지울 것은 **index.html 뿐**입니다.
//   assets 는 내용이 바뀌면 이름이 바뀌니까요. (개념01)
//   옛 이름의 캐시는 아무도 안 찾습니다. 지울 이유가 없습니다.
//   `"/"` 를 같이 넣은 건 인덱스 문서로 들어온 요청이 따로 캐시되기 때문입니다.
//
// ★★ `--paths "/*"` 로 통째로 지우고 싶어집니다. 참으세요.
//   · 무효화는 **한 달에 1,000 경로까지 무료**이고 그 뒤로는 경로당 요금입니다.
//     (`/*` 는 한 경로로 세지만, 매 배포마다 쓰면 다른 경로와 합쳐서 넘깁니다)
//   · 그리고 캐시를 전부 비우니 다음 요청이 **전부 S3 까지** 갑니다.
//     한동안 느려집니다. CDN 을 둔 의미가 그만큼 줄어듭니다.
//
// ★★★ 순서는 S3 와 똑같습니다.
//     assets 올리기 → index.html 올리기 → **그다음에** 무효화
//   무효화를 먼저 하면 CloudFront 가 옛 index.html 을 다시 받아 갑니다.
//   그러면 아무것도 안 한 것과 같습니다.
//
// ★ CloudFront 쪽에서 캐시 기간을 따로 정할 수도 있지만,
//   오리진(S3)이 보낸 Cache-Control 을 그대로 쓰게 두는 게 단순합니다.
//   규칙이 한 군데에만 있어야 헷갈리지 않습니다.

// ============================================================
// 정리
// ============================================================
//
//   1. 이름에 해시가 있으면 → 영원히 캐시 (max-age=31536000, immutable)
//   2. index.html 은 → no-cache (매번 물어보되 안 바뀌었으면 304)
//      ★ 해시가 **없는** 파일(vite.svg·favicon)도 2번 쪽입니다.
//        폴더가 아니라 이름에 해시가 있느냐로 가르세요.
//   3. ★ 반대로 하면 "안 바뀌어요" 또는 "깨졌어요" 가 나옵니다.
//   4. 올리는 순서: assets 먼저, index.html 나중에
//   5. 옛 파일은 며칠 뒤에 지웁니다. 평소 배포에 `--delete` 를 붙이지 마세요.
//   6. no-cache ≠ no-store. 이름에 속지 마세요.

// 1차 배포 · 2차 배포. 해시가 바뀐 것에 주의하세요.
const 배포판 = {
  1: {
    "index.html": "…src=/assets/index-a1b2c3d4.js…",
    "assets/index-a1b2c3d4.js": "화면을 그리는 코드 (옛것)",
  },
  2: {
    "index.html": "…src=/assets/index-9f8e7d6c.js…",
    "assets/index-9f8e7d6c.js": "화면을 그리는 코드 (새것)",
  },
};

// ★ S3 에 지금 올라가 있는 것. 배포하면 이걸 갈아 끼웁니다.
function 호스팅만들기(규칙) {
  let 올라간것 = { ...배포판[1] };

  return {
    배포하기(차수, 옛것도남길까) {
      올라간것 = 옛것도남길까 ? { ...올라간것, ...배포판[차수] } : { ...배포판[차수] };
    },

    요청(키) {
      if (키 in 올라간것) {
        return { 상태: 200, 내용: 올라간것[키], 규칙: 규칙(키) };
      }
      // 개념03 에서 정한 오류 문서. 없는 주소면 index.html 을 줍니다.
      return { 상태: 404, 내용: 올라간것["index.html"], 규칙: 규칙("index.html") };
    },
  };
}

function 캐시만들기() {
  const 저장 = new Map(); // 키 → { 내용, 규칙, 나이 }

  return {
    // 지난시간(초) 만큼 흐른 뒤에 이 키를 받아 봅니다
    받기(키, 호스팅, 지난시간) {
      const 든것 = 저장.get(키);

      if (든것) {
        든것.나이 += 지난시간;

        // ★ 아직 안 늙었으면 서버에 아예 안 물어봅니다
        if (든것.나이 < 든것.규칙.최대나이) {
          return { 어디서: "캐시", 내용: 든것.내용 };
        }
      }

      const 답 = 호스팅.요청(키);
      저장.set(키, { 내용: 답.내용, 규칙: 답.규칙, 나이: 0 });
      return { 어디서: "서버", 내용: 답.내용, 상태: 답.상태 };
    },

    // ★ 브라우저는 자리가 모자라면 캐시를 **하나씩** 버립니다.
    //   전부 지우는 게 아닙니다. 이게 3번 시나리오의 조건입니다.
    버리기(키) {
      저장.delete(키);
    },
  };
}

// ★ `최대나이: 0` 이면 매번 서버에 물어봅니다. 그게 no-cache 입니다.

// ============================================================
// 1. 규칙을 두 가지로 나눕니다
// ============================================================

const 나쁜규칙 = () => ({ 최대나이: 31536000, 이름: "max-age=31536000 (1년)" });

const 좋은규칙 = (키) =>
  키 === "index.html"
    ? { 최대나이: 0, 이름: "no-cache" }
    : { 최대나이: 31536000, 이름: "max-age=31536000, immutable" };

function 규칙보기() {
  console.log("=== 1. 파일마다 다른 규칙 ===\n");

  for (const 키 of ["index.html", "assets/index-a1b2c3d4.js"]) {
    console.log(`${키}`);
    console.log(`   나쁜 규칙: ${나쁜규칙(키).이름}`);
    console.log(`   좋은 규칙: ${좋은규칙(키).이름}\n`);
  }
}

// ★★★ 왜 반대로 나뉘나 — 이름에 해시가 있느냐 없느냐입니다.
//
//   assets/index-a1b2c3d4.js
//     내용이 바뀌면 **이름이 바뀝니다.** (개념01)
//     그러니 이 이름의 파일은 절대 안 바뀝니다. 영원히 캐시해도 안전합니다.
//
//   index.html
//     내용이 바뀌어도 **이름이 그대로**입니다.
//     주소창에 치는 파일이라 이름을 못 바꿉니다.
//     그러니 캐시하면 안 됩니다.
//
// ★ `immutable` 은 "만료 전에는 새로고침해도 다시 묻지 마라" 는 뜻입니다.
//   해시가 붙은 파일에만 붙이세요.

// ============================================================
// 2·3. 진짜로 돌려 봅니다
// ============================================================

function 시나리오(제목, 규칙, 옛것도남길까, 자산캐시버림 = false) {
  console.log(`\n=== ${제목} ===\n`);

  const 호스팅 = 호스팅만들기(규칙);
  const 브라우저 = 캐시만들기();

  // ── 첫 방문 ──
  const 첫html = 브라우저.받기("index.html", 호스팅, 0);
  const 첫자산키 = 첫html.내용.match(/assets\/[^…]+\.js/)[0];
  브라우저.받기(첫자산키, 호스팅, 0);

  console.log(`[첫 방문]  ${첫html.어디서}에서 index.html → ${첫자산키}`);

  // ── 새로 배포 ──
  호스팅.배포하기(2, 옛것도남길까);
  console.log(`[배포]     2차 배포. 옛 assets 를 ${옛것도남길까 ? "남겨 뒀습니다" : "지웠습니다"}`);

  if (자산캐시버림) {
    브라우저.버리기(첫자산키);
    console.log(`[캐시]     브라우저가 자리가 모자라 ${첫자산키} 를 버렸습니다`);
  }

  // ── 하루 뒤 다시 방문 ──
  const 다시html = 브라우저.받기("index.html", 호스팅, 86400);
  const 다시자산키 = 다시html.내용.match(/assets\/[^…]+\.js/)[0];
  const 자산답 = 브라우저.받기(다시자산키, 호스팅, 86400);

  console.log(`[재방문]   ${다시html.어디서}에서 index.html → ${다시자산키}`);
  console.log(`           ${다시자산키} → ${자산답.어디서} / ${자산답.내용}`);

  // ── 판정 ──
  const 새것인가 = 자산답.내용 === "화면을 그리는 코드 (새것)";
  const 깨졌나 = 자산답.내용.startsWith("…src=");

  console.log(
    `\n→ ${깨졌나 ? "★ 깨짐 — .js 를 달랬는데 HTML 이 왔습니다 (Unexpected token '<')" : 새것인가 ? "정상 — 새 화면이 보입니다" : "★ 옛 화면 그대로입니다"}`,
  );
}


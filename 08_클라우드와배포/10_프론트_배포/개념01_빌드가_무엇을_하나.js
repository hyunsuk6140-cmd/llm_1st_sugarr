function 왜해시() {
  console.log("\n=== 3. 이름의 해시 ===\n");
  // 출력:
  // 출력: === 3. 이름의 해시 ===
  // 출력:

  console.log("index-a1b2c3d4.js   ← a1b2c3d4 가 내용에서 나온 값입니다");
  // 출력: index-a1b2c3d4.js   ← a1b2c3d4 가 내용에서 나온 값입니다
  console.log("");
  // 출력:
  console.log("내용이 바뀌면 이름도 바뀝니다:");
  // 출력: 내용이 바뀌면 이름도 바뀝니다:
  console.log("  index-a1b2c3d4.js  →  index-9f8e7d6c.js");
  // 출력:   index-a1b2c3d4.js  →  index-9f8e7d6c.js
}

// ★★ 해시가 16진수처럼 보이지만 **그렇게 단정하면 안 됩니다.**
//   Vite 는 base64 계열로 줄여 씁니다. **영문 대소문자와 숫자가 섞여** 나옵니다.
//   (이 단원의 예제dist 에 있는 `index-e5f6g7h8.css` 에는 g·h 가 들어 있습니다)
//   ★ 그래서 파일 이름을 정규식으로 가려낼 때 `[0-9a-f]+` 로 잡으면 놓칩니다.
//     연습문제 1번이 그 함정입니다.

// ★★★ 왜 이렇게 하나 — 캐시 때문입니다.
//
//   브라우저는 한 번 받은 파일을 저장해 두고 다시 안 받습니다. (캐시)
//   그래야 빠르니까요.
//
//   그런데 이름이 `index.js` 로 늘 같으면
//   새로 배포해도 브라우저가 **옛날 것을 계속 씁니다.**
//   "저는 안 바뀌는데요?" 가 여기서 나옵니다.
//
//   ★ 이름이 바뀌면 브라우저가 "처음 보는 파일" 로 알고 새로 받습니다.
//     그래서 **해시가 붙은 파일은 영원히 캐시해도 안전합니다.** (개념05)
//
// ★★ 그럼 index.html 은? 얘는 이름이 안 바뀝니다.
//   주소창에 치는 게 이 파일이니까요.
//   ★ 그래서 index.html 만 **캐시하면 안 됩니다.** (개념05 에서 다룹니다)


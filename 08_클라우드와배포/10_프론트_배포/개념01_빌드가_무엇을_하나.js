//
//   빌드 = 소스를 **브라우저가 바로 읽을 수 있는 파일 몇 개**로 만드는 것
//     JSX → JS · 여러 파일 → 한 파일 · 압축 · 이름에 해시
//
//   ★ 결과는 그냥 파일입니다. 서버가 필요 없습니다. 그래서 S3 로 됩니다.
//
//   ★★ 파일 이름의 해시는 **캐시 때문**입니다.
//     내용이 바뀌면 이름이 바뀌어 브라우저가 새로 받습니다.
//     index.html 만 이름이 안 바뀝니다. → 얘만 캐시하면 안 됩니다 (개념05)
//
//   ★ index.html 은 거의 비어 있습니다. JS 를 못 받으면 하얀 화면입니다.
//
//   ★★★ 배포하면 화면(S3)과 API(EC2)가 **다른 주소**가 됩니다.
//     CORS 가 필요하고, 프론트가 API 주소를 알아야 합니다. (개념04)
//
// 다음(개념02) 에서 S3 에 올립니다.

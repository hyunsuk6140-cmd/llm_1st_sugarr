// ★ "한 파일" 이 아니라 "몇 덩어리" 라고 적은 이유
//
//   Vite 는 **코드 스플리팅**을 합니다. 화면마다 나눠서 필요할 때 받게 하거나,
//   잘 안 바뀌는 라이브러리를 따로 빼거나 합니다.
//   그래서 진짜 dist/assets 에는 해시가 붙은 .js 가 여러 개 나옵니다.
//
//   ★★ 그 "여러 개" 라는 게 개념05 캐시 전략의 전제입니다.
//     하나만 바뀌면 그 하나만 이름이 바뀌고, 나머지는 캐시 그대로 씁니다.
//     한 덩어리였다면 한 글자만 고쳐도 전부 다시 받아야 합니다.
//   (여기 예제dist 는 구조만 보려고 .js 하나 .css 하나로 아주 작게 만들었습니다)

// ★★★ 제일 중요한 것
//
//   빌드 결과는 **그냥 파일 몇 개**입니다.
//   Node 도, 서버도 필요 없습니다. 브라우저가 받아서 실행합니다.
//
//   ★ 그래서 EC2 에 안 올려도 됩니다. S3 만으로 됩니다. (개념02)
//     서버가 필요 없는 걸 "정적(static)" 이라고 합니다.

// ============================================================
// 2. dist 안에 뭐가 있나
// ============================================================

function 안에뭐가() {
  console.log("\n=== 2. dist 안 ===\n");
  // 출력:
  // 출력: === 2. dist 안 ===
  // 출력:

  const 목록 = [];

  (function 훑기(현재, 앞) {
    for (const 이름 of fs.readdirSync(현재).sort()) {
      const 전체 = path.join(현재, 이름);

      if (fs.statSync(전체).isDirectory()) {
        훑기(전체, `${앞}${이름}/`);
      } else {
        목록.push({ 경로: `${앞}${이름}`, 크기: fs.statSync(전체).size });
      }
    }
  })(dist, "");

  for (const 하나 of 목록) {
    console.log(`${하나.경로.padEnd(32, " ")} ${String(하나.크기).padStart(5, " ")} 바이트`);
    // 출력?: assets/index-a1b2c3d4.js           299 바이트
    // 출력?: assets/index-e5f6g7h8.css          105 바이트
    // 출력?: index.html                         400 바이트
    // 출력?: vite.svg                           119 바이트
    //
    // ★ 위 네 줄은 `// 출력?:` 입니다. 값은 안 보고 줄이 있는지만 봅니다.
    //   줄 끝 문자가 컴퓨터마다 다릅니다. (윈도우는 두 글자, 리눅스·맥은 한 글자)
    //   그래서 같은 파일인데도 **바이트 수가 달라집니다.**
    //   컴퓨터마다 달라지는 값은 못 박으면 안 됩니다.
  }

  console.log(`\n파일 ${목록.length}개`);
  // 출력:
  // 출력: 파일 4개

  return 목록;
}

// ★ 진짜 빌드 결과는 훨씬 큽니다. React 만 해도 JS 가 150KB 쯤 됩니다.

// ★★★ 이 오류를 처음 보면 도무지 감이 안 옵니다.
//   내 코드에 `<` 를 쓴 적이 없는데 왜 이러지?
//
//   `<` 는 `<!doctype html>` 의 첫 글자입니다.
//   JS 파일인 줄 알고 실행했는데 안에 HTML 이 들어 있는 것입니다.
//
// ★★ 왜 없는 해시를 부르나 — 이게 진짜 원인입니다.
//
//   (1) 새로 배포해서 assets 이름이 index-9f8e7d6c.js 로 바뀌었습니다
//   (2) 그런데 브라우저가 **옛날 index.html 을 캐시**해 뒀습니다
//   (3) 옛 index.html 은 index-a1b2c3d4.js 를 찾습니다
//   (4) 그 파일은 이미 지웠습니다 → 없음 → 오류 문서 = index.html → HTML 이 옴
//
//   ★ 그래서 개념05 에서 "index.html 은 캐시하면 안 된다" 를 다룹니다.
//     여기서 만난 오류가 거기서 풀립니다.
//

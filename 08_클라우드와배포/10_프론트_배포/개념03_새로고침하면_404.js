// ★ 어떻게 200 으로 만드나
//
//   · CloudFront 를 앞에 둡니다. 403·404 를 200 + /index.html 로 바꿔 줍니다.
//     (이 과정 밖입니다. 나중에 필요하면 찾아보세요.)
//
//     ★ 404 만이 아니라 **403 도** 적어 둔 이유가 있습니다.
//       오리진을 REST 엔드포인트 + OAC 로 잡으면(개념02 의 끝) 없는 키에도
//       404 가 아니라 **403** 이 옵니다. OAC 정책이 s3:GetObject 만 주고
//       s3:ListBucket 은 안 주기 때문입니다. 목록 권한이 없으면 S3 는
//       "없다" 와 "못 본다" 를 구분해 주지 않습니다.

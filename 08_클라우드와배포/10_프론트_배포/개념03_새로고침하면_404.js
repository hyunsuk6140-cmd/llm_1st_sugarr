function 가짜호스팅(설정) {
  // 개념02 에서 올린 것과 같습니다
  const 있는키 = new Set([
    "index.html",
    "assets/index-a1b2c3d4.js",
    "assets/index-e5f6g7h8.css",
    "vite.svg",
  ]);

  return function 요청(경로) {
    // 앞의 / 를 떼면 S3 의 '키' 가 됩니다
    let 키 = 경로.replace(/^\//, "");

    // 비었거나 / 로 끝나면 인덱스 문서를 붙입니다
    if (키 === "" || 키.endsWith("/")) 키 += 설정.인덱스문서;

    if (있는키.has(키)) return { 상태: 200, 준것: 키 };

    // ★ 오류 문서를 정해 뒀으면 그걸 줍니다. 상태는 404 그대로입니다.
    if (설정.오류문서) return { 상태: 404, 준것: 설정.오류문서 };

    return { 상태: 404, 준것: "(S3 의 기본 오류 화면)" };
  };
}


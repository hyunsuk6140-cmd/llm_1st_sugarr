//       → 그래서 CloudFront 오류 응답 설정에 **403 과 404 를 둘 다** 넣습니다.
//         하나만 넣으면 새로고침이 여전히 안 됩니다.
//   · nginx 로 서비스하면 `try_files` 가 **처음부터 200** 으로 줍니다. (7번 절)

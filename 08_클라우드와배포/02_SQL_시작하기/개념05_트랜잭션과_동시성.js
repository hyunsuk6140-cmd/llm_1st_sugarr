const 속도db = new DatabaseSync(":memory:");
속도db.exec("CREATE TABLE 기록 (n INTEGER) STRICT");
const 기록넣기 = 속도db.prepare("INSERT INTO 기록 (n) VALUES (?)");

function 재기(하기) {
  const 시작 = process.hrtime.bigint();
  하기();
  return Number(process.hrtime.bigint() - 시작) / 1e6;
}

const 낱개 = 재기(() => {
  for (let i = 0; i < 2000; i++) 기록넣기.run(i);
});

const 묶음 = 재기(() => {
  속도db.exec("BEGIN");
  for (let i = 0; i < 2000; i++) 기록넣기.run(i);
  속도db.exec("COMMIT");
});

console.log("묶는 게 더 빠른가:", 묶음 < 낱개);
// 출력: 묶는 게 더 빠른가: true


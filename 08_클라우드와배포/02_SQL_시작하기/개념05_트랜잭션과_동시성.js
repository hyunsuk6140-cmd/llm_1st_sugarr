// 정리
// ============================================================
//
//   BEGIN / COMMIT / ROLLBACK
//     둘 다 되거나 둘 다 안 되게
//     catch 에 ROLLBACK 을 반드시
//     겹쳐서 BEGIN 하면 오류
//     묶으면 훨씬 빠릅니다 (파일 DB 에서 1000배 넘게)
//
//   경합 (같은 자료를 동시에 고칠 때)
//     읽고→계산→쓰기 는 DB 를 써도 여전히 위험합니다
//     UPDATE ... SET 수량 = 수량 + 1  로 DB 한테 계산을 맡기세요
//     확인도 WHERE 에 넣으세요 (AND 잔액 >= ?)
//     트랜잭션 안에서 await 하지 마세요

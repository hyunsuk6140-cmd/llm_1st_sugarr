const { DatabaseSync } = require("node:sqlite");

// ============================================================
// 1. 트랜잭션이 뭔가
// ============================================================
//
// 계좌 이체를 생각해 봅시다. 두 문장이 필요합니다.
//
//   철수에서 3000원 빼기
//   영희에게 3000원 넣기
//
// 첫 줄만 되고 둘째 줄에서 서버가 죽으면?
// 3000원이 세상에서 사라집니다.
//
// "둘 다 되거나, 둘 다 안 되거나" 를 보장하는 게 트랜잭션입니다.

const 은행 = new DatabaseSync(":memory:");
은행.exec("CREATE TABLE 계좌 (이름 TEXT PRIMARY KEY, 잔액 INTEGER NOT NULL) STRICT");
은행.exec("INSERT INTO 계좌 VALUES ('철수', 10000), ('영희', 5000)");

은행.exec("BEGIN");
은행.prepare("UPDATE 계좌 SET 잔액 = 잔액 - ? WHERE 이름 = ?").run(3000, "철수");
은행.prepare("UPDATE 계좌 SET 잔액 = 잔액 + ? WHERE 이름 = ?").run(3000, "영희");
은행.exec("COMMIT");

console.log(JSON.stringify(은행.prepare("SELECT * FROM 계좌").all().map((계좌) => `${계좌.이름}:${계좌.잔액}`)));
// 출력: ["철수:7000","영희:8000"]

//   BEGIN     여기서부터 묶는다
//   COMMIT    지금까지 한 걸 확정한다
//   ROLLBACK  지금까지 한 걸 없던 일로 한다

// ============================================================
// 2. ROLLBACK
// ============================================================

은행.exec("BEGIN");
은행.prepare("UPDATE 계좌 SET 잔액 = 잔액 - ? WHERE 이름 = ?").run(9999, "철수");

console.log("트랜잭션 안에서 본 잔액:", 은행.prepare("SELECT 잔액 FROM 계좌 WHERE 이름 = '철수'").get().잔액);
// 출력: 트랜잭션 안에서 본 잔액: -2999

은행.exec("ROLLBACK");

console.log("ROLLBACK 뒤:", 은행.prepare("SELECT 잔액 FROM 계좌 WHERE 이름 = '철수'").get().잔액);
// 출력: ROLLBACK 뒤: 7000

// ★ 트랜잭션 안에서는 바뀐 것처럼 보입니다. 나만 그렇게 보이는 것입니다.
//   COMMIT 을 해야 밖에서도 보입니다.
//
// ★ 잔액이 -2999 가 된 걸 보세요. DB 는 막아 주지 않았습니다.
//   "잔액은 0 이상" 이라는 규칙을 안 걸었기 때문입니다.
//   CHECK (잔액 >= 0) 을 걸었다면 이 UPDATE 자체가 거절됐을 겁니다.

// ============================================================
// 3. 실무에서 쓰는 모양 — try / catch
// ============================================================

function 이체(보내는이, 받는이, 금액) {
  은행.exec("BEGIN");
  try {
    const 뺀결과 = 은행.prepare(`
      UPDATE 계좌 SET 잔액 = 잔액 - ? WHERE 이름 = ? AND 잔액 >= ?
    `).run(금액, 보내는이, 금액);

    if (뺀결과.changes === 0) {
      throw new Error("잔액이 모자라거나 없는 계좌입니다");
    }

    은행.prepare("UPDATE 계좌 SET 잔액 = 잔액 + ? WHERE 이름 = ?").run(금액, 받는이);
    은행.exec("COMMIT");
    return { 성공: true };
  } catch (에러) {
    은행.exec("ROLLBACK");
    return { 성공: false, 이유: 에러.message };
  }
}

console.log(이체("철수", "영희", 1000));
// 출력: { '성공': true }
console.log(이체("철수", "영희", 999999));
// 출력: { '성공': false, '이유': '잔액이 모자라거나 없는 계좌입니다' }

console.log(JSON.stringify(은행.prepare("SELECT * FROM 계좌").all().map((계좌) => `${계좌.이름}:${계좌.잔액}`)));
// 출력: ["철수:6000","영희:9000"]

// ★★ 뜯어볼 부분이 두 군데 있습니다.
//
//   1) WHERE 에 `AND 잔액 >= ?` 가 붙어 있습니다.
//      "잔액을 먼저 읽어서 확인" 하지 않았습니다.
//      확인과 차감을 한 문장으로 합쳤습니다. 그 사이에 끼어들 틈이 없습니다.
//
//   2) changes 로 성공 여부를 판단했습니다. (개념04)
//      잔액이 모자라면 조건에 안 걸려서 changes 가 0 이 됩니다.
//
// ★ catch 안의 ROLLBACK 을 빼먹으면 트랜잭션이 열린 채로 남습니다.
//   그 뒤 모든 요청이 "cannot start a transaction within a transaction" 으로 죽습니다.
//   try 를 썼으면 catch 에 ROLLBACK 이 반드시 있어야 합니다.

// ============================================================
// 4. 트랜잭션은 겹칠 수 없습니다
// ============================================================

은행.exec("BEGIN");
try {
  은행.exec("BEGIN");
} catch (에러) {
  console.log(에러.message);
  // 출력: cannot start a transaction within a transaction
}
은행.exec("ROLLBACK");

try {
  은행.exec("COMMIT");
} catch (에러) {
  console.log(에러.message);
  // 출력: cannot commit - no transaction is active
}


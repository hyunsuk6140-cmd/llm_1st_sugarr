  실무설정.forEach((줄) => console.log(줄));
  // 출력: const db = new DatabaseSync("데이터.db", { timeout: 5000 });
  // 출력: db.exec("PRAGMA journal_mode = WAL");
  // 출력: db.exec("PRAGMA foreign_keys = ON");   // node:sqlite 는 기본이 ON 이지만 명시


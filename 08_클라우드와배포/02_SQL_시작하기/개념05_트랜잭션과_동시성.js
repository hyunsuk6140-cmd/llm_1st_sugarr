function 새재고db() {
  const db = new DatabaseSync(":memory:");
  db.exec("CREATE TABLE 재고 (품목 TEXT PRIMARY KEY, 수량 INTEGER NOT NULL) STRICT");
  db.exec("INSERT INTO 재고 VALUES ('볼트', 0)");
  return db;
}

async function 실험(설명, 한번처리) {
  const db = 새재고db();
  await Promise.all(Array.from({ length: 20 }, () => 한번처리(db)));
  const 수량 = db.prepare("SELECT 수량 FROM 재고 WHERE 품목 = '볼트'").get().수량;
  console.log(`${설명} → ${수량}`);
  db.close();
}

async function 전부실험() {
  // 방법 1: 읽고, 자바스크립트에서 더하고, 쓴다 (07단원에서 하던 방식)
  await 실험("읽고→더하고→쓰기 (사이에 await 있음)", async (db) => {
    const 지금 = db.prepare("SELECT 수량 FROM 재고 WHERE 품목 = '볼트'").get().수량;
    await new Promise((풀기) => setImmediate(풀기)); // ← 다른 요청에 순서를 넘김
    db.prepare("UPDATE 재고 SET 수량 = ? WHERE 품목 = '볼트'").run(지금 + 1);
  });
  // 출력: 읽고→더하고→쓰기 (사이에 await 있음) → 1

  // 방법 2: DB 안에서 더한다
  await 실험("수량 = 수량 + 1                    ", async (db) => {
    await new Promise((풀기) => setImmediate(풀기));
    db.prepare("UPDATE 재고 SET 수량 = 수량 + 1 WHERE 품목 = '볼트'").run();
  });
  // 출력: 수량 = 수량 + 1                     → 20

  await 이어서();
}

// ============================================================
// 6-2. 왜 1 이 됐나
// ============================================================
//
// 20개가 전부 "0" 을 읽었습니다.
//
//   요청1: 0 을 읽음 → await 에서 멈춤
//   요청2: 0 을 읽음 → await 에서 멈춤
//   ...
//   요청20: 0 을 읽음 → await 에서 멈춤
//   (여기서 첫 요청이 깨어남)
//   요청1: 0 + 1 = 1 을 씀
//   요청2: 0 + 1 = 1 을 씀   ← 자기가 읽어 둔 0 을 씁니다
//   ...
//
// 20번 다 썼는데 전부 1 을 썼습니다. 19건이 사라졌습니다.
// 07단원의 그 문제와 **똑같은** 문제입니다. DB 로 바꿔도 안 없어집니다.
//
// ★★★ 여기가 핵심입니다.
//
//   DB 를 쓴다고 경합이 저절로 사라지지 않습니다.
//   "읽어서 → 계산해서 → 쓴다" 는 모양 자체가 문제입니다.
//
//   해결은 **DB 한테 계산까지 시키는 것** 입니다.
//
//     ✗  const 지금 = 읽기();  쓰기(지금 + 1);
//     ○  UPDATE 재고 SET 수량 = 수량 + 1 WHERE ...
//
//   한 문장짜리 UPDATE 는 SQLite 가 통째로 처리합니다.
//   중간에 다른 요청이 끼어들 지점이 아예 없습니다.

// ============================================================
// 6-3. 그럼 await 없이 짜면 되나요?
// ============================================================
//
// 사실 node:sqlite 는 동기(Sync) 라서, 읽기와 쓰기 사이에 await 가
// 하나도 없으면 20 이 나옵니다. 자바스크립트가 한 번에 한 줄씩만 돌기 때문입니다.
//
// 그런데 그걸 믿으면 안 됩니다.
//
//   1) 실제 핸들러에는 await 가 들어갑니다.
//      로그를 파일에 쓰고, 다른 API 를 부르고, 파일을 저장합니다.
//      나중에 그 줄 하나가 추가되는 순간 조용히 깨집니다.
//
//   2) 서버를 두 대로 늘리면(PM2 클러스터, 08단원) 프로세스가 여러 개입니다.
//      한 프로세스 안에서 순서가 지켜져도 소용없습니다.
//
//   3) Postgres 나 Supabase 로 옮기면 전부 비동기입니다. (05단원)
//      그때 이 코드가 전부 문제가 됩니다.
//
// ★ "지금은 되네" 로 넘기지 말고 처음부터 안전한 모양으로 쓰세요.

// ============================================================
// 7. 그럼 트랜잭션으로 감싸면 되지 않나요
// ============================================================

async function 이어서() {
  const db = 새재고db();
  let 오류메시지 = "";

  await Promise.all(Array.from({ length: 5 }, () => (async () => {
    try {
      db.exec("BEGIN");
      const 지금 = db.prepare("SELECT 수량 FROM 재고 WHERE 품목 = '볼트'").get().수량;
      await new Promise((풀기) => setImmediate(풀기));
      db.prepare("UPDATE 재고 SET 수량 = ? WHERE 품목 = '볼트'").run(지금 + 1);
      db.exec("COMMIT");
    } catch (에러) {
      오류메시지 = 에러.message;
    }
  })()));

  console.log("트랜잭션으로 감싸면:", 오류메시지);
  // 출력: 트랜잭션으로 감싸면: cannot start a transaction within a transaction

  db.close();
  마무리();
}

// ★★ 안 됩니다. 오히려 터집니다.
//
//   트랜잭션은 **연결(connection) 단위** 입니다.
//   연결이 하나인데 요청 20개가 그 위에서 BEGIN 을 부르면 겹칩니다.
//
//   두 번째 요청의 BEGIN 이 첫 번째 요청의 트랜잭션 안에 들어가 버립니다.
//
// ★ 그래서 규칙이 이렇게 됩니다.
//
//   트랜잭션 안에서는 await 를 하지 마세요.
//
//     ✗  db.exec("BEGIN");
//        await 뭔가();          ← 여기서 다른 요청이 끼어듭니다
//        db.exec("COMMIT");
//
//     ○  const 자료 = await 뭔가();   ← 먼저 다 받아 두고
//        db.exec("BEGIN");
//        ... 동기 작업만 ...
//        db.exec("COMMIT");
//
//   node:sqlite 가 동기인 게 여기서는 오히려 도움이 됩니다.
//   BEGIN 과 COMMIT 사이에 await 만 없으면 안전합니다.

// ============================================================
// 8. 연결이 여러 개면 — database is locked
// ============================================================
//
// 파일 DB 를 두 곳에서 열면 이야기가 달라집니다.
// (서버 두 대, 또는 서버 하나 + DB 를 들여다보는 도구)
//
//   A: BEGIN 하고 쓰는 중
//   B: 같은 표에 쓰려고 함
//   →  B 에서 오류: database is locked
//
// SQLite 는 **쓰는 사람이 한 번에 한 명** 입니다.
//
// ★ 해결 방법 두 가지
//
//   1) busy_timeout — "잠겨 있으면 기다려라"
//
//        new DatabaseSync("데이터.db", { timeout: 5000 })
//
//      5초 동안 기다렸다가, 그래도 안 풀리면 그때 오류를 냅니다.
//      대부분의 잠깐 겹침은 이걸로 넘어갑니다.
//
//      ★★ 그런데 **평범한 BEGIN 에는 안 통하는 경우**가 있습니다.
//
//        BEGIN 은 기본이 DEFERRED 입니다. 읽을 때는 잠그지 않다가
//        중간에 쓰기가 나오면 그때 잠금을 올립니다.
//        그 순간 다른 쪽이 이미 쓰고 있으면 **기다리지 않고 바로** 오류입니다.
//        기다리면 서로 물고 늘어질(교착) 수 있어서 그렇게 정해져 있습니다.
//
//      ★ 트랜잭션 안에서 쓸 게 확실하면 처음부터 잠그고 시작하세요.
//
//        db.exec("BEGIN IMMEDIATE");
//
//        이러면 busy_timeout 이 제대로 듣습니다. 5초를 기다려 줍니다.
//
//   2) WAL 모드 — "읽는 사람은 안 막는다"
//
//        db.exec("PRAGMA journal_mode = WAL");
//
//      기본 모드에서는 쓰는 동안 읽기도 막힙니다.
//      WAL 을 켜면 쓰는 중에도 다른 연결이 읽을 수 있습니다.
//      (쓰기는 여전히 한 명입니다)
//
//      켜면 데이터.db 옆에 -wal, -shm 파일이 생깁니다. 정상입니다.
//      셋 다 같이 옮겨야 합니다.
//
// ★ 실무에서는 파일 DB 를 열 때 이 두 줄을 거의 항상 같이 씁니다.
//   04단원에서 실제로 그렇게 만듭니다.

const 실무설정 = [
  'const db = new DatabaseSync("데이터.db", { timeout: 5000 });',
  'db.exec("PRAGMA journal_mode = WAL");',
  'db.exec("PRAGMA foreign_keys = ON");   // node:sqlite 는 기본이 ON 이지만 명시',
];


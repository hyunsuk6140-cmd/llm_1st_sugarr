// ============================================================
// 5-2. SELECT * 를 쓰지 마세요
// ============================================================
//
//   ✗  SELECT * FROM 회원 WHERE id = ?
//   ○  SELECT id, 아이디, 이름 FROM 회원 WHERE id = ?
//
// * 를 쓰면 나중에 비밀번호 칸을 추가했을 때
// 그게 그대로 API 응답에 실려 나갑니다. 코드는 한 글자도 안 고쳤는데요.
//
// 필요한 칸만 적으세요. 칸이 늘어도 응답은 그대로입니다.

// ============================================================
// 6. WHERE — 조건 고르기
// ============================================================

// ★★★ 먼저 짚고 갑니다 — 아래 세기() 는 조건을 **문자열로 이어 붙입니다.**
//
//   여기 들어가는 조건은 전부 **내가 이 파일에 직접 적은 상수**입니다.
//   사용자가 보낸 값이 이 자리에 오면 그 즉시 SQL 인젝션이 됩니다.
//   왜 그런지는 8번에서 직접 뚫어 보고, 자리표시자(?)로 막습니다.
//
//   ★ 규칙 하나만 기억하세요. **값은 언제나 ? 로 넘깁니다.**
//     WHERE 조건 모양을 여러 개 보여 주려고 여기서만 이렇게 뒀습니다.
//     (값을 따로 넘길 수 있게 ...값들 자리는 열어 뒀습니다)

function 세기(조건, ...값들) {
  // 검증무시: 조건은 이 파일에 적힌 상수뿐입니다 (사용자 입력이 오면 안 됩니다)
  const 수 = db.prepare(`SELECT COUNT(*) AS n FROM 설비 WHERE ${조건}`).get(...값들).n;
  console.log(`${조건} → ${수}대`);
}

세기("라인 = 'A'");
// 출력: 라인 = 'A' → 2대
세기("온도 > 40");
// 출력: 온도 > 40 → 1대
세기("온도 BETWEEN 20 AND 30");
// 출력: 온도 BETWEEN 20 AND 30 → 3대
세기("라인 IN ('A', 'B')");
// 출력: 라인 IN ('A', 'B') → 4대
세기("이름 LIKE '프레스%'");
// 출력: 이름 LIKE '프레스%' → 2대
세기("이름 LIKE '%1호'");
// 출력: 이름 LIKE '%1호' → 5대
세기("라인 = 'A' AND 온도 > 40");
// 출력: 라인 = 'A' AND 온도 > 40 → 1대

// ★ LIKE 의 % 는 "아무 글자 몇 개든" 입니다.
//     '프레스%'  프레스로 시작
//     '%1호'     1호로 끝
//     '%로봇%'   로봇을 포함
//
// ★ _ 는 "아무 글자 정확히 한 개" 입니다. 잘 안 씁니다.

// ============================================================
// 6-2. NULL 은 = 로 비교가 안 됩니다
// ============================================================

세기("담당자 = NULL");
// 출력: 담당자 = NULL → 0대
세기("담당자 IS NULL");
// 출력: 담당자 IS NULL → 4대

// ★★ = NULL 은 항상 0건입니다. 오류도 안 납니다. 그냥 아무것도 안 나옵니다.
//   NULL 은 "값이 없음" 이라서 무엇과도 같지 않습니다. 자기 자신과도요.
//   IS NULL / IS NOT NULL 을 쓰세요.

// ★★★ 더 위험한 건 이겁니다.

세기("담당자 <> '김민준'");
// 출력: 담당자 <> '김민준' → 4대

console.log("전체:", db.prepare("SELECT COUNT(*) AS n FROM 설비").get().n, "대");
// 출력: 전체: 9 대
console.log("김민준 담당:", db.prepare("SELECT COUNT(*) AS n FROM 설비 WHERE 담당자 = '김민준'").get().n, "대");
// 출력: 김민준 담당: 1 대

// 전체 9대, 김민준이 1대인데 "김민준이 아닌" 게 4대?
// 9 - 1 = 8 이어야 할 것 같은데 4 입니다.
//
// 담당자가 NULL 인 4대가 빠졌기 때문입니다.
// NULL <> '김민준' 은 참도 거짓도 아닌 "모름" 이라서 걸러집니다.
//
// 이걸 원했다면 이렇게 써야 합니다.

세기("담당자 IS NULL OR 담당자 <> '김민준'");
// 출력: 담당자 IS NULL OR 담당자 <> '김민준' → 8대

// ★ 실무에서 "숫자가 안 맞아요" 의 절반은 이 NULL 때문입니다.
//   그래서 개념02 에서 "고민되면 NOT NULL 을 붙여라" 고 한 것입니다.

// ============================================================
// 7. ORDER BY · LIMIT
// ============================================================

const 더운순 = db.prepare(`
  SELECT 이름, 온도 FROM 설비
  WHERE 온도 IS NOT NULL
  ORDER BY 온도 DESC
  LIMIT 3
`).all();
console.log(JSON.stringify(더운순.map((설비) => `${설비.이름}(${설비.온도})`)));
// 출력: ["프레스 1호(41.2)","프레스 2호(39.8)","용접로봇 1호(36.5)"]

//   ORDER BY 온도       작은 것부터 (ASC 가 기본)
//   ORDER BY 온도 DESC  큰 것부터
//   ORDER BY 라인, 온도 DESC   라인으로 먼저, 같으면 온도로
//   LIMIT 3             3개만
//   LIMIT 3 OFFSET 10   11번째부터 3개 (11~13)

const 둘째장 = db.prepare("SELECT 이름 FROM 설비 ORDER BY id LIMIT 3 OFFSET 3").all();
console.log(JSON.stringify(둘째장.map((설비) => 설비.이름)));
// 출력: ["컨베이어 1호","검사기 1호","시험1"]

// ★★ ORDER BY 없이 LIMIT 을 쓰면 안 됩니다.
//   순서를 정하지 않으면 "어떤 3개" 인지 보장이 없습니다.
//   지금은 넣은 순서대로 나오지만, 자료가 많아지고 색인이 생기면 달라집니다.
//   (03단원 색인에서 다시 봅니다)

// ============================================================
// 7-2. 대소문자
// ============================================================

db.prepare("INSERT INTO 설비 (이름, 라인) VALUES (?, ?)").run("Pump A", "D");

세기("이름 = 'PUMP A'");
// 출력: 이름 = 'PUMP A' → 0대
세기("이름 LIKE 'PUMP A'");
// 출력: 이름 LIKE 'PUMP A' → 1대

// ★ = 는 대소문자를 가리고, LIKE 는 안 가립니다. (영문만 해당)
//   검색 기능을 만들 때 LIKE 를 쓰는 이유 중 하나입니다.
//   = 로도 안 가리게 하려면 칸을 만들 때 TEXT COLLATE NOCASE 를 붙입니다.

// ============================================================
// 8. ★★★ SQL 인젝션 — 직접 해 봅니다
// ============================================================
//
// 지금까지 값을 항상 ? 자리표시자로 넘겼습니다.
// 왜 그래야 하는지 이제 봅니다.

const 회원db = new DatabaseSync(":memory:");
회원db.exec("CREATE TABLE 회원 (id INTEGER PRIMARY KEY, 아이디 TEXT, 비번 TEXT, 등급 TEXT) STRICT");
회원db.exec(`
  INSERT INTO 회원 (아이디, 비번, 등급) VALUES
    ('kim', '1234', '일반'),
    ('admin', 's3cret', '관리자'),
    ('lee', 'abcd', '일반')
`);

// 흔히 이렇게 짭니다. 눈으로 보면 멀쩡해 보입니다.

function 위험한_로그인(아이디, 비번) {
  // 검증무시: 인젝션이 어떻게 뚫리는지 보여 주는 자리입니다 (바로 아래에서 막습니다)
  const sql = `SELECT * FROM 회원 WHERE 아이디 = '${아이디}' AND 비번 = '${비번}'`;
  return 회원db.prepare(sql).all();
}

console.log(위험한_로그인("kim", "1234").length);
// 출력: 1
console.log(위험한_로그인("kim", "틀린비번").length);
// 출력: 0

// 잘 동작합니다. 그런데 비번 칸에 이걸 칩니다.

const 공격 = "' OR '1'='1";
const 뚫린것 = 위험한_로그인("admin", 공격);
console.log("나온 줄 수:", 뚫린것.length);
// 출력: 나온 줄 수: 3

console.log(JSON.stringify(뚫린것.map((회원) => `${회원.아이디}/${회원.등급}`)));
// 출력: ["kim/일반","admin/관리자","lee/일반"]

// 비번을 모르는데 회원 명단이 통째로 나왔습니다. 비밀번호까지 같이요.
// 만들어진 SQL 을 눈으로 봅시다.

// 검증무시: 공격 문자열이 SQL 에 어떻게 박히는지 눈으로 보는 자리
console.log(`SELECT * FROM 회원 WHERE 아이디 = 'admin' AND 비번 = '${공격}'`);
// 출력: SELECT * FROM 회원 WHERE 아이디 = 'admin' AND 비번 = '' OR '1'='1'

//   (아이디 = 'admin' AND 비번 = '')   →  거짓
//   OR '1'='1'                        →  항상 참
//
// AND 가 OR 보다 먼저 묶이기 때문에 조건 전체가 "항상 참" 이 됐습니다.
// 그래서 admin 한 줄이 아니라 **모든 줄**이 나온 것입니다.
//
// 내가 넣은 따옴표가 SQL 의 따옴표를 닫아 버렸고,
// 그 뒤에 적은 글자가 "값" 이 아니라 "SQL 문법" 으로 읽혔습니다.
// 이게 SQL 인젝션입니다.
//
// ★ 보통 로그인 코드는 나온 것 중 첫 줄을 그 사람으로 칩니다.

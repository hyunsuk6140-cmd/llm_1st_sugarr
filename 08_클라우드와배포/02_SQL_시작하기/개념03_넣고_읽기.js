//
// ★ 순서가 상관없어지는 게 진짜 장점입니다.
//   { 라인: "C", 이름: "...", 담당자: "...", 온도: 20.1 } 로 줘도 됩니다.

// ============================================================
// 5. SELECT — 꺼내는 세 가지 방법

// ============================================================
// 개념 03 — 넣고 읽기 (INSERT · SELECT)
// ============================================================
//
// 표를 만들었으니 이제 자료를 넣고 꺼냅니다.
//
// 이 단원에서 제일 중요한 건 마지막 섹션입니다.
// 값을 SQL 문장에 직접 이어 붙이면 어떤 일이 벌어지는지
// 말로만 듣지 말고 직접 해 봅니다.
//
// 실행: node 개념03_넣고_읽기.js
// ============================================================

const { DatabaseSync } = require("node:sqlite");

const db = new DatabaseSync(":memory:");

db.exec(`
  CREATE TABLE 설비 (
    id     INTEGER PRIMARY KEY,
    이름   TEXT    NOT NULL UNIQUE,
    라인   TEXT    NOT NULL,
    온도   REAL,
    가동   INTEGER NOT NULL DEFAULT 1,
    담당자 TEXT
  ) STRICT
`);

// ============================================================
// 1. INSERT — 한 줄 넣기
// ============================================================

const 넣기 = db.prepare(`
  INSERT INTO 설비 (이름, 라인, 온도, 담당자) VALUES (?, ?, ?, ?)
`);

const 결과 = 넣기.run("용접로봇 1호", "A", 36.5, "김민준");
console.log(결과);
// 출력: { changes: 1, lastInsertRowid: 1 }

// changes         바뀐 줄 수
// lastInsertRowid 방금 들어간 줄의 id
//
// ★ lastInsertRowid 는 아주 자주 씁니다.
//   "만들고 나서 만든 걸 돌려주는" API 에서 이게 있어야 합니다.
//
//     const { lastInsertRowid } = 넣기.run(...);
//     const 만든것 = db.prepare("SELECT * FROM 설비 WHERE id = ?").get(lastInsertRowid);
//     res.status(201).json(만든것);

// ============================================================
// 2. prepare 는 한 번, run 은 여러 번
// ============================================================

const 자료 = [
  ["프레스 1호", "A", 41.2, "이서연"],
  ["프레스 2호", "B", 39.8, "이서연"],
  ["컨베이어 1호", "B", 25.0, null],
  ["검사기 1호", "C", 22.4, "박도윤"],
];

for (const [이름, 라인, 온도, 담당자] of 자료) {
  넣기.run(이름, 라인, 온도, 담당자);
}

console.log("총", db.prepare("SELECT COUNT(*) AS 개수 FROM 설비").get().개수, "대");
// 출력: 총 5 대

// ★ prepare 는 SQL 문장을 미리 해석해 두는 것입니다.
//   반복문 안에서 prepare 를 부르면 매번 다시 해석합니다. 느립니다.
//
//     ✗  for (...) { db.prepare("INSERT ...").run(...); }
//     ○  const 넣기 = db.prepare("INSERT ..."); for (...) { 넣기.run(...); }
//
//   서버에서는 보통 파일 맨 위나 저장소(repository) 모듈에서 한 번만 준비합니다.

// ============================================================
// 3. 자리표시자에 넣을 수 있는 값 / 없는 값
// ============================================================
//
// 여기서 학생들이 제일 많이 막힙니다. 재 봤습니다.

function 시도(설명, 하기) {
  try {
    하기();
    console.log(`${설명} → 통과`);
  } catch (에러) {
    console.log(`${설명} → 오류: ${에러.message}`);
  }
}

시도("숫자     ", () => 넣기.run("시험1", "Z", 10, null));
// 출력: 숫자      → 통과
시도("null     ", () => 넣기.run("시험2", "Z", null, null));
// 출력: null      → 통과
시도("true     ", () => 넣기.run("시험3", "Z", 10, true));
// 출력: true      → 오류: Provided value cannot be bound to SQLite parameter 4.
시도("undefined", () => 넣기.run("시험4", "Z", 10, undefined));
// 출력: undefined → 오류: Provided value cannot be bound to SQLite parameter 4.

// ★★ true / false 를 못 넣습니다. SQLite 에 참거짓 타입이 없기 때문입니다.
//   1 과 0 으로 바꿔서 넣으세요.
//
//     넣기.run(이름, 라인, 온도, 가동 ? 1 : 0);
//
//   꺼낼 때도 1/0 으로 나옵니다. 필요하면 Boolean(행.가동) 으로 바꿔 쓰세요.
//
// ★★ undefined 도 못 넣습니다. null 로 바꿔야 합니다.
//
//   이게 왜 무서우냐면 — req.body.담당자 처럼 클라이언트가 안 보낸 값이
//   그대로 undefined 라서, 평소엔 잘 되다가 그 필드만 빠지면 500 이 납니다.
//
//     ✗  넣기.run(몸.이름, 몸.라인, 몸.온도, 몸.담당자);
//     ○  넣기.run(몸.이름, 몸.라인, 몸.온도, 몸.담당자 ?? null);
//
//   ?? (널 병합) 는 undefined 와 null 일 때만 오른쪽을 씁니다.
//   || 를 쓰면 0 이나 "" 까지 바뀌어 버리니 ?? 를 쓰세요.

// ============================================================
// 3-2. 인자를 적게 주면? — 조용히 통과합니다
// ============================================================

시도("인자 4개 중 2개만", () => 넣기.run("시험5", "Z"));
// 출력: 인자 4개 중 2개만 → 통과

const 시험5 = db.prepare("SELECT 온도, 담당자 FROM 설비 WHERE 이름 = ?").get("시험5");
console.log({ ...시험5 });
// 출력: { '온도': null, '담당자': null }

// ★★★ 오류가 안 납니다. 안 준 자리는 NULL 이 됩니다.
//
//   이게 제일 찾기 힘든 버그입니다.
//   칸을 하나 추가했는데 run(...) 은 안 고쳤다 — 오류는 없고, 값만 비어 있습니다.
//   며칠 뒤에 "왜 담당자가 다 비어 있지?" 하고 발견합니다.
//
//   반대로 많이 주면 오류가 납니다.

시도("인자를 더 많이  ", () => 넣기.run("시험6", "Z", 10, null, 999));
// 출력: 인자를 더 많이   → 오류: column index out of range


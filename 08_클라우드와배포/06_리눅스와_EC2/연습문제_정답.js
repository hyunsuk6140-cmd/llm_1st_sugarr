function 어디를볼까(메시지) {
  const 표 = {
    "Connection timed out": "보안 그룹(방화벽)",
    "Connection refused": "서버가 안 떴거나 포트가 다름",
    "Permission denied (publickey)": "키 경로·사용자 이름",
    "No such file or directory": "경로 (대소문자 확인)",
    "Address already in use": "그 포트를 이미 쓰는 프로세스",
  };

  return 표[메시지] ?? "모르겠습니다";
}

for (const 메시지 of ["Connection timed out", "Connection refused",
  "Permission denied (publickey)", "No such file or directory", "Address already in use"]) {
  console.log(`${메시지} → ${어디를볼까(메시지)}`);
}
// 출력: Connection timed out → 보안 그룹(방화벽)
// 출력: Connection refused → 서버가 안 떴거나 포트가 다름
// 출력: Permission denied (publickey) → 키 경로·사용자 이름
// 출력: No such file or directory → 경로 (대소문자 확인)
// 출력: Address already in use → 그 포트를 이미 쓰는 프로세스

// ★★★ timed out 과 refused 를 구분하는 게 이 문제의 핵심입니다.
//
//   timed out  패킷이 아예 안 갑니다. **중간에서 막혔습니다.**
//              → 보안 그룹을 보세요. 서버 안은 볼 필요가 없습니다.
//
//   refused    서버까지는 갔습니다. 그 포트에 아무도 없습니다.
//              → 서버 안을 보세요. 방화벽은 문제가 아닙니다.
//
//   이 하나로 "어디를 볼지" 가 절반 정해집니다.
//   모르고 헤매면 방화벽을 열었다 닫았다 하면서 시간을 씁니다.
//
// ★ Address already in use 를 만나면
//
//     sudo lsof -i :3000        누가 쓰는지 봅니다
//     kill $(sudo lsof -t -i:3000)
//
//   보통은 아까 띄운 서버가 아직 살아 있는 것입니다.



function CIDR판정(표기) {
  const [, 비트] = 표기.split("/");
  const 개수 = 2 ** (32 - Number(비트));

  return Number(비트) === 0 ? `${개수}개 ★위험` : `${개수}개`;
}

for (const 표기 of ["0.0.0.0/0", "1.2.3.4/32", "10.0.0.0/16", "192.168.0.0/24"]) {
  console.log(`${표기} → ${CIDR판정(표기)}`);
}
// 출력: 0.0.0.0/0 → 4294967296개 ★위험
// 출력: 1.2.3.4/32 → 1개
// 출력: 10.0.0.0/16 → 65536개
// 출력: 192.168.0.0/24 → 256개

// ★ /뒤의 숫자는 "앞에서 몇 비트가 고정인가" 입니다.
//   IPv4 는 32비트니까 나머지 (32 - 비트) 만큼이 자유입니다.
//
//     /32  전부 고정 → 딱 한 대
//     /24  앞 24비트 고정 → 마지막 자리만 자유 → 256개
//     /0   아무것도 안 고정 → 전부 → 43억 개
//
// ★★ AWS 화면에서 "내 IP" 를 고르면 /32 가 들어갑니다.
//   "위치 무관" 을 고르면 /0 입니다. 22번에는 절대 쓰지 마세요.



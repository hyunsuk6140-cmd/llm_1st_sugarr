function 키만들어보기() {
  const 폴더 = path.join(os.tmpdir(), "연습키폴더");
  fs.rmSync(폴더, { recursive: true, force: true });
  fs.mkdirSync(폴더, { recursive: true });

  const 키경로 = path.join(폴더, "연습키");

  execFileSync("ssh-keygen", ["-t", "ed25519", "-C", "practice", "-f", 키경로, "-N", ""], {
    stdio: "ignore",
  });

  console.log("파일 2개 생겼나:", fs.readdirSync(폴더).length === 2);
  // 출력: 파일 2개 생겼나: true

  const 공개키 = fs.readFileSync(`${키경로}.pub`, "utf-8").trim();

  console.log("공개키가 한 줄인가:", 공개키.split("\n").length === 1);
  // 출력: 공개키가 한 줄인가: true
  console.log("공개키가 ssh-ed25519 로 시작하나:", 공개키.startsWith("ssh-ed25519"));
  // 출력: 공개키가 ssh-ed25519 로 시작하나: true

  fs.rmSync(폴더, { recursive: true, force: true });
  console.log("정리했나:", !fs.existsSync(폴더));
  // 출력: 정리했나: true
}


function 권한표기(숫자) {
  return String(숫자)
    .padStart(3, "0")
    .split("")
    .map(Number)
    .map((값) => ((값 & 4) ? "r" : "-") + ((값 & 2) ? "w" : "-") + ((값 & 1) ? "x" : "-"))
    .join("");
}

for (const 숫자 of [600, 644, 755, 400, 777]) {
  console.log(`${숫자} → ${권한표기(숫자)}`);
}
// 출력: 600 → rw-------
// 출력: 644 → rw-r--r--
// 출력: 755 → rwxr-xr-x
// 출력: 400 → r--------
// 출력: 777 → rwxrwxrwx

// ★ & 는 비트 AND 입니다. 값에 그 권한이 들어 있는지 봅니다.
//     6 & 4 = 4 (참) → 읽기 있음
//     6 & 1 = 0 (거짓) → 실행 없음
//
// ★ padStart(3, "0") 을 쓴 이유
//   chmod 40 처럼 두 자리로 적는 경우가 있습니다. 040 으로 봐야 맞습니다.


// ───── 문제 4 ─────
function 권한숫자(표기) {
  const 값 = [0, 1, 2].map((묶음) => {
    const 세글자 = 표기.slice(묶음 * 3, 묶음 * 3 + 3);
    return (세글자[0] === "r" ? 4 : 0) + (세글자[1] === "w" ? 2 : 0) + (세글자[2] === "x" ? 1 : 0);
  });

  return Number(값.join(""));
}

for (const 표기 of ["rw-------", "rwxr-xr-x", "r--r--r--"]) {
  console.log(`${표기} → ${권한숫자(표기)}`);
}
// 출력: rw------- → 600
// 출력: rwxr-xr-x → 755
// 출력: r--r--r-- → 444

// ★ ls -la 의 출력을 읽을 때 이 계산을 머릿속으로 합니다.
//     -rw-r--r--  1 ubuntu ubuntu  1024 ...
//      ↑ 맨 앞 한 글자는 종류입니다. - 는 파일, d 는 폴더, l 은 링크
//      그다음 9글자가 권한입니다.
//
// ★ 문제 3 과 문제 4 는 서로 반대입니다.
//   권한숫자(권한표기(755)) === 755 가 되는지 확인해 보세요.

console.log("왕복이 맞나:", 권한숫자(권한표기(755)) === 755);
// 출력: 왕복이 맞나: true



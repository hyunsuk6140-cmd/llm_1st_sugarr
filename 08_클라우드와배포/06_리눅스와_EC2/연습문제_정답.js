function 프리티어판정(대수, 하루시간, 일수 = 30) {
  const 총시간 = 대수 * 하루시간 * 일수;
  const 한도 = 750;

  return 총시간 <= 한도
    ? `${총시간}시간 → 안전`
    : `${총시간}시간 → 초과 ${총시간 - 한도}시간`;
}


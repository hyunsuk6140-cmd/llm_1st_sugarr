function 실행방법판정(방법) {
  const 표 = {
    "node 서버.js": ["SSH닫으면죽음", "안살아남", "재부팅안뜸"],
    "node 서버.js &": ["SSH닫으면죽음", "안살아남", "재부팅안뜸"],
    "nohup node 서버.js &": ["SSH닫아도삶", "안살아남", "재부팅안뜸"],
    "systemd": ["SSH닫아도삶", "살아남", "재부팅뜸"],
    "PM2 (startup 등록)": ["SSH닫아도삶", "살아남", "재부팅뜸"],
  };

  return (표[방법] ?? ["모름", "모름", "모름"]).join(" / ");
}

for (const 방법 of ["node 서버.js", "node 서버.js &", "nohup node 서버.js &",
  "systemd", "PM2 (startup 등록)"]) {
  console.log(`${방법} : ${실행방법판정(방법)}`);
}
// 출력: node 서버.js : SSH닫으면죽음 / 안살아남 / 재부팅안뜸
// 출력: node 서버.js & : SSH닫으면죽음 / 안살아남 / 재부팅안뜸
// 출력: nohup node 서버.js & : SSH닫아도삶 / 안살아남 / 재부팅안뜸
// 출력: systemd : SSH닫아도삶 / 살아남 / 재부팅뜸
// 출력: PM2 (startup 등록) : SSH닫아도삶 / 살아남 / 재부팅뜸

// ★★★ 두 번째 줄이 이 문제의 핵심입니다.
//
//   & 를 붙이면 살아남을 것 같지만 아닙니다.
//   & 는 "터미널 프롬프트를 돌려 달라" 는 뜻일 뿐입니다.
//   그 프로세스는 여전히 그 터미널에 속해 있어서 SIGHUP 을 같이 받습니다.
//
//   이걸 모르면 "백그라운드로 돌렸는데 왜 죽지" 로 한참 헤맵니다.
//
// ★ 정확히는 "연결이 끊기면" 입니다.
//
//   exit 로 얌전히 나갈 때는 bash 의 huponexit(기본값 off) 때문에
//   안 죽기도 합니다. 셸 설정에 따라 갈립니다.
//   창을 그냥 닫거나 네트워크가 끊기면 확실히 죽습니다.
//

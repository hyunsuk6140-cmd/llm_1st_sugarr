// ============================================================
// 7. ★★ 공인 IP 가 바뀝니다
// ============================================================
//
// 인스턴스를 **중지했다 켜면 공인 IP 가 바뀝니다.**
//
//   어제 접속하던 주소로 오늘 접속하면 timed out 이 납니다.
//   도메인을 연결해 뒀다면 그것도 끊깁니다.
//
// ★ 해결: 탄력적 IP (Elastic IP)
//
//   고정 IP 를 하나 받아서 인스턴스에 붙입니다. 그러면 안 바뀝니다.
//
//   EC2 → 탄력적 IP → 탄력적 IP 주소 할당 → 작업 → 주소 연결
//
// ★★★ 요금 주의
//
//   **2024년 2월 1일부터 모든 공인 IPv4 에 시간당 요금이 붙습니다.**
//   인스턴스에 붙어 있어도 나갑니다. 한 개에 한 달 3~4달러쯤입니다.
//   (프리티어 안에서는 월 750시간까지 덮어 줍니다)
//
//   ★ 예전 자료에는 "붙어 있으면 무료" 라고 적혀 있습니다. 지금은 틀립니다.
//     개념01 에서 "숫자를 외우지 말라" 고 한 게 이런 이유입니다.
//
//   실습을 끝내고 인스턴스를 종료하면 탄력적 IP 가 붕 뜹니다.
//   붙어 있을 때보다 **더 비싸집니다.** 인스턴스를 지울 때 IP 도 해제(release) 하세요.
//
//   지금 조건은 aws.amazon.com/ko/free 에서 확인하세요.

function IP요금(시간당달러, 시간 = 720, 환율 = 1400) {
  return Math.round(시간당달러 * 시간 * 환율);
}

console.log("시간당 $0.005 인 IP 를 한 달 놀리면:", IP요금(0.005).toLocaleString("ko-KR"), "원");
// 출력: 시간당 $0.005 인 IP 를 한 달 놀리면: 5,040 원


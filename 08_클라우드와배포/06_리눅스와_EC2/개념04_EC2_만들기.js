function 유형읽기(이름) {
  const 맞음 = 이름.match(/^([a-z]+)(\d+)([a-z]*)\.(\w+)$/);
  if (!맞음) return "형태가 다릅니다";

  const [, 계열, 세대, 옵션, 크기] = 맞음;

  const 계열설명 = { t: "범용(순간 성능)", m: "범용", c: "계산 중심", r: "메모리 중심" }[계열] ?? "기타";
  const 옵션설명 = 옵션.includes("g") ? " / ARM 칩" : "";

  return `${계열설명} ${세대}세대${옵션설명} / 크기 ${크기}`;
}


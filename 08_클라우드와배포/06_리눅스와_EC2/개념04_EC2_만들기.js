//   막으면 아무것도 설치가 안 됩니다.

// ── CIDR 읽는 법 ──

function CIDR읽기(표기) {
  const [주소, 비트] = 표기.split("/");
  const 개수 = 2 ** (32 - Number(비트));
  return `${주소} 부터 ${개수.toLocaleString("ko-KR")}개 주소`;
}

for (const 표기 of ["0.0.0.0/0", "1.2.3.4/32", "10.0.0.0/16", "192.168.1.0/24"]) {
  console.log(`${표기} → ${CIDR읽기(표기)}`);
}
// 출력: 0.0.0.0/0 → 0.0.0.0 부터 4,294,967,296개 주소
// 출력: 1.2.3.4/32 → 1.2.3.4 부터 1개 주소
// 출력: 10.0.0.0/16 → 10.0.0.0 부터 65,536개 주소
// 출력: 192.168.1.0/24 → 192.168.1.0 부터 256개 주소

// ★ /32 는 딱 한 대입니다. "내 IP" 를 고르면 이게 들어갑니다.

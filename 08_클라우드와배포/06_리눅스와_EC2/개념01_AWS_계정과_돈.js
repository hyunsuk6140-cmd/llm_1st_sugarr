// ============================================================
// 6. 요금이 얼마나 나올 수 있나 — 감을 잡아 봅시다
// ============================================================
//
// 숫자는 바뀝니다. 자릿수의 감만 잡으세요.

function 한달요금(시간당달러, 시간 = 720, 환율 = 1400) {
  const 달러 = 시간당달러 * 시간;
  return { 달러: Math.round(달러 * 100) / 100, 원: Math.round(달러 * 환율) };
}

const 예시들 = [
  ["아주 작은 인스턴스", 0.0126],
  ["보통 인스턴스", 0.05],
  ["큰 인스턴스", 0.2],
  ["아주 큰 인스턴스", 1.0],
];

for (const [이름, 시간당] of 예시들) {
  const 결과 = 한달요금(시간당);
  console.log(`${이름}: 시간당 $${시간당} → 한 달 $${결과.달러} (약 ${결과.원.toLocaleString("ko-KR")}원)`);
}
// 출력: 아주 작은 인스턴스: 시간당 $0.0126 → 한 달 $9.07 (약 12,701원)
// 출력: 보통 인스턴스: 시간당 $0.05 → 한 달 $36 (약 50,400원)

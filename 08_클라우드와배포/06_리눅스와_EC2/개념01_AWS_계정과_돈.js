//
//   Vercel · Netlify   프론트엔드에 아주 편합니다. 서버는 제약이 있습니다.
//   Railway · Render   훨씬 쉽습니다. 대신 배우는 게 적습니다.
//   Cloudtype · NHN    국내 서비스. 한국어 지원이 좋습니다.
//   AWS EC2            어렵습니다. 대신 **무슨 일이 일어나는지 다 보입니다.**
//
// ★★ 이 수업이 EC2 를 고른 이유
//
//   리눅스·SSH·프로세스·포트·방화벽을 직접 만지게 됩니다.
//   쉬운 서비스들은 이걸 다 가려 줍니다. 편하지만 안 배웁니다.
//
//   한 번 EC2 로 해 보면 다른 서비스는 다 쉬워집니다. 반대는 아닙니다.
//   그리고 회사 채용 공고에 AWS 가 압도적으로 많이 적혀 있습니다.


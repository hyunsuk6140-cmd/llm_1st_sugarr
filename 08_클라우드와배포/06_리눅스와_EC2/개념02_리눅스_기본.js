// 2. 권한 숫자의 뜻
// ============================================================
//
// chmod 600 의 600 이 뭘까요? 계산해 봅시다.

function 권한풀기(숫자) {
  const 자리 = String(숫자).padStart(3, "0").split("").map(Number);
  const 대상 = ["소유자", "그룹", "그 외"];

  return 자리.map((값, 자리번호) => {
    const 읽기 = (값 & 4) ? "r" : "-";
    const 쓰기 = (값 & 2) ? "w" : "-";
    const 실행 = (값 & 1) ? "x" : "-";
    return `${대상[자리번호]}=${읽기}${쓰기}${실행}`;
  }).join(" ");
}

for (const 숫자 of [600, 644, 755, 777, 400, 700]) {
  console.log(`${숫자} → ${권한풀기(숫자)}`);
}
// 출력: 600 → 소유자=rw- 그룹=--- 그 외=---
// 출력: 644 → 소유자=rw- 그룹=r-- 그 외=r--
// 출력: 755 → 소유자=rwx 그룹=r-x 그 외=r-x
// 출력: 777 → 소유자=rwx 그룹=rwx 그 외=rwx
// 출력: 400 → 소유자=r-- 그룹=--- 그 외=---
// 출력: 700 → 소유자=rwx 그룹=--- 그 외=---

// ★ 자리마다 세 사람입니다. 왼쪽부터 소유자 / 그룹 / 그 외 누구나.
// ★ 숫자는 더한 값입니다. 읽기 4 + 쓰기 2 + 실행 1.
//
//     7 = 4+2+1 = 읽기·쓰기·실행
//     6 = 4+2   = 읽기·쓰기
//     5 = 4+1   = 읽기·실행
//     4 = 4     = 읽기만
//
// ★★ 자주 쓰는 것 네 개만 외우면 됩니다.
//
//     600  나만 읽고 쓰기        ← .env, SSH 개인키
//     644  나만 쓰고 남들은 읽기  ← 보통 파일
//     700  나만 다 하기          ← 폴더
//     755  나만 쓰고 남들은 읽고 들어가기 ← 웹 폴더

console.log("700 이 폴더에서 뜻하는 것:", 권한풀기(700));
// 출력: 700 이 폴더에서 뜻하는 것: 소유자=rwx 그룹=--- 그 외=---

// ★★★ 폴더에서는 뜻이 다릅니다. 여기서 많이 헷갈립니다.
//

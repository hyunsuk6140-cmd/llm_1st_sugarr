function 저장요금(GB, 달당달러 = 0.025, 환율 = 1400) {
  return Math.round(GB * 달당달러 * 환율);
}

console.log("10GB 한 달:", 저장요금(10).toLocaleString("ko-KR"), "원");
// 출력: 10GB 한 달: 350 원
console.log("1TB 한 달:", 저장요금(1024).toLocaleString("ko-KR"), "원");

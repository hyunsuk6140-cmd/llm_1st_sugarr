// ============================================================
// 2. 가짜 S3 — 인터넷 없이 확인하려고
// ============================================================
//
// 05단원의 가짜Supabase.js 와 같은 생각입니다.
// 진짜 SDK 를 쓰되, 네트워크 대신 메모리가 대답하게 만듭니다.

function 가짜S3만들기() {
  const 안에든것 = new Map(); // 키 → { 내용, 종류 }

  return {
    async send(명령) {
      const 이름 = 명령.constructor.name;
      const 입력 = 명령.input;

      // ★ 입력.Bucket 을 아예 안 봅니다. 버킷을 틀리게 줘도 그냥 됩니다.
      //   진짜라면 NoSuchBucket·AccessDenied 가 납니다. (아래 한계 ①)

      if (이름 === "PutObjectCommand") {
        안에든것.set(입력.Key, { 내용: Buffer.from(입력.Body), 종류: 입력.ContentType });
        return { ETag: '"가짜"' };
      }

      if (이름 === "HeadObjectCommand") {
        const 것 = 안에든것.get(입력.Key);
        if (!것) {
          const 에러 = new Error("NotFound");
          에러.name = "NotFound";
          에러.$metadata = { httpStatusCode: 404 };
          throw 에러;
        }
        return { ContentLength: 것.내용.length, ContentType: 것.종류 };
      }

      if (이름 === "GetObjectCommand") {
        const 것 = 안에든것.get(입력.Key);
        if (!것) {
          const 에러 = new Error("NoSuchKey");
          에러.name = "NoSuchKey";
          throw 에러;
        }
        // ★ 진짜 Body 는 스트림이라 transformToByteArray()·pipe() 도 있습니다. (한계 ②)
        return { Body: { transformToString: async () => 것.내용.toString("utf-8") } };
      }

      if (이름 === "DeleteObjectCommand") {
        // ★ 있든 없든 성공합니다. 진짜 S3 와 같습니다.
        안에든것.delete(입력.Key);
        return {};
      }

      if (이름 === "ListObjectsV2Command") {
        // ★ ContinuationToken·MaxKeys·IsTruncated 를 전부 무시하고 한 번에 다 줍니다. (한계 ③)
        const 접두 = 입력.Prefix ?? "";
        const 키들 = [...안에든것.keys()].filter((키) => 키.startsWith(접두)).sort();

        // ★ 하나도 없으면 Contents 가 아예 없습니다. 진짜 S3 와 같습니다.
        return 키들.length === 0
          ? { KeyCount: 0 }
          : { KeyCount: 키들.length, Contents: 키들.map((키) => ({ Key: 키, Size: 안에든것.get(키).내용.length })) };
      }

      throw new Error(`가짜 S3 가 모르는 명령: ${이름}`);
    },

    지금든것: () => [...안에든것.keys()].sort(),
  };
}

// ★★ 이 가짜가 진짜와 같게 흉내 낸 것 두 가지가 중요합니다.
//
//   ① DeleteObject 는 없는 것을 지워도 성공합니다
//   ② ListObjectsV2 는 하나도 없으면 Contents 가 undefined 입니다
//
//   이 둘이 갈아 끼울 때 걸리는 지점이라 일부러 흉내 냈습니다.

// ★★★ 반대로 **흉내 내지 않은 것**도 알아 두세요. 여기서 헛짚기 쉽습니다.
//
//   ① Bucket 을 아예 안 봅니다
//      버킷 이름을 틀리게 줘도 그냥 성공합니다.
//      진짜라면 NoSuchBucket 이나 AccessDenied 가 납니다. (개념03 의 7번)
//      → 버킷 이름·IAM 권한 문제는 이 가짜로 **못 잡습니다.** 진짜 버킷에서 확인하세요.
//
//   ② Body 에 transformToString 만 있습니다
//      진짜 응답의 Body 는 스트림이라 transformToByteArray() 와 pipe() 도 있습니다.
//      개념03 의 4번대로 이미지(바이너리) 를 받으려 하면 여기서는 터집니다.
//      → 이 가짜로는 글자 파일까지만 시험할 수 있습니다.
//
//   ③ 페이지네이션이 없습니다
//      ContinuationToken·IsTruncated·MaxKeys 를 전부 무시하고 한 번에 다 줍니다.
//      진짜는 한 번에 1000개에서 끊깁니다. (개념03 의 6번)
//      → do/while 로 이어받는 코드가 맞는지는 이 가짜로 확인할 수 없습니다.
//
//   ★★ 가짜는 **여기까지가 한계**라고 적어 두는 것이 중요합니다.
//     적어 두지 않으면 "시험이 통과했으니 됐다" 고 믿게 됩니다.
//     05단원의 가짜Supabase 도 같은 이유로 못 하는 것을 적어 뒀습니다.
//     ★ 가짜가 진짜보다 **친절하면** 시험이 아무것도 못 잡습니다.
//   가짜를 만들 때는 "편한 대로" 가 아니라 **진짜의 까다로운 부분**을 흉내 내야
//   시험이 값어치가 있습니다.

// ============================================================
// 3. 디스크 판 (09단원 그대로)
// ============================================================

function 디스크저장소만들기(업로드폴더) {
  fs.mkdirSync(업로드폴더, { recursive: true });

  const 디스크 = {
    경로: async (저장이름) => path.join(업로드폴더, 저장이름),

    있나: async (저장이름) => fs.existsSync(path.join(업로드폴더, 저장이름)),

    저장: async (저장이름, 내용) => {
      await fs.promises.writeFile(path.join(업로드폴더, 저장이름), 내용);
    },

    지우기: async (저장이름) => {
      try {
        await fs.promises.unlink(path.join(업로드폴더, 저장이름));
        return true;
      } catch (에러) {
        if (에러.code === "ENOENT") return false;
        throw 에러;
      }
    },

    전부목록: async () => fs.readdirSync(업로드폴더).sort(),
  };

  return 디스크;
}


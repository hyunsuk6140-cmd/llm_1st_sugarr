function 가려서보기(설정) {
  const 복사 = { ...설정 };
  for (const 키이름 of Object.keys(복사)) {
    if (/KEY|SECRET|PASSWORD|TOKEN/i.test(키이름)) {
      const 값 = String(복사[키이름]);
      복사[키이름] = 값.slice(0, 4) + "***" + `(${값.length}자)`;
    }
  }
  return 복사;
}


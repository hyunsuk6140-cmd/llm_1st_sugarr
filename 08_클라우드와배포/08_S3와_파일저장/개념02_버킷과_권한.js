const 정책 = {
  Version: "2012-10-17",
  Statement: [
    {
      Sid: "그버킷의파일만",
      Effect: "Allow",
      Action: ["s3:PutObject", "s3:GetObject", "s3:DeleteObject"],
      Resource: "arn:aws:s3:::내버킷이름/uploads/*",
    },
    {
      Sid: "목록조회는버킷에",
      Effect: "Allow",
      Action: ["s3:ListBucket"],
      Resource: "arn:aws:s3:::내버킷이름",
      Condition: { StringLike: { "s3:prefix": ["uploads/*"] } },
    },
  ],
};

console.log(JSON.stringify(정책.Statement[0].Action));
// 출력: ["s3:PutObject","s3:GetObject","s3:DeleteObject"]
console.log(정책.Statement[0].Resource);
// 출력: arn:aws:s3:::내버킷이름/uploads/*
console.log(정책.Statement[1].Resource);
// 출력: arn:aws:s3:::내버킷이름

// ★★★ 두 Statement 의 Resource 가 다릅니다. 여기서 많이 막힙니다.
//
//   파일 동작(PutObject 등)  →  버킷이름/키패턴   ← 뒤에 /* 가 붙습니다
//   목록 조회(ListBucket)     →  버킷이름          ← /* 가 없습니다
//
//   ListBucket 은 "버킷" 에 대한 동작이고, GetObject 는 "객체" 에 대한 동작이라
//   가리키는 대상이 다릅니다.
//
//   이걸 헷갈리면 "파일은 올라가는데 목록이 안 나온다" 가 됩니다.
//
// ★ uploads/* 로 좁힌 것도 눈여겨보세요.
//   그 서버는 uploads/ 아래만 만질 수 있습니다.
//   같은 버킷의 backups/ 는 못 건드립니다.

// ── 권한 판정을 코드로 확인해 봅시다 ──

function 허용되나(정책, 동작, 자원) {
  return 정책.Statement.some((문장) => {
    if (문장.Effect !== "Allow") return false;
    if (!문장.Action.includes(동작)) return false;

    // * 를 아무 글자로 바꿔서 견줍니다
    const 규칙 = new RegExp("^" + 문장.Resource.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\\\*/g, ".*") + "$");
    return 규칙.test(자원);
  });
}


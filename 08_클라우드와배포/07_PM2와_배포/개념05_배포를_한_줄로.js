// ============================================================
//
// 셸 스크립트는 기본적으로 **실패해도 다음 줄을 계속합니다.**
//
//   #!/bin/bash
//   git pull          # 실패
//   npm ci            # 그래도 실행됨
//   pm2 reload 앱     # 그래도 실행됨
//
// 맨 위에 이 한 줄을 넣으면 달라집니다.
//
//   set -e            # 하나라도 실패하면 즉시 멈춤
//
// ★ 더 챙기면 이렇게 씁니다.
//
//   set -euo pipefail
//
//     -e            실패하면 멈춤
//     -u            정의 **안 된** 변수를 쓰면 멈춤 (빈 문자열은 못 잡습니다 ★ 아래)
//     -o pipefail   파이프 중간이 실패해도 잡음
//
// 이 세 개가 셸 스크립트의 기본 안전장치입니다. 외워 두세요.
//
// ★★★ 그런데 -u 만 믿으면 안 됩니다. 여기서 아주 많이 오해합니다.
//
//   06단원에서 이야기한 그 사고입니다.
//
//     rm -rf $DEPLOY_DIR/*     ← 변수가 비면 rm -rf /* 가 됩니다
//
//   -u 는 변수가 **아예 없을 때(unset)** 만 잡습니다.
//   DEPLOY_DIR="" 처럼 **빈 문자열**이면 -u 는 조용히 넘어갑니다.
//   그리고 실제 사고는 대개 이쪽입니다. 앞 줄이 실패해서 빈 값이 들어가는 식입니다.
//
//     set -u; X= ; echo "[$X]"        → []                    (안 멈춥니다)
//     set -u; echo "[$NO_SUCH]"       → NO_SUCH: unbound variable (멈춥니다)
//
// ★★ 진짜 방어책은 ${변수:?} 입니다.
//
//     rm -rf "${DEPLOY_DIR:?DEPLOY_DIR 가 비었습니다}"/*
//
//   :? 는 **없거나 비어 있으면** 메시지를 내고 그 자리에서 죽습니다.
//   따옴표도 꼭 씌우세요. 경로에 공백이 있으면 단어가 쪼개집니다.
//   슬래시는 따옴표 **밖**에 둡니다. 안에 넣으면 "경로/" 가 한 덩어리가 됩니다.

// ── 논리를 실제로 확인해 봅시다 ──

function 단계실행(단계들, 멈출까) {
  const 한것 = [];

  for (const [이름, 성공하나] of 단계들) {
    한것.push(이름);

    if (!성공하나) {
      한것.push(`✗ ${이름} 실패`);
      if (멈출까) {
        한것.push("멈춤");
        return { 한것, 끝까지갔나: false };
      }
    }
  }

  return { 한것, 끝까지갔나: true };
}


// ============================================================
// 7. 스크립트를 실제로 시험해 봅니다
// ============================================================

const 연습폴더 = path.join(os.tmpdir(), "배포연습");
fs.rmSync(연습폴더, { recursive: true, force: true });
fs.mkdirSync(연습폴더, { recursive: true });

// set -e 가 정말 멈추는지 봅니다 (Git Bash 가 있으면)
const 시험스크립트 = path.join(연습폴더, "시험.sh");
fs.writeFileSync(시험스크립트, [
  "#!/bin/bash",
  "set -e",
  'echo "1단계"',
  "false", // 실패하는 명령
  'echo "2단계"', // 여기까지 오면 안 됩니다
].join("\n"), "utf-8");

function 셸시험() {
  try {
    const 결과 = execFileSync("bash", [시험스크립트], { encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] });
    return { 끝까지: true, 출력: 결과.trim() };
  } catch (에러) {
    return { 끝까지: false, 출력: (에러.stdout ?? "").trim() };
  }
}

let 시험결과;
try {
  시험결과 = 셸시험();
} catch (에러) {
  시험결과 = null; // bash 가 없는 환경
}

if (시험결과) {
  console.log("set -e 스크립트가 끝까지 갔나:", 시험결과.끝까지);
  // 출력: set -e 스크립트가 끝까지 갔나: false
  console.log("찍힌 것:", JSON.stringify(시험결과.출력));
  // 출력: 찍힌 것: "1단계"
} else {
  console.log("bash 가 없어서 건너뜁니다");
}

// ★★ "2단계" 가 안 찍혔습니다. false 에서 멈춘 것입니다.
//   set -e 를 빼고 같은 걸 해 보면 "2단계" 까지 찍힙니다.
//   그 한 줄 차이가 반쯤 배포된 서버를 막습니다.

fs.rmSync(연습폴더, { recursive: true, force: true });


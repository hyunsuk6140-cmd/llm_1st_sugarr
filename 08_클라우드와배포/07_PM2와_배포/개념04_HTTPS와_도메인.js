function 남은날(발급일, 유효일수 = 90) {
  const 만료 = new Date(발급일);
  만료.setDate(만료.getDate() + 유효일수);
  return { 만료: 만료.toISOString().slice(0, 10), 갱신시작: new Date(만료.getTime() - 30 * 86400000).toISOString().slice(0, 10) };
}

const 계산 = 남은날("2026-08-18");
console.log("2026-08-18 에 받으면 만료:", 계산.만료);
// 출력: 2026-08-18 에 받으면 만료: 2026-11-16
console.log("certbot 이 갱신을 시도하기 시작하는 날쯤:", 계산.갱신시작);
// 출력: certbot 이 갱신을 시도하기 시작하는 날쯤: 2026-10-17


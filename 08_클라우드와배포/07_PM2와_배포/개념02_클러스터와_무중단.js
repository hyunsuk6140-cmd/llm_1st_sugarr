// ★★★ 네 개가 **같은 포트 3198** 을 씁니다.
//
//   보통은 "Address already in use" 가 나야 합니다. (06단원 개념02)
//   그런데 안 납니다. 왜일까요?
//
//   Node 의 cluster 는 이렇게 동작합니다.
//     · 부모(마스터) 프로세스가 포트를 엽니다
//     · 자식들에게 그 소켓을 넘겨줍니다
//     · 들어온 연결을 자식들에게 나눠 줍니다
//
//   그래서 자식들은 포트를 직접 열지 않습니다. 부모 것을 나눠 씁니다.
//
// ★ -i 옵션
//     -i 4        4개
//     -i max      코어 수만큼
//     -i 0        코어 수만큼 (max 와 같음)
//     -i -1       코어 수보다 하나 적게
//
//   ★★★ max 는 **코어 수**를 따릅니다. 같은 micro 라도 결과가 다릅니다.
//
//     t3.micro(코어 2개) 에서 max → 2개
//     t2.micro(코어 1개) 에서 max → 1개   ← 클러스터가 아니라 사실상 fork 입니다
//
//     그래서 이 자료는 max 대신 **-i 2** 로 개수를 직접 적습니다.
//     코어가 1개여도 프로세스 2개는 띄울 수 있습니다. 번갈아 나눠 씁니다.
//     무중단 배포(아래 4번) 에는 2개 이상이 꼭 필요합니다.
//
//     메모리가 1GB 인데 Node 하나가 50~100MB 를 씁니다.
//     너무 많이 띄우면 오히려 죽습니다. micro 에서는 2개면 충분합니다.


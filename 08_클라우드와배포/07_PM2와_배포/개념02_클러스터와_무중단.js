// (숫자는 컴퓨터마다 다르니 "있는지" 만 확인했습니다. 진짜 숫자는 os.cpus().length 입니다)
//
// ★★ EC2 의 micro 는 **종류에 따라 코어 수가 다릅니다.**
//
//     t2.micro   코어 1개 / 메모리 1GB
//     t3.micro   코어 2개 / 메모리 1GB
//
//   06단원에서 본 대로 어느 쪽이 프리티어인지는 **리전마다 다릅니다.**
//   그래서 이 단원도 타입 이름을 못 박지 않습니다. 서버에서 직접 세어 보세요.
//
//     nproc          ← 코어 수가 바로 나옵니다
//
//   ★ 코어가 1개여도 클러스터를 배우는 데는 문제가 없습니다.
//     -i max 대신 -i 2 로 개수를 직접 적으면 됩니다. (아래 2번)

// ★★ 그런데 코어를 다 쓰는 것보다 더 중요한 이유가 있습니다.
//
//   프로세스가 하나면, 그게 죽는 순간 **모든 요청이 끊깁니다.**
//   여러 개면 하나가 죽어도 나머지가 받습니다.
//
//   그리고 새 코드로 바꿀 때 하나씩 교체할 수 있습니다. (이게 무중단 배포입니다)


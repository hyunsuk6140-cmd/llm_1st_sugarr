//
//   코어가 4개인 컴퓨터에서 Node 를 하나만 띄우면 25% 만 쓰는 셈입니다.
//   나머지 3개는 놀고 있습니다.
//
// ★ 코어가 몇 개인지 봅시다.

console.log("이 컴퓨터에 CPU 코어가 있나:", os.cpus().length > 0);

  const 다른PID수 = new Set(받은PID).size;

  console.log("응답한 프로세스가 하나라도 있나:", 다른PID수 >= 1);
  // 출력: 응답한 프로세스가 하나라도 있나: true

  // ★★★ 여기서 OS 마다 결과가 다릅니다. 재 봤습니다.
  //
  //   리눅스   Node 가 라운드로빈으로 돌아가며 나눠 줍니다.
  //            12번 요청하면 4개 프로세스에 골고루 갑니다.
  //
  //   윈도우   OS 가 알아서 정합니다. 제 컴퓨터에서 재 보니

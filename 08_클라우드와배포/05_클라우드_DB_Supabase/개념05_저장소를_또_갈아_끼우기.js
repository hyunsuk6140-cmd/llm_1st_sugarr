function 세번비교() {
  const 비교 = [
    ["못 찾았을 때", "find → ?? null", ".get() ?? null", ".maybeSingle()"],
    ["만들고 받기", "목록 다시 읽기", "RETURNING", ".select().single()"],
    ["지웠는지", "길이 비교", "changes > 0", ".select() 뒤 length"],
    ["번호 매기기", "Math.max + 1", "AUTOINCREMENT", "identity (DB 가)"],
    ["동시 쓰기", "줄 세우기 필요", "한 문장이면 안전", "한 요청이면 안전"],
    ["트랜잭션", "없음", "BEGIN/COMMIT", "✗ rpc 로 DB 함수"],
    ["네트워크 실패", "없음", "없음", "★ 다뤄야 함 (status 0)"],
    ["권한", "없음", "없음", "★ RLS"],
  ];

  console.log("항목 | 파일(07단원) | SQLite(04단원) | Supabase(05단원)");
  // 출력: 항목 | 파일(07단원) | SQLite(04단원) | Supabase(05단원)
  for (const [항목, 파일, sqlite, supabase] of 비교) {
    console.log(`${항목} | ${파일} | ${sqlite} | ${supabase}`);
  }
  // 출력: 못 찾았을 때 | find → ?? null | .get() ?? null | .maybeSingle()
  // 출력: 만들고 받기 | 목록 다시 읽기 | RETURNING | .select().single()
  // 출력: 지웠는지 | 길이 비교 | changes > 0 | .select() 뒤 length
  // 출력: 번호 매기기 | Math.max + 1 | AUTOINCREMENT | identity (DB 가)
  // 출력: 동시 쓰기 | 줄 세우기 필요 | 한 문장이면 안전 | 한 요청이면 안전
  // 출력: 트랜잭션 | 없음 | BEGIN/COMMIT | ✗ rpc 로 DB 함수
  // 출력: 네트워크 실패 | 없음 | 없음 | ★ 다뤄야 함 (status 0)
  // 출력: 권한 | 없음 | 없음 | ★ RLS

  // ★★★ 오른쪽으로 갈수록 저장소가 아는 게 많아집니다.
  //   그래도 **밖에 내주는 약속은 세 번 다 같습니다.**
  //   그게 계층을 나눈 값어치입니다.

  마지막();
}


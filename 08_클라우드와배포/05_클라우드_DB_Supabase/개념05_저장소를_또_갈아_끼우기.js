async function 동작확인() {
  const { 클라이언트, 지금자료 } = 표있는클라이언트(처음자료, { 겹치면안되는칸: "name" });
  const 저장소 = 설비저장소.만들기(클라이언트);

  console.log("전부:", (await 저장소.전부()).map((설비) => 설비.name).join(", "));
  // 출력: 전부: 컨베이어 1호, 프레스 1호

  const 하나 = await 저장소.하나(1);
  console.log("하나(1):", 하나.name, "/", 하나.status);
  // 출력: 하나(1): 컨베이어 1호 / 가동

  const 없는것 = await 저장소.하나(9999);
  console.log("하나(9999):", 없는것, `(${typeof 없는것})`);
  // 출력: 하나(9999): null (object)

  // ★ null 입니다. undefined 가 아닙니다.
  //   서비스의 if (설비 === null) 이 그대로 걸립니다.

  const 만든것 = await 저장소.추가({ name: "용접로봇 1호", line: "C" });
  console.log("추가:", JSON.stringify(만든것));
  // 출력: 추가: {"id":3,"name":"용접로봇 1호","line":"C","status":"정지"}

  // ★ status 를 안 줬는데 '정지' 입니다. 저장소가 기본값을 넣었습니다.

  const 고친것 = await 저장소.수정(3, { status: "가동" });
  console.log("수정:", 고친것.status, "/ name 그대로:", 고친것.name);
  // 출력: 수정: 가동 / name 그대로: 용접로봇 1호

  console.log("수정(9999):", await 저장소.수정(9999, { status: "정지" }));
  // 출력: 수정(9999): null

  console.log("삭제(3):", await 저장소.삭제(3));
  // 출력: 삭제(3): true
  console.log("삭제(9999):", await 저장소.삭제(9999));
  // 출력: 삭제(9999): false

  console.log("남은:", 지금자료().length);
  // 출력: 남은: 2

  await 오류확인();
}


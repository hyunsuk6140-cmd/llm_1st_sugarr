const crypto = require("node:crypto");


// ============================================================
// 1. 그대로 저장하면 어떻게 되나
// ============================================================
//
// 제일 쉬운 방법부터 봅시다. 친 대로 저장하는 것입니다.

const 그대로저장한표 = [
  { 아이디: "kim", 비밀번호: "1234" },
  { 아이디: "lee", 비밀번호: "qwer1234" },
];

console.log("표에 든 것:", 그대로저장한표[0].비밀번호);
// 출력: 표에 든 것: 1234

// 로그인 검사도 쉽습니다. 그냥 같은지 보면 됩니다.

function 그대로검사(아이디, 친것) {
  const 사람 = 그대로저장한표.find((행) => 행.아이디 === 아이디);
  return Boolean(사람) && 사람.비밀번호 === 친것;
}

console.log("맞는 비밀번호:", 그대로검사("kim", "1234"));
// 출력: 맞는 비밀번호: true
console.log("틀린 비밀번호:", 그대로검사("kim", "9999"));
// 출력: 틀린 비밀번호: false

// 잘 돕니다. 그런데 이렇게 하면 안 됩니다.
//
// ★ 이유는 "해킹당하면" 이 아닙니다. 그건 두 번째 이유입니다.
//
//   첫 번째 이유: **당신이 볼 수 있습니다.**
//
//   DB 를 열면 남의 비밀번호가 그대로 보입니다.
//   당신도 보고, 같이 일하는 사람도 보고, 나중에 들어올 사람도 봅니다.
//   백업 파일에도 그대로 들어갑니다. 로그에 실수로 찍히면 거기에도 남습니다.
//
//   그리고 사람들은 비밀번호를 돌려 씁니다.
//   당신 사이트의 비밀번호가 그 사람의 은행 비밀번호일 수 있습니다.
//   당신은 남의 은행 비밀번호를 보관하고 싶지 않습니다.
//
// ★ 목표를 이렇게 바꿉니다.
//   "안전하게 보관한다" 가 아니라 **"아예 보관하지 않는다"** 입니다.
//   비밀번호를 모르면서도 맞는지 확인할 수 있어야 합니다.
//   그게 가능합니다. 지금부터 그걸 만듭니다.


// ============================================================
// 2. 해시 — 되돌릴 수 없는 계산
// ============================================================
//
// 해시는 어떤 글자를 정해진 길이의 값으로 바꾸는 계산입니다.
//
//   · 같은 것을 넣으면 언제나 같은 것이 나옵니다
//   · 조금만 달라도 결과가 완전히 달라집니다
//   · 나온 값에서 넣은 값을 되돌릴 수 없습니다   ← 이게 핵심입니다

function sha256(글자) {
  return crypto.createHash("sha256").update(글자).digest("hex");
}

console.log(sha256("1234"));
// 출력: 03ac674216f3e15c761ee1a5e255f067953623c8b388b4459e13f978d7c846f4
console.log(sha256("1235"));
// 출력: 310ced37200b1a0dae25edb263fe52c491f6e467268acab0ffec06666e2ed959

// 한 글자만 바꿨는데 완전히 다릅니다.
// 이걸 보고 "1234 였겠구나" 를 알아낼 방법은 없습니다.

// 그러면 비밀번호 대신 이 값을 저장하면 됩니다.
// 로그인할 때 친 것을 똑같이 해시해서, 저장된 값과 같은지 보면 됩니다.

console.log("친 것을 해시하면 같은가:", sha256("1234") === 그대로저장한표[0].비밀번호 ? "?" : "저장값을 해시로 바꿔야 합니다");
// 출력: 친 것을 해시하면 같은가: 저장값을 해시로 바꿔야 합니다


// ============================================================
// 3. 그런데 해시만으로는 부족합니다
// ============================================================
//
// 여기서 멈추면 안 됩니다. 두 가지가 남습니다.

// ── 3-1. 같은 비밀번호는 같은 해시가 됩니다 ──

const 해시만저장한표 = [
  { 아이디: "kim", 해시: sha256("1234") },
  { 아이디: "lee", 해시: sha256("1234") },
  { 아이디: "park", 해시: sha256("qwer1234") },
];

console.log("kim 과 lee 가 같은가:", 해시만저장한표[0].해시 === 해시만저장한표[1].해시);
// 출력: kim 과 lee 가 같은가: true

// ★ DB 를 본 사람이 비밀번호는 몰라도 **"이 둘은 같은 걸 쓴다"** 를 압니다.
//   한 명 것만 알아내면 나머지도 다 뚫립니다.

// ── 3-2. 미리 계산해 두면 됩니다 ──
//
// 되돌릴 수는 없지만, **넣어 보는 것** 은 막을 수 없습니다.
// 흔한 비밀번호를 전부 해시해서 표로 만들어 두면 그냥 찾아보면 됩니다.

const 미리계산표 = {};
for (const 흔한것 of ["1234", "0000", "password", "qwer1234", "admin"]) {
  미리계산표[sha256(흔한것)] = 흔한것;
}

console.log("표에서 찾아낸 kim 의 비밀번호:", 미리계산표[해시만저장한표[0].해시]);
// 출력: 표에서 찾아낸 kim 의 비밀번호: 1234

// ★ 다섯 개를 만드는 데 눈 깜짝할 새도 안 걸렸습니다.
//   실제로는 수십억 개짜리 표가 인터넷에 굴러다닙니다.
//   sha256 은 너무 빨라서, 그 표를 만드는 비용이 거의 0 입니다.
//
//   ★★ sha256 이 나쁜 게 아닙니다. **빠른 게 문제** 입니다.
//     파일이 안 바뀌었는지 확인할 때는 빠른 것이 장점입니다.
//     비밀번호에는 그 장점이 그대로 약점이 됩니다.


// ============================================================
// 4. 소금(salt) — 사람마다 다르게 만들기
// ============================================================
//
// 3-1 과 3-2 를 한 번에 푸는 방법이 있습니다.
// 사람마다 **아무 값이나 하나씩** 만들어서 비밀번호에 섞습니다.
// 그 값을 소금(salt) 이라고 부릅니다.

const kim소금 = "a1b2c3d4";
const lee소금 = "z9y8x7w6";

console.log("kim:", sha256(kim소금 + "1234"));
// 출력: kim: 5a88a6798156aa2fa43905f6075cb26466936509ebff14a8a4cdf886e31db160
console.log("lee:", sha256(lee소금 + "1234"));
// 출력: lee: 0bf8143e68f108fddae8a9bb558d632c83cc02279376f47202a90070bcfb2073

// 같은 `1234` 인데 결과가 다릅니다. 3-1 이 풀렸습니다.
// 그리고 미리 만든 표도 못 씁니다. 소금까지 합친 표를 사람마다 새로 만들어야 합니다.
//
// ★ 소금은 비밀이 아닙니다. DB 에 그대로 저장합니다.
//   숨기려고 쓰는 게 아니라 **겹치지 않게 하려고** 쓰는 것입니다.
//   비밀로 관리하려 들면 오히려 일이 복잡해집니다.
//
// ★ 소금은 사람마다 새로 만듭니다. 하나를 돌려 쓰면 3-1 이 그대로 돌아옵니다.


// ============================================================
// 5. 느린 해시 — scrypt
// ============================================================
//
// 소금을 넣어도 3-2 의 "넣어 보기" 자체는 남습니다.
// 한 사람을 노리고 그 사람의 소금으로 표를 새로 만들면 됩니다.
// sha256 은 빠르니까 그것도 금방입니다.
//
// 그래서 비밀번호에는 **일부러 느린** 계산을 씁니다.
// 한 번 하는 데 0.1초쯤 걸리게 만듭니다.
//
//   로그인하는 사람   0.1초 → 못 느낍니다
//   넣어 보는 쪽      1억 번 × 0.1초 = 317년
//
// 같은 계산인데 한쪽에만 손해입니다. 이게 느린 해시의 전부입니다.
//
// ★ Node 에 내장되어 있습니다. 설치할 게 없습니다.
//   `bcrypt`, `argon2` 같은 것도 많이 씁니다. 생각은 똑같습니다.
//   여기서는 내장된 scrypt 를 씁니다.

function 비밀번호섞기(비밀번호, 소금) {
  // 64는 만들어 낼 길이(바이트)입니다.
  return crypto.scryptSync(비밀번호, 소금, 64).toString("hex");
}

// ── 저장할 때 ──

function 만들기(비밀번호) {
  // 소금은 매번 새로, 아무렇게나 만듭니다.
  const 소금 = crypto.randomBytes(16).toString("hex");
  const 섞은것 = 비밀번호섞기(비밀번호, 소금);

  // ★ 소금과 결과를 한 칸에 같이 넣습니다.
  //   칸을 두 개 쓰면 한쪽만 옮기다 짝이 어긋납니다. 실제로 자주 나는 사고입니다.
  return `scrypt$${소금}$${섞은것}`;
}

const kim것 = 만들기("1234");

console.log("저장 모양:", kim것.slice(0, 7) + "...");
// 출력: 저장 모양: scrypt$...
console.log("칸 개수:", kim것.split("$").length);
// 출력: 칸 개수: 3
console.log("두 번 만들면 같은가:", 만들기("1234") === 만들기("1234"));
// 출력: 두 번 만들면 같은가: false

// ★ 같은 비밀번호인데 결과가 다릅니다. 소금이 매번 다르니까요.
//   그래서 **저장된 값끼리 비교하면 안 됩니다.** 아래처럼 풀어서 확인합니다.

// ── 확인할 때 ──

function 맞나(비밀번호, 저장된것) {
  const [방식, 소금, 섞은것] = 저장된것.split("$");

  if (방식 !== "scrypt") return false;

  const 다시섞은것 = 비밀번호섞기(비밀번호, 소금);

  // ★ === 로 비교하지 않습니다. 아래 6번에서 이유를 봅니다.
  return crypto.timingSafeEqual(Buffer.from(다시섞은것, "hex"), Buffer.from(섞은것, "hex"));
}

console.log("맞는 비밀번호:", 맞나("1234", kim것));
// 출력: 맞는 비밀번호: true
console.log("틀린 비밀번호:", 맞나("9999", kim것));
// 출력: 틀린 비밀번호: false

// ★ 저장된 것에서 `1234` 를 알아낼 방법은 없습니다.
//   그런데도 맞는지는 확인됩니다. 1번에서 세운 목표 그대로입니다.


// ============================================================
// 6. === 로 비교하면 안 되는 이유
// ============================================================
//
// `가 === 나` 는 다른 글자가 나오는 순간 멈춥니다. 그게 보통은 장점입니다.
// 그런데 비밀 값을 비교할 때는 **걸린 시간이 힌트가 됩니다.**
//
//   첫 글자부터 틀림   → 아주 빨리 false
//   앞 열 글자가 맞음  → 조금 늦게 false
//
// 이 차이를 재면서 한 글자씩 맞춰 나가면 결국 다 알아냅니다.
// 이런 걸 곁수로 새는 정보(side channel) 라고 부릅니다.
//
// `crypto.timingSafeEqual` 은 다르든 같든 **끝까지** 봅니다. 시간이 일정합니다.

const 값A = Buffer.from("aaaaaaaa");
const 값B = Buffer.from("aaaaaaab");

console.log("timingSafeEqual 결과:", crypto.timingSafeEqual(값A, 값B));
// 출력: timingSafeEqual 결과: false

// ★ 길이가 다르면 에러를 냅니다. 길이는 시간으로 못 숨기니까요.
try {
  crypto.timingSafeEqual(Buffer.from("짧다"), Buffer.from("좀 더 길다"));
} catch (에러) {
  console.log("길이가 다르면:", 에러.code);
  // 출력: 길이가 다르면: ERR_CRYPTO_TIMING_SAFE_EQUAL_LENGTH
}

// ★ 그래서 `맞나()` 에서 방식(scrypt) 을 먼저 확인했습니다.
//   저장 모양이 이상하면 길이부터 안 맞아서 에러가 납니다.


// ============================================================
// 7. 얼마나 느린지 재 봅니다
// ============================================================

function 재기(할일) {
  const 시작 = process.hrtime.bigint();
  할일();
  return Number(process.hrtime.bigint() - 시작) / 1e6;
}

const sha걸린시간 = 재기(() => sha256("1234"));
const scrypt걸린시간 = 재기(() => 비밀번호섞기("1234", "소금"));

console.log("sha256   :", sha걸린시간.toFixed(3), "ms");
// 출력?: sha256   : 0.030 ms
console.log("scrypt   :", scrypt걸린시간.toFixed(3), "ms");
// 출력?: scrypt   : 75.000 ms
console.log("scrypt 가 더 느린가:", scrypt걸린시간 > sha걸린시간);
// 출력: scrypt 가 더 느린가: true

// ★ 숫자는 컴퓨터마다 다릅니다. 몇백 배 차이가 나면 맞게 돌아가는 것입니다.
//
// ★ "느려서 서버가 못 버티면 어떡하나" 는 질문이 나옵니다.
//   로그인은 자주 일어나는 일이 아닙니다. 목록 조회는 초당 수천 번이지만
//   로그인은 사람이 하루에 한 번 합니다. 거기에 0.1초는 싼 값입니다.
//
//   ★★ 그래도 걱정되면 scryptSync 대신 crypto.scrypt (콜백판) 를 쓰세요.
//     Sync 는 그 0.1초 동안 서버 전체가 멈춥니다.
//     자료에서는 읽기 쉬우라고 Sync 를 썼습니다. 진짜 서버는 콜백판이 맞습니다.
//     (백엔드 03단원에서 본 "한 줄로 도는 Node" 이야기 그대로입니다)


// ============================================================
// 8. 정리
// ============================================================
//
//   그대로 저장   ✗  당신이 남의 비밀번호를 보게 됩니다
//   해시만        ✗  같은 비밀번호가 같은 값이 되고, 미리 만든 표에 뚫립니다
//   해시 + 소금   △  표는 막았지만 한 사람을 노리면 여전히 넣어 볼 수 있습니다
//   느린 해시     ○  넣어 보는 비용을 감당 못 하게 만듭니다
//
// 저장 모양은 이 한 줄입니다.
//
//   scrypt$소금$섞은것
//
// 다음 개념02 에서 이걸 진짜 표에 넣습니다.

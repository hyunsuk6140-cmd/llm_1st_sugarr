// ============================================================
// 개념 03 — 토큰을 직접 만들어 본다
// ============================================================
//
// 개념02 에서 "이 사람이 맞다" 까지 확인했습니다.
// 그런데 요청마다 비밀번호를 칠 수는 없습니다.
// 목록 한 번 볼 때마다 비밀번호를 보내면
//   · scrypt 를 요청마다 돌려야 하고 (0.1초씩)
//   · 비밀번호가 회선을 그만큼 자주 오갑니다
//
// 그래서 한 번 확인한 다음에는 **증표** 를 주고 그걸로 다닙니다.
// 백엔드 05단원의 `key-user-1` 이 그 자리였습니다. 이제 진짜를 만듭니다.
//
// 실행: node 개념03_토큰을_직접_만들어_본다.js
// ============================================================

const crypto = require("node:crypto");


// ============================================================
// 1. 두 가지 방법이 있습니다
// ============================================================
//
// ── 방법 A: 서버가 기억한다 (세션) ──
//
//   로그인하면 아무 글자나 만들어서 주고, 서버는 이렇게 적어 둡니다.
//     { "a8f3...": { 사용자id: 1 } }
//   요청이 오면 그 글자로 찾아봅니다.
//
//   장점  로그아웃이 확실합니다. 적어 둔 것을 지우면 끝입니다.
//   단점  서버가 기억해야 합니다. 07단원에서 PM2 로 프로세스를 여러 개 띄웠죠.
//         1번 프로세스가 적어 둔 것을 2번은 모릅니다. 로그인이 풀립니다.
//         그래서 Redis 같은 것을 따로 둡니다. 관리할 것이 하나 늘어납니다.
//
// ── 방법 B: 토큰 안에 적어서 준다 ──
//
//   "너는 1번 사용자다" 라고 **종이에 적어서** 줍니다.
//   서버는 아무것도 기억하지 않습니다. 받은 종이를 읽으면 됩니다.
//
//   장점  서버가 기억할 게 없습니다. 프로세스가 몇 개든 상관없습니다.
//   단점  준 종이를 되돌릴 수 없습니다. 만료될 때까지 유효합니다.
//         (개념05 에서 이 단점을 다룹니다)
//
// ★ 어느 쪽이 낫다가 아니라 **뭘 감당할지** 를 고르는 것입니다.
//   이 단원은 B 로 갑니다. 07단원에서 클러스터로 띄웠기 때문입니다.
//
// 그런데 B 에는 당장 문제가 하나 보입니다.
// 종이에 "나는 1번" 이라고 적어서 주면, 받은 사람이 "나는 2번" 으로 고쳐 오면 됩니다.
// 그래서 **고치면 티가 나게** 만들어야 합니다. 그게 서명입니다.


// ============================================================
// 2. 서명 — 고치면 티가 나게
// ============================================================
//
// 서버만 아는 비밀키로 내용을 계산해서 붙입니다.
// 내용을 고치면 계산 결과가 달라지므로 바로 걸립니다.
//
// 이걸 HMAC 이라고 합니다. 해시(개념01)에 비밀키를 같이 넣은 것입니다.

const 비밀키 = "이건-서버만-압니다";

function 서명하기(글자) {
  return crypto.createHmac("sha256", 비밀키).update(글자).digest("base64url");
}

console.log(서명하기("나는 1번 사용자다"));
// 출력: 6BICAmZaO4ZQpQkuvUtnXa-0ncalr2z1ns_h9X8giEk
console.log(서명하기("나는 2번 사용자다"));
// 출력: GZEsHKmjsByZfSPvdDLqQwr-UGLMWfYksnhaxOMIJVM

// 한 글자 바뀌었는데 결과가 완전히 다릅니다.
// 비밀키를 모르면 "나는 2번" 에 맞는 서명을 만들 수 없습니다.
//
// ★ 개념01 의 해시와 뭐가 다른가:
//   해시는 아무나 계산할 수 있습니다. HMAC 은 **비밀키가 있어야** 계산됩니다.
//   그래서 "서버가 만든 게 맞다" 를 증명할 수 있습니다.


// ============================================================
// 3. JWT — 이걸 세 칸으로 정리한 것
// ============================================================
//
// 방금 한 것에 이름을 붙인 것이 JWT(JSON Web Token) 입니다.
// 새로운 기술이 아니라 **모양을 정해 둔 약속** 입니다.
//
//   머리.몸.서명
//
//   머리   무슨 방식으로 서명했나
//   몸     하고 싶은 말 (누구인지, 언제까지인지)
//   서명   앞의 두 칸을 비밀키로 계산한 것
//
// 세 칸을 점으로 잇습니다. 각 칸은 base64url 로 적습니다.

function 담기(객체) {
  return Buffer.from(JSON.stringify(객체)).toString("base64url");
}

function 풀기(글자) {
  return JSON.parse(Buffer.from(글자, "base64url").toString());
}

// ★ base64url 은 base64 에서 `+ / =` 를 뺀 것입니다.
//   그 세 글자가 주소와 헤더에서 다른 뜻을 갖기 때문입니다.
//   Node 에 내장되어 있습니다. 따로 만들 것 없습니다.

const 머리 = { alg: "HS256", typ: "JWT" };
const 몸 = { sub: 1, 아이디: "kim", 역할: "user" };

const 앞부분 = `${담기(머리)}.${담기(몸)}`;
const 토큰 = `${앞부분}.${서명하기(앞부분)}`;

console.log(토큰);
// 출력: eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOjEsIuyVhOydtOuUlCI6ImtpbSIsIuyXre2VoCI6InVzZXIifQ._aBzj_3QkZ7hm5ECjNg5nXkz_8qAk57J8NpIMB-IoHM
console.log("칸 개수:", 토큰.split(".").length);
// 출력: 칸 개수: 3


// ============================================================
// 4. ★★ 토큰은 암호가 아닙니다 ★★
// ============================================================
//
// 여기가 이 단원에서 제일 자주 틀리는 곳입니다.
//
// base64url 은 암호가 아닙니다. **글자를 바꿔 적는 방법** 일 뿐입니다.
// 비밀키가 없어도 누구나 읽을 수 있습니다.

console.log(풀기(토큰.split(".")[1]));
// 출력: { sub: 1, '아이디': 'kim', '역할': 'user' }

// 비밀키를 하나도 안 쓰고 내용을 다 읽었습니다.
//
// ★ 서명이 막는 것은 **고치는 것** 이지 **읽는 것** 이 아닙니다.
//
//   토큰에 넣어도 되는 것    사용자 id, 아이디, 역할, 만료시각
//   절대 넣으면 안 되는 것   비밀번호, 주민번호, 카드번호, 전화번호,
//                            내부 주소, API 키
//
//   ★★ 브라우저 개발자도구에서 토큰을 복사해 <https://jwt.io> 에 붙여 보세요.
//     내용이 그대로 나옵니다. 남이 볼 수 있다는 뜻입니다.
//
// 그리고 이건 개인정보 문제이기도 합니다.
// AI자료 06단원에서 "개인정보는 넣지 않는다" 를 배웁니다. 같은 이야기입니다.


// ============================================================
// 5. 만료 — 언제까지 쓸 수 있나
// ============================================================
//
// 1번에서 본 B 의 단점입니다. 준 토큰은 되돌릴 수 없습니다.
// 그래서 **스스로 죽게** 만듭니다. 유효기간을 안에 적습니다.
//
//   iat  발급한 시각 (issued at)
//   exp  만료되는 시각 (expiration)
//
// ★ JWT 의 시각은 **초** 단위입니다. JavaScript 의 Date.now() 는 밀리초입니다.
//   1000 을 안 나누면 만료가 5만 년 뒤가 됩니다. 아주 자주 나는 실수입니다.

function 발급(내용, 지금, 살시간초) {
  const 몸 = {
    ...내용,
    iat: Math.floor(지금 / 1000),
    exp: Math.floor(지금 / 1000) + 살시간초,
  };
  const 앞 = `${담기(머리)}.${담기(몸)}`;
  return `${앞}.${서명하기(앞)}`;
}

// ★ `지금` 을 인자로 받는 이유
//   Date.now() 를 안에서 부르면 돌릴 때마다 결과가 달라집니다.
//   그러면 "만료되면 어떻게 되는지" 를 시험해 볼 수가 없습니다.
//   시각을 밖에서 넣으면 시험이 됩니다. 진짜 서버에서는 Date.now() 를 넣습니다.

const 열시 = new Date("2026-08-27T10:00:00Z").getTime();
const 짧은토큰 = 발급({ sub: 1, 아이디: "kim" }, 열시, 60 * 60);

console.log(풀기(짧은토큰.split(".")[1]));
// 출력: { sub: 1, '아이디': 'kim', iat: 1787824800, exp: 1787828400 }


// ============================================================
// 6. 확인하는 쪽 — 순서를 지켜야 합니다
// ============================================================

function 확인(토큰, 지금) {
  const 칸들 = 토큰.split(".");

  if (칸들.length !== 3) return { 된것: false, 이유: "토큰 모양이 아닙니다" };

  const [머리부분, 몸부분, 서명부분] = 칸들;

  // ── ① 서명부터 봅니다 ──
  //
  // ★ 순서를 바꾸면 안 됩니다.
  //   내용을 먼저 읽어서 쓰면, 위조된 토큰의 내용을 잠깐이라도 믿게 됩니다.
  //   "잠깐 믿었다가 나중에 버리면 되지" 가 안 됩니다.
  //   그 사이에 DB 를 한 번 뒤졌으면 이미 일어난 일입니다.
  const 제대로된서명 = 서명하기(`${머리부분}.${몸부분}`);

  if (서명부분.length !== 제대로된서명.length) {
    return { 된것: false, 이유: "서명이 맞지 않습니다" };
  }
  if (!crypto.timingSafeEqual(Buffer.from(서명부분), Buffer.from(제대로된서명))) {
    return { 된것: false, 이유: "서명이 맞지 않습니다" };
  }

  // ── ② 이제 내용을 읽습니다 ──
  const 머리읽은것 = 풀기(머리부분);
  const 몸읽은것 = 풀기(몸부분);

  // ── ③ 머리에 적힌 alg 를 믿지 않습니다 ──
  //
  // ★★ 유명한 사고가 여기서 났습니다.
  //   초기 JWT 라이브러리들이 머리의 `alg` 를 그대로 믿었습니다.
  //   그래서 `{"alg":"none"}` 으로 바꾸고 서명 칸을 비우면 통과했습니다.
  //   "서명 안 했다니까 확인 안 할게" 가 된 것입니다.
  //
  //   우리가 쓸 방식은 우리가 정합니다. 토큰이 정하는 게 아닙니다.
  if (머리읽은것.alg !== "HS256") return { 된것: false, 이유: "서명 방식이 다릅니다" };

  // ── ④ 만료 ──
  if (Math.floor(지금 / 1000) >= 몸읽은것.exp) return { 된것: false, 이유: "만료되었습니다" };

  return { 된것: true, 내용: 몸읽은것 };
}

console.log(확인(짧은토큰, 열시).내용.아이디);
// 출력: kim


// ============================================================
// 7. 고쳐 봅시다 — 진짜 걸리는지
// ============================================================
//
// 말로만 "걸립니다" 하면 안 믿깁니다. 직접 해 봅니다.

// ── 7-1. 역할을 admin 으로 고치기 ──

const [머리칸, 몸칸, 서명칸] = 짧은토큰.split(".");
const 고친몸 = 풀기(몸칸);
고친몸.역할 = "admin";

const 고친토큰 = `${머리칸}.${담기(고친몸)}.${서명칸}`;

console.log("고친 내용이 보이나:", 풀기(고친토큰.split(".")[1]).역할);
// 출력: 고친 내용이 보이나: admin
console.log("통과하나:", 확인(고친토큰, 열시).이유);
// 출력: 통과하나: 서명이 맞지 않습니다

// ★ 고치는 것 자체는 됩니다. 아무도 못 막습니다.
//   서버가 안 받아 줄 뿐입니다. 그거면 충분합니다.

// ── 7-2. 서명까지 새로 만들어 보기 ──

const 남의비밀키 = "찍어본-비밀키";
const 남의서명 = crypto.createHmac("sha256", 남의비밀키).update(`${머리칸}.${담기(고친몸)}`).digest("base64url");
const 통째로만든것 = `${머리칸}.${담기(고친몸)}.${남의서명}`;

console.log("비밀키를 찍어서 만든 것:", 확인(통째로만든것, 열시).이유);
// 출력: 비밀키를 찍어서 만든 것: 서명이 맞지 않습니다

// ★ 그래서 비밀키가 전부입니다.
//   비밀키가 새면 누구나 아무 토큰이나 만들 수 있습니다. 로그인이 통째로 뚫립니다.
//
//   · 코드에 적지 않습니다 (01단원)
//   · `.env` 는 git 에 올리지 않습니다 (01단원 개념02)
//   · 길고 아무 뜻 없는 값으로 만듭니다:  node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
//   · 새면 바꿉니다. 바꾸면 그때까지 준 토큰이 전부 무효가 됩니다.

// ── 7-3. alg 를 none 으로 바꾸기 ──

const none머리 = 담기({ alg: "none", typ: "JWT" });
const none토큰 = `${none머리}.${담기(고친몸)}.`;

console.log("alg none:", 확인(none토큰, 열시).이유);
// 출력: alg none: 서명이 맞지 않습니다

// ── 7-4. 만료된 토큰 ──

console.log("한 시간 뒤:", 확인(짧은토큰, 열시 + 60 * 60 * 1000).이유);
// 출력: 한 시간 뒤: 만료되었습니다
console.log("59분 뒤:", 확인(짧은토큰, 열시 + 59 * 60 * 1000).된것);
// 출력: 59분 뒤: true



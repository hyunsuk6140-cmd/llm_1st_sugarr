//
//   토큰은 서버가 서명해서 준 종이입니다
//   고치면 서명이 안 맞아서 걸립니다
//   ★ 읽는 것은 아무나 할 수 있습니다. 비밀은 넣지 않습니다
//   만료를 반드시 넣습니다. 되돌릴 수 없으니 스스로 죽게 합니다
//   서명 → 내용 순서로 봅니다. 방식(alg)은 서버가 정합니다
//   비밀키가 새면 전부 뚫립니다. .env 에 두고 git 에 안 올립니다
//
// 방금 만든 것을 `토큰.js` 에 정리해 뒀습니다.
// 개념04 에서 진짜 서버에 붙입니다.

// ============================================================
// 8. 정리
// ============================================================
//
//   UNIQUE 는 DB 에                코드로 확인하면 틈이 생깁니다
//   역할은 넘겨받지 않습니다        받은 객체를 통째로 넣지 않습니다
//   비밀번호에 위·아래 한도         짧으면 뚫리고, 길면 서버가 지칩니다
//   실패 메시지는 한 가지로         누가 가입했는지 새면 안 됩니다
//   없는 아이디도 시간을 씁니다     메시지를 맞춰도 시간이 다르면 소용없습니다

const { DatabaseSync } = require("node:sqlite");

const { 만들기, 맞나, 시간만쓰기 } = require("./비밀번호");

const db = new DatabaseSync(":memory:");


// ============================================================
// 1. 표 만들기
// ============================================================

db.exec(`
  CREATE TABLE 사용자 (
    id        INTEGER PRIMARY KEY,
    아이디    TEXT    NOT NULL UNIQUE,
    비밀번호  TEXT    NOT NULL,
    역할      TEXT    NOT NULL DEFAULT 'user',
    가입시각  TEXT    NOT NULL
  ) STRICT;
`);

// 칸을 하나씩 봅시다. 그냥 넣은 게 하나도 없습니다.
//
//   아이디 UNIQUE
//     같은 아이디로 두 명이 가입하면 로그인할 때 누가 누군지 모릅니다.
//     ★ 코드로 "이미 있나 찾아보고 없으면 넣기" 를 하면 안 됩니다.
//       찾는 순간과 넣는 순간 사이에 다른 요청이 끼어들 수 있습니다.
//       (02단원 개념05 의 동시성 이야기입니다)
//       DB 에 UNIQUE 를 걸어 두면 그 틈이 없습니다.
//
//   비밀번호 TEXT
//     여기 들어가는 것은 `scrypt$...` 입니다. 비밀번호 자체가 아닙니다.
//     ★ 칸 이름을 `비밀번호` 라고 지은 게 좀 위험합니다.
//       실무에서는 `password_hash` 처럼 **해시라는 게 이름에 드러나게** 짓습니다.
//       그래야 "여기 평문 넣으면 되겠네" 하는 사람이 안 생깁니다.
//       자료에서는 읽기 쉬우라고 한글로 뒀습니다.
//
//   역할 DEFAULT 'user'
//     가입할 때 역할을 넘겨받으면 안 됩니다. 5번에서 다시 봅니다.
//
//   STRICT
//     03단원에서 쓴 그대로입니다. 칸 종류를 안 지키면 에러를 냅니다.


// ============================================================
// 2. 회원가입
// ============================================================

const 넣기문장 = db.prepare(`
  INSERT INTO 사용자 (아이디, 비밀번호, 가입시각)
  VALUES (?, ?, ?)
`);

function 가입(아이디, 비밀번호) {
  // ★ 넣기 전에 검사합니다. 순서가 중요합니다.
  const 문제 = 검사(아이디, 비밀번호);
  if (문제) return { 된것: false, 이유: 문제 };

  try {
    const 결과 = 넣기문장.run(아이디, 만들기(비밀번호), "2026-08-27T09:00:00Z");
    return { 된것: true, id: Number(결과.lastInsertRowid) };
  } catch (에러) {
    // ★ UNIQUE 를 어기면 여기로 옵니다. 에러 종류를 보고 갈라야 합니다.
    //   전부 "가입 실패" 로 뭉뚱그리면 진짜 고장을 놓칩니다.
    if (String(에러.message).includes("UNIQUE")) {
      return { 된것: false, 이유: "이미 있는 아이디입니다" };
    }
    throw 에러;
  }
}

function 검사(아이디, 비밀번호) {
  if (typeof 아이디 !== "string" || typeof 비밀번호 !== "string") {
    return "아이디와 비밀번호가 필요합니다";
  }
  if (!/^[a-z0-9_]{3,20}$/.test(아이디)) {
    return "아이디는 영소문자·숫자·밑줄 3~20자입니다";
  }
  if (비밀번호.length < 8) {
    return "비밀번호는 8자 이상이어야 합니다";
  }
  // ★ 위쪽 한도도 둡니다. 이유는 4번에 있습니다.
  if (비밀번호.length > 200) {
    return "비밀번호가 너무 깁니다";
  }
  return null;
}


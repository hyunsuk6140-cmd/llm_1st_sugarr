const 틀림 = db.prepare("UPDATE 사용자 SET 틀린횟수 = 틀린횟수 + 1 WHERE id = ?");
const 잠금 = db.prepare("UPDATE 사용자 SET 잠긴시각 = ? WHERE id = ?");
const 풀기 = db.prepare("UPDATE 사용자 SET 틀린횟수 = 0, 잠긴시각 = NULL WHERE id = ?");

const 한도 = 5;

function 로그인_세면서(아이디, 비밀번호, 지금) {
  const 사람 = 찾기문장.get(아이디);

  if (!사람) {
    시간만쓰기(비밀번호);
    return "아이디 또는 비밀번호가 올바르지 않습니다";
  }

  if (사람.잠긴시각 && 지금 < 잠깐뒤(사람.잠긴시각)) {
    // ★ 잠겼다는 것도 알려 주면 "이 아이디는 있다" 가 새어 나갑니다.
    //   그래도 잠금은 알려 주는 쪽이 낫습니다. 주인이 이유를 알아야 하니까요.
    //   ★★ 어디까지 알려 줄지는 **정하기 나름** 입니다. 정답이 하나가 아닙니다.
    //     다만 "아무 생각 없이 다 알려 준" 상태는 아니어야 합니다.
    return "잠시 뒤에 다시 시도해 주세요";
  }

  if (!맞나(비밀번호, 사람.비밀번호)) {
    틀림.run(사람.id);
    const 센것 = 찾기문장.get(아이디).틀린횟수;
    if (센것 >= 한도) 잠금.run(지금, 사람.id);
    return "아이디 또는 비밀번호가 올바르지 않습니다";
  }

  풀기.run(사람.id);
  return "로그인 성공";
}

// 15분 뒤를 계산합니다.
function 잠깐뒤(시각) {
  return new Date(new Date(시각).getTime() + 15 * 60 * 1000).toISOString();
}


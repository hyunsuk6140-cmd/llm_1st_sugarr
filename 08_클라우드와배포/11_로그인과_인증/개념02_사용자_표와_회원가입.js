//   회원 목록이 새면 그 자체로 문제입니다.
//   그리고 아이디를 확보한 다음, 흔한 비밀번호를 그 아이디들에만 넣어 보면 됩니다.

// ○ 같은 말로 대답합니다
function 로그인(아이디, 비밀번호) {
  const 사람 = 찾기문장.get(아이디);

  if (!사람) {
    // ★ 그냥 돌려보내면 안 됩니다. **시간** 이 다르기 때문입니다.
    //   아이디가 있으면 scrypt 를 하느라 0.1초, 없으면 즉시 돌아옵니다.
    //   그 차이만 재도 아이디가 있는지 알 수 있습니다.
    //   그래서 없을 때도 계산을 한 번 합니다. 개념01 의 6번과 같은 이야기입니다.
    시간만쓰기(비밀번호);
    return { 된것: false, 이유: "아이디 또는 비밀번호가 올바르지 않습니다" };
  }

  if (!맞나(비밀번호, 사람.비밀번호)) {
    return { 된것: false, 이유: "아이디 또는 비밀번호가 올바르지 않습니다" };
  }

  return { 된것: true, 사람: { id: 사람.id, 아이디: 사람.아이디, 역할: 사람.역할 } };
}


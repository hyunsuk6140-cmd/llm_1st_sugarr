// _검증도구/출력검증.js — `// 출력:` 주석과 진짜 실행 결과를 대조한다
// ------------------------------------------------------------
// 사용:
//   node _검증도구/출력검증.js 01_Node_시작하기
//   node _검증도구/출력검증.js                  ← 모든 단원
//
// 하는 일:
//   폴더의 .js 파일을 하나씩 node 로 실행하고,
//   찍힌 줄과 파일에 적힌 `// 출력:` 주석을 순서대로 비교한다.
//   하나라도 다르면 알려 준다.
//
// 왜 필요한가:
//   자료에 적힌 출력이 실제와 다르면, 학생이 자기가 틀린 줄 알고 헤맨다.
//   사람 눈으로는 절대 못 잡는다. 기계로 훑어야 한다.
// ============================================================

const fs = require("fs");
const path = require("path");
const cp = require("child_process");

const 자료뿌리 = path.join(__dirname, "..");


// ── 선언 문법 ──
//
//   console.log(1 + 2);
//   // 출력: 3
//
//   · `// 출력:` 은 반드시 '다음 줄에 단독으로' 씁니다.
//     코드와 같은 줄에 붙이면 수집이 안 됩니다. (경고를 냅니다)
//   · 앞에 공백이 있어도 됩니다. (catch 블록 안 등)
//   · 정답 블록 안의 `//    // 출력:` 은 // 로 시작하므로 자동으로 제외됩니다.
//   · 여러 줄이 나오면 `// 출력:` 도 그 줄 수만큼 씁니다.
//
//   측정값처럼 컴퓨터마다 달라지는 줄은 `// 출력?:` 으로 씁니다.
//
//   console.log("걸린 시간:", 재기().ms, "ms");
//   // 출력?: 걸린 시간: 1810 ms      ← 값은 안 보고, 줄이 있는지만 봅니다
//
//   왜 필요한가: 색인 효과나 속도 비교는 실제로 재야 의미가 있는데,
//   그 숫자는 컴퓨터마다 다릅니다. 그렇다고 출력을 지우면 학생이 자기 값을
//   확인할 수 없습니다. 값은 안 보고 줄 수만 맞춥니다.
//   판정이 필요한 것은 `색인후 < 색인없이` 처럼 참거짓으로 따로 찍으세요.

const 출력선언 = /^\s*\/\/ 출력(\?)?:\s?(.*)$/;

// ★ 건너뛴 파일을 기록합니다. 조용히 건너뛰면 "검사했다" 고 착각하게 됩니다.
const 건너뛴것 = [];


// ★ 주석과 글자 안의 내용을 걷어 낸 '진짜 코드' 만 남깁니다.
//
//   자료에는 설명하려고 코드를 글자로 적어 두는 곳이 많습니다.
//     "후 · 서버.js": "app.listen(설정.포트)"
//     // app.listen(PORT, ...) 처럼 씁니다
//
//   이걸 그대로 보면 "이 파일은 서버구나" 하고 잘못 판단합니다.
//   실제로 그 오탐이 났고, 도구를 고쳤습니다.
function 코드만남기기(소스) {
  return (
    소스
      // 여러 줄 주석
      .replace(/\/\*[\s\S]*?\*\//g, " ")
      // 한 줄 주석
      .replace(/(^|[^:])\/\/.*$/gm, "$1")
      // 글자 (따옴표 세 종류)
      .replace(/"(?:[^"\\]|\\.)*"/g, '""')
      .replace(/'(?:[^'\\]|\\.)*'/g, "''")
      .replace(/`(?:[^`\\]|\\.)*`/g, "``")
  );
}


function 파일검사(전체경로, 보일이름) {
  const 소스 = fs.readFileSync(전체경로, "utf8");

  // 서버 파일은 끝나지 않으므로 건너뜁니다. 서버검증.js 가 따로 봅니다.
  //
  // ★ 예외: 서버를 띄웠다가 **스스로 닫는** 파일이 있습니다.
  //   (프록시가 무엇을 바꾸는지 재 보는 파일 같은 것)
  //   그런 파일은 맨 위에 이렇게 적어 두면 여기서 검사합니다.
  //
  //     // 이파일은끝납니다
  //
  //   실제로 그 오탐이 났습니다. .listen 이 있다고 전부 서버는 아닙니다.
  const 끝난다고선언 = /^\s*\/\/ 이파일은끝납니다\s*$/m.test(소스);

  if (!끝난다고선언 && /\.listen\s*\(/.test(코드만남기기(소스))) {
    건너뛴것.push({ 이름: 보일이름, 이유: "서버 파일(.listen)" });
    return null;
  }

  const 기대 = [];
  const 스타일경고 = [];


  소스.split(/\r?\n/).forEach((줄, 자리) => {
    const 맞음 = 줄.match(출력선언);

    if (맞음) {
      기대.push({ 값: 맞음[2], 아무거나: 맞음[1] === "?" });
      return;
    }

    if (/\/\/ 출력\??:/.test(줄) && !줄.trimStart().startsWith("//")) {
      스타일경고.push(`  ${자리 + 1}행: 코드와 같은 줄에 // 출력: 이 붙어 있음 → ${줄.trim()}`);
    }
  });

  if (스타일경고.length) {
    console.log(`\n[스타일] ${보일이름} — // 출력: 은 반드시 다음 줄에 단독으로 쓸 것`);
    스타일경고.forEach((줄) => console.log(줄));
  }

  let 찍힌것;

  try {
    // ★ process.execPath — 이 도구를 돌린 것과 **같은 node** 로 실행합니다.
    //   "node" 라고만 쓰면 PATH 의 다른 버전이 잡힙니다.
    //   node:sqlite 처럼 버전에 따라 동작이 달라지는 것을 쓰면 결과가 어긋납니다.
    찍힌것 = cp.execSync(`"${process.execPath}" "${전체경로}"`, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      // ★ PM2 를 실제로 띄우는 파일은 30초를 넘깁니다. 넉넉히 잡습니다.
      //   그래도 안 끝나면 무한 반복에 빠진 것이니 알려 줘야 합니다.
      timeout: 180000,
    });
  } catch (에러) {
    console.log(`\n[실행실패] ${보일이름}`);
    console.log((에러.stderr || 에러.message).split(/\r?\n/).slice(0, 6).join("\n"));
    return { 실패: 1 };
  }

  const 실제 = 찍힌것.split(/\r?\n/);
  while (실제.length && 실제[실제.length - 1] === "") 실제.pop();

  const 문제 = [];

  if (기대.length !== 실제.length) {
    문제.push(`개수 불일치: 주석 ${기대.length}개 / 실제 ${실제.length}줄`);
  }

  for (let i = 0; i < Math.max(기대.length, 실제.length); i++) {
    const 이번 = 기대[i];

    // `// 출력?:` 은 줄이 있는지만 봅니다. 값은 컴퓨터마다 다릅니다.
    if (이번 && 이번.아무거나) {
      if (실제[i] === undefined) {
        문제.push(`  ${i + 1}번째  주석[${이번.값}] 자리에 찍힌 줄이 없음`);
      }
      continue;
    }

    const 기대값 = 이번 ? 이번.값 : undefined;

    if (기대값 !== 실제[i]) {
      문제.push(`  ${i + 1}번째  주석[${기대값}]  실제[${실제[i]}]`);
    }
  }

  if (문제.length) {
    console.log(`\n[불일치] ${보일이름}`);
    문제.slice(0, 15).forEach((줄) => console.log(줄));
    if (문제.length > 15) console.log(`  ...외 ${문제.length - 15}건`);
    return { 실패: 1 };
  }

  console.log(`[OK] ${보일이름}  (${기대.length}줄 일치)`);
  return { 실패: 0 };
}


function 폴더검사(폴더) {
  if (!fs.existsSync(폴더)) {
    console.log(`[없는 폴더] ${폴더}`);
    return { 파일수: 0, 실패: 1 };
  }

  let 파일수 = 0;
  let 실패 = 0;

  for (const 이름 of fs.readdirSync(폴더).filter((f) => f.endsWith(".js")).sort()) {
    const 결과 = 파일검사(path.join(폴더, 이름), 이름);

    if (결과) {
      파일수 += 1;
      실패 += 결과.실패;
    }
  }

  if (건너뛴것.length > 0) {
    console.log(`\n[건너뜀] ${건너뛴것.length}개 — 이 파일들은 출력 대조를 하지 않았습니다`);
    for (const { 이름, 이유 } of 건너뛴것) console.log(`  · ${이름}  (${이유})`);
    건너뛴것.length = 0;
  }

  console.log(`\n===== ${path.basename(폴더)} : 파일 ${파일수}개 중 ${실패}개 불일치 =====`);
  return { 파일수, 실패 };
}


// ── 단원 폴더 찾기 ──
// 01_ 처럼 숫자로 시작하는 폴더만 단원으로 봅니다.
function 단원목록() {
  return fs
    .readdirSync(자료뿌리, { withFileTypes: true })
    .filter((항목) => 항목.isDirectory() && /^\d\d_/.test(항목.name))
    .map((항목) => 항목.name)
    .sort();
}


const 넘어온것 = process.argv.slice(2);
const 대상들 = 넘어온것.length > 0 ? 넘어온것 : 단원목록();

let 전체파일 = 0;
let 전체실패 = 0;

for (const 대상 of 대상들) {
  const 폴더 = path.isAbsolute(대상) ? 대상 : path.join(자료뿌리, 대상);
  const 결과 = 폴더검사(폴더);

  전체파일 += 결과.파일수;
  전체실패 += 결과.실패;
}

if (대상들.length > 1) {
  console.log(`\n########## 전체: 파일 ${전체파일}개 / 불일치 ${전체실패}개 ##########`);
}

// 실패가 있으면 0이 아닌 값으로 끝냅니다. 스크립트에서 확인할 수 있습니다.
process.exit(전체실패 > 0 ? 1 : 0);
